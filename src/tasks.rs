pub(crate) fn read_task_bundle(source: &Path) -> Result<TaskBundle, ZdevError> {
    let bytes = if source == Path::new("-") {
        let mut bytes = Vec::new();
        io::stdin()
            .read_to_end(&mut bytes)
            .map_err(|error| ZdevError::io("Cannot read task bundle from standard input", error))?;
        bytes
    } else {
        fs::read(source)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", source.display()), error))?
    };
    serde_json::from_slice(&bytes)
        .map_err(|error| ZdevError::new(format!("Invalid task bundle: {error}")))
}

fn validate_task_bundle(root: &Path, bundle: &TaskBundle, area: &str) -> Result<(), ZdevError> {
    if bundle.schema_version != SCHEMA_VERSION || bundle.area != area {
        return Err(ZdevError::new(
            "Task bundle does not match the selected area",
        ));
    }
    if bundle.tasks.is_empty() {
        return Err(ZdevError::new("Task bundle contains no tasks"));
    }
    let slices = slice_briefs(root, area)?;
    let research = load_area(root, area)?.0.research;
    let existing = if bundle.tasks.iter().any(|task| {
        task.hypothesis.is_some() || !task.requires_code.is_empty() || !task.blocked_by.is_empty()
    }) && root.join(".zdev").join(area).join("tasks").is_dir()
    {
        load_tasks(root, area)?
    } else {
        Vec::new()
    };
    let context_ids = existing
        .iter()
        .map(|task| task.header.id.as_str())
        .chain(bundle.tasks.iter().map(|task| task.key.as_str()))
        .collect::<BTreeSet<_>>();
    let slice_keys = slices
        .iter()
        .map(|slice| slice.key.as_str())
        .collect::<BTreeSet<_>>();
    let mut seen_keys = BTreeSet::new();
    for task in &bundle.tasks {
        require_retained_code(root, &task.requires_code, &existing)?;
        for blocker in &task.blocked_by {
            let is_known = context_ids.contains(blocker.as_str())
                || task_exists_in_other_area(root, area, blocker)?;
            if !is_known {
                return Err(unknown_blocker_error(root, area, &task.key, blocker));
            }
        }
        if let Some(hypothesis) = &task.hypothesis {
            if research.is_none() {
                return Err(ZdevError::new(
                    "Hypothesis tasks require research settings on their area",
                ));
            }
            hypothesis.validate()?;
            for context in &hypothesis.context_tasks {
                if context == &task.key || !context_ids.contains(context.as_str()) {
                    return Err(ZdevError::new(format!(
                        "Hypothesis {} has unknown or self context task {context}",
                        task.key
                    )));
                }
            }
        }
        validate_segment(&task.key, "Task key")?;
        validate_nonempty_line(&task.title, "Task title")?;
        validate_nonempty_line(&task.outcome, "Task outcome")?;
        if let Some(slice) = &task.slice {
            validate_segment(slice, "Slice key")?;
            if !slice_keys.contains(slice.as_str()) {
                return Err(ZdevError::new(format!(
                    "Task {} references unknown slice {slice}",
                    task.key
                )));
            }
        }
        if task
            .context
            .as_deref()
            .is_some_and(|context| context.trim().is_empty())
        {
            return Err(ZdevError::new(format!(
                "Task {} has empty context",
                task.key
            )));
        }
        if task.done_when.is_empty() {
            return Err(ZdevError::new(format!(
                "Task {} has no done conditions",
                task.key
            )));
        }
        if !seen_keys.insert(task.key.as_str()) {
            return Err(ZdevError::new(format!("Duplicate task key: {}", task.key)));
        }
    }
    Ok(())
}

fn task_bundle_approval_id(bundle: &TaskBundle) -> Result<String, ZdevError> {
    let canonical = serde_json::to_vec(bundle)
        .map_err(|error| ZdevError::new(format!("Cannot fingerprint task bundle: {error}")))?;
    let hash = canonical.iter().fold(0xcbf29ce484222325_u64, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
    });
    Ok(format!("T{hash:016x}"))
}

fn task_review_id(fingerprint: &str) -> String {
    format!("R{}", fingerprint.strip_prefix('T').unwrap_or(fingerprint))
}

fn task_review_store(root: &Path, area: &str) -> Result<PathBuf, ZdevError> {
    let name = format!("zdev/reviews/{area}");
    let path = PathBuf::from(git_output(root, &["rev-parse", "--git-path", &name])?);
    Ok(if path.is_absolute() {
        path
    } else {
        root.join(path)
    })
}

fn task_review_path_value(root: &Path, path: &Path) -> String {
    relative(root, path)
}

fn valid_task_review_id(value: &str) -> bool {
    value.len() == 17
        && value.starts_with('R')
        && value[1..]
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn approval_value(value: Option<&str>) -> &str {
    value.filter(|value| !value.is_empty()).unwrap_or("None")
}

fn approval_list(values: &[String]) -> String {
    if values.is_empty() {
        "None".to_owned()
    } else {
        values
            .iter()
            .enumerate()
            .map(|(index, value)| format!("{}. {value}", index + 1))
            .collect::<Vec<_>>()
            .join("\n")
    }
}

fn longest_backtick_run(value: &str) -> usize {
    value
        .split(|character| character != '`')
        .map(str::len)
        .max()
        .unwrap_or(0)
}

fn render_task_bundle_approval_with_selection_fields(
    bundle: &TaskBundle,
    include_selection_fields: bool,
) -> String {
    let mut document = format!(
        "# Task Bundle\n\n## Area\n{}\n\n## Schema version\n{}",
        bundle.area, bundle.schema_version
    );
    for (index, task) in bundle.tasks.iter().enumerate() {
        document.push_str(&format!(
            "\n\n## Task {}\n\n### Key\n{}\n\n### Title\n{}",
            index + 1,
            task.key,
            task.title,
        ));
        if let Some(complexity) = task.complexity {
            document.push_str(&format!("\n\n### Complexity\n{}", complexity.as_str()));
        }
        if let Some(hypothesis) = &task.hypothesis {
            document.push_str(&format!(
                "\n\n### Hypothesis\n{}\n\n### Context tasks (not dependencies)\n{}",
                hypothesis.mechanism,
                approval_list(&hypothesis.context_tasks)
            ));
        }
        if include_selection_fields {
            document.push_str(&format!(
                "\n\n### AFK\n{}\n\n### Priority\n{}",
                task.afk,
                task.priority.unwrap_or(TaskPriority::Normal).as_str(),
            ));
        }
        document.push_str(&format!(
            "\n\n### Slice\n{}\n\n### Outcome\n{}\n\n### Context\n{}\n\n### Boundaries\n{}\n\n### Blocked by\n{}\n\n### Done when / proof\n{}\n\n### Validation / Testing\n{}",
            approval_value(task.slice.as_deref()),
            task.outcome,
            approval_value(task.context.as_deref()),
            approval_list(&task.boundaries),
            approval_list(&task.blocked_by),
            approval_list(&task.done_when),
            approval_list(&task.validation),
        ));
        if !task.requires_code.is_empty() {
            document.push_str(&format!(
                "\n\n### Requires retained code\n{}",
                approval_list(&task.requires_code)
            ));
        }
    }
    let fence = "`".repeat(longest_backtick_run(&document).saturating_add(1).max(3));
    format!("{fence}markdown\n{document}\n{fence}")
}

fn render_task_bundle_approval(bundle: &TaskBundle) -> String {
    render_task_bundle_approval_with_selection_fields(bundle, true)
}

fn legacy_task_bundle_approval(bundle: &TaskBundle) -> Option<String> {
    bundle
        .tasks
        .iter()
        .all(|task| !task.afk && task.priority.is_none())
        .then(|| render_task_bundle_approval_with_selection_fields(bundle, false))
}

pub(super) fn review(root: &Path, area: &str, source: &Path) -> Result<CommandOutput, ZdevError> {
    load_area(root, area)?;
    let bundle = read_task_bundle(source)?;
    validate_task_bundle(root, &bundle, area)?;
    let fingerprint = task_bundle_approval_id(&bundle)?;
    let review = task_review_id(&fingerprint);
    let markdown = render_task_bundle_approval(&bundle);
    let metadata = TaskReviewMetadata {
        schema_version: SCHEMA_VERSION,
        area: area.to_owned(),
        review: review.clone(),
        fingerprint,
    };
    let mut bundle_bytes = serde_json::to_vec(&bundle)
        .map_err(|error| ZdevError::new(format!("Cannot serialize task bundle: {error}")))?;
    bundle_bytes.push(b'\n');
    let mut metadata_bytes = serde_json::to_vec_pretty(&metadata)
        .map_err(|error| ZdevError::new(format!("Cannot serialize task review: {error}")))?;
    metadata_bytes.push(b'\n');
    let _lock = ZdevStateLock::acquire(root)?;
    load_area(root, area)?;
    validate_task_bundle(root, &bundle, area)?;
    let store = task_review_store(root, area)?;
    let directory = store.join(&review);
    fs::create_dir_all(&directory).map_err(|error| {
        ZdevError::io(
            format!(
                "Cannot create task review directory {}",
                directory.display()
            ),
            error,
        )
    })?;
    let bundle_path = directory.join("bundle.json");
    let metadata_path = directory.join("metadata.json");
    let markdown_path = directory.join("review.md");
    write_atomic(&bundle_path, &bundle_bytes)?;
    write_atomic(&metadata_path, &metadata_bytes)?;
    write_atomic(&markdown_path, markdown.as_bytes())?;
    write_atomic(&store.join("current"), format!("{review}\n").as_bytes())?;
    if let Ok(entries) = fs::read_dir(&store) {
        for entry in entries.flatten() {
            if entry.file_name() != OsStr::new(&review)
                && entry.file_type().is_ok_and(|kind| kind.is_dir())
            {
                let _ = fs::remove_dir_all(entry.path());
            }
        }
    }
    Ok(CommandOutput::new(
        markdown,
        json!({
            "schema_version": SCHEMA_VERSION,
            "status": "reviewed",
            "area": area,
            "review": review,
            "path": task_review_path_value(root, &markdown_path),
        }),
    ))
}

fn read_regular_file(path: &Path, area: &str) -> Result<Vec<u8>, ZdevError> {
    let metadata = fs::symlink_metadata(path).map_err(|error| {
        ZdevError::io(
            format!(
                "Cannot inspect stored task review for area {area} at {}",
                path.display()
            ),
            error,
        )
    })?;
    if !metadata.file_type().is_file() {
        return Err(ZdevError::new(format!(
            "Stored task review path {} is not a regular file",
            path.display()
        )));
    }
    fs::read(path).map_err(|error| {
        ZdevError::io(
            format!(
                "Cannot read stored task review for area {area} at {}",
                path.display()
            ),
            error,
        )
    })
}

fn read_task_review(
    root: &Path,
    area: &str,
    expected_review: Option<&str>,
) -> Result<TaskReview, ZdevError> {
    let store = task_review_store(root, area)?;
    let current_path = store.join("current");
    let current_metadata = fs::symlink_metadata(&current_path).map_err(|error| {
        if error.kind() == io::ErrorKind::NotFound {
            ZdevError::new(format!(
                "No stored task review exists for area {area}; run `zdev tasks review {area} --from <PATH_OR_DASH>`"
            ))
        } else {
            ZdevError::io(
                format!("Cannot inspect task review pointer {}", current_path.display()),
                error,
            )
        }
    })?;
    if !current_metadata.file_type().is_file() {
        return Err(ZdevError::new(format!(
            "Stored task review pointer for area {area} is corrupt; run `zdev tasks review {area} --from <PATH_OR_DASH>` again"
        )));
    }
    let current_bytes = fs::read(&current_path).map_err(|error| {
        ZdevError::io(
            format!("Cannot read task review pointer {}", current_path.display()),
            error,
        )
    })?;
    let current = std::str::from_utf8(&current_bytes)
        .ok()
        .and_then(|value| value.strip_suffix('\n'));
    let Some(current) = current.filter(|value| valid_task_review_id(value)) else {
        return Err(ZdevError::new(format!(
            "Stored task review pointer for area {area} is corrupt; run `zdev tasks review {area} --from <PATH_OR_DASH>` again"
        )));
    };
    if let Some(expected) = expected_review
        && expected != current
    {
        return Err(ZdevError::new(format!(
            "Task review {expected} was replaced by {current}; show and approve the current review before importing"
        )));
    }
    let directory = store.join(current);
    let metadata_path = directory.join("metadata.json");
    let bundle_path = directory.join("bundle.json");
    let markdown_path = directory.join("review.md");
    let metadata_bytes = read_regular_file(&metadata_path, area)?;
    let metadata: TaskReviewMetadata = serde_json::from_slice(&metadata_bytes).map_err(|error| {
        ZdevError::new(format!(
            "Stored task review for area {area} is corrupt: {error}. Run `zdev tasks review {area} --from <PATH_OR_DASH>` again"
        ))
    })?;
    if metadata.schema_version != SCHEMA_VERSION
        || metadata.area != area
        || metadata.review != current
    {
        return Err(ZdevError::new(format!(
            "Stored task review does not match selected area {area}; run `zdev tasks review {area} --from <PATH_OR_DASH>` again"
        )));
    }
    let bundle_bytes = read_regular_file(&bundle_path, area)?;
    let bundle: TaskBundle = serde_json::from_slice(&bundle_bytes).map_err(|error| {
        ZdevError::new(format!(
            "Stored task bundle for area {area} is corrupt: {error}. Run `zdev tasks review {area} --from <PATH_OR_DASH>` again"
        ))
    })?;
    validate_task_bundle(root, &bundle, area).map_err(|error| {
        ZdevError::new(format!(
            "Stored task review for area {area} is no longer valid: {error}"
        ))
    })?;
    let markdown_bytes = read_regular_file(&markdown_path, area)?;
    let markdown = String::from_utf8(markdown_bytes).map_err(|_| {
        ZdevError::new(format!(
            "Stored task review Markdown for area {area} is not valid UTF-8"
        ))
    })?;
    let fingerprint = task_bundle_approval_id(&bundle)?;
    let review = task_review_id(&fingerprint);
    let markdown_matches = markdown == render_task_bundle_approval(&bundle)
        || legacy_task_bundle_approval(&bundle).as_deref() == Some(markdown.as_str());
    if metadata.fingerprint != fingerprint || metadata.review != review || !markdown_matches {
        return Err(ZdevError::new(format!(
            "Stored task review for area {area} does not match its bundle; run `zdev tasks review {area} --from <PATH_OR_DASH>` again"
        )));
    }
    Ok(TaskReview {
        metadata,
        bundle,
        markdown,
        markdown_path,
    })
}

pub(super) fn show_review(root: &Path, area: &str) -> Result<CommandOutput, ZdevError> {
    load_area(root, area)?;
    let _lock = ZdevStateLock::acquire(root)?;
    let artifact = read_task_review(root, area, None)?;
    Ok(CommandOutput::new(
        artifact.markdown.clone(),
        json!({
            "schema_version": SCHEMA_VERSION,
            "status": "reviewed",
            "area": area,
            "review": artifact.metadata.review,
            "path": task_review_path_value(root, &artifact.markdown_path),
            "markdown": artifact.markdown,
        }),
    ))
}

fn parse_derived_proposal(bytes: &[u8]) -> Result<DerivedProposalInput, ZdevError> {
    let input = std::str::from_utf8(bytes)
        .map_err(|error| ZdevError::new(format!("Invalid derived proposal UTF-8: {error}")))?;
    let (first_line, json) = input.split_once('\n').ok_or_else(|| {
        ZdevError::new("Invalid derived proposal: expected an identity line and one JSON object")
    })?;
    let proposal: DerivedProposal = serde_json::from_str(json)
        .map_err(|error| ZdevError::new(format!("Invalid derived proposal: {error}")))?;
    let expected = format!(
        "PROPOSE zdev-derived {} {}",
        proposal.area, proposal.source_task
    );
    if first_line != expected {
        return Err(ZdevError::new(format!(
            "Derived proposal identity line does not match its area and source task; expected `{expected}`"
        )));
    }
    Ok(DerivedProposalInput {
        proposal,
        json: json.as_bytes().to_vec(),
    })
}

fn read_derived_proposal(source: &Path) -> Result<DerivedProposalInput, ZdevError> {
    let bytes = if source == Path::new("-") {
        let mut bytes = Vec::new();
        io::stdin().read_to_end(&mut bytes).map_err(|error| {
            ZdevError::io("Cannot read derived proposal from standard input", error)
        })?;
        bytes
    } else {
        fs::read(source)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", source.display()), error))?
    };
    parse_derived_proposal(&bytes)
}

fn validate_derived_proposal(
    root: &Path,
    proposal: &DerivedProposal,
    area: &str,
) -> Result<TaskBundle, ZdevError> {
    if proposal.schema_version != SCHEMA_VERSION || proposal.area != area {
        return Err(ZdevError::new(
            "Derived proposal does not match the selected area",
        ));
    }
    if proposal.tasks.is_empty() || proposal.tasks.len() > 5 {
        return Err(ZdevError::new(
            "Derived proposal must contain between one and five tasks",
        ));
    }
    validate_nonempty_line(&proposal.source_result.summary, "Source result summary")?;
    for validation in &proposal.source_result.validation {
        validate_nonempty_line(validation, "Source result validation")?;
    }
    match proposal.proposal {
        DerivedProposalKind::InvestigationFollowUp => {
            if proposal.source_result.status != "complete"
                || proposal.source_result.validation.is_empty()
                || proposal.split_ownership.is_some()
            {
                return Err(ZdevError::new(
                    "Investigation follow-up requires a complete validated source result and forbids split ownership",
                ));
            }
        }
        DerivedProposalKind::ImplementationSplit => {
            if proposal.source_result.status != "split"
                || !proposal.source_result.validation.is_empty()
                || proposal.split_ownership.is_none()
            {
                return Err(ZdevError::new(
                    "Implementation split requires a split source result with empty validation and exact split ownership",
                ));
            }
        }
    }

    let bundle = TaskBundle {
        schema_version: proposal.schema_version,
        area: proposal.area.clone(),
        tasks: proposal.tasks.clone(),
    };
    validate_task_bundle(root, &bundle, area)?;
    let existing = load_tasks(root, area)?;
    let existing_ids = existing
        .iter()
        .map(|task| task.header.id.as_str())
        .collect::<BTreeSet<_>>();
    let existing_keys = existing
        .iter()
        .map(|task| task.header.key.as_str())
        .collect::<BTreeSet<_>>();
    if !existing_ids.contains(proposal.source_task.as_str()) {
        return Err(ZdevError::new(format!(
            "Derived proposal source task {} does not exist in area {area}",
            proposal.source_task
        )));
    }
    let proposed_keys = bundle
        .tasks
        .iter()
        .map(|task| task.key.as_str())
        .collect::<BTreeSet<_>>();
    for task in &bundle.tasks {
        if existing_keys.contains(task.key.as_str()) {
            return Err(ZdevError::new(format!("Duplicate task key: {}", task.key)));
        }
        for blocker in &task.blocked_by {
            if blocker == &proposal.source_task {
                return Err(ZdevError::new(format!(
                    "Derived task {} cannot be blocked by its source task",
                    task.key
                )));
            }
            if !existing_ids.contains(blocker.as_str()) && !proposed_keys.contains(blocker.as_str())
            {
                return Err(ZdevError::new(format!(
                    "Derived task {} has unknown blocker {blocker}",
                    task.key
                )));
            }
        }
    }
    validate_derived_dependencies(&bundle.tasks)?;
    if let Some(ownership) = &proposal.split_ownership {
        validate_split_ownership(root, &bundle.tasks, ownership)?;
    }
    Ok(bundle)
}

fn validate_derived_dependencies(tasks: &[TaskDraft]) -> Result<(), ZdevError> {
    let proposed = tasks
        .iter()
        .map(|task| task.key.as_str())
        .collect::<BTreeSet<_>>();
    let mut remaining = tasks
        .iter()
        .map(|task| {
            (
                task.key.as_str(),
                task.blocked_by
                    .iter()
                    .map(String::as_str)
                    .filter(|blocker| proposed.contains(blocker))
                    .collect::<BTreeSet<_>>(),
            )
        })
        .collect::<BTreeMap<_, _>>();
    loop {
        let ready = remaining
            .iter()
            .filter_map(|(key, blockers)| blockers.is_empty().then_some(*key))
            .collect::<Vec<_>>();
        if ready.is_empty() {
            break;
        }
        for key in &ready {
            remaining.remove(key);
        }
        for blockers in remaining.values_mut() {
            for key in &ready {
                blockers.remove(key);
            }
        }
    }
    if remaining.is_empty() {
        Ok(())
    } else {
        Err(ZdevError::new(
            "Derived proposal contains a cyclic or self dependency",
        ))
    }
}

fn validate_derived_path(root: &Path, value: &str, must_exist: bool) -> Result<(), ZdevError> {
    validate_nonempty_line(value, "Derived ownership path")?;
    if matches!(value.split('/').next(), Some(".git" | ".zdev")) {
        return Err(ZdevError::new(format!(
            "Derived ownership path cannot name repository control or zdev managed state: {value}"
        )));
    }
    if value.contains('\\')
        || value.starts_with('/')
        || value.ends_with('/')
        || value.contains("//")
        || value
            .split('/')
            .any(|part| part.is_empty() || part == "." || part == "..")
    {
        return Err(ZdevError::new(format!(
            "Derived ownership path is not normalized and repository-relative: {value}"
        )));
    }
    let path = root.join(value);
    let mut current = root.to_path_buf();
    let parts = value.split('/').collect::<Vec<_>>();
    for part in &parts[..parts.len().saturating_sub(1)] {
        current.push(part);
        let metadata = fs::symlink_metadata(&current).map_err(|error| {
            ZdevError::io(
                format!("Cannot inspect ownership path parent {}", current.display()),
                error,
            )
        })?;
        if metadata.file_type().is_symlink() || !metadata.is_dir() {
            return Err(ZdevError::new(format!(
                "Derived ownership path has a non-directory or symlinked parent: {value}"
            )));
        }
    }
    match fs::symlink_metadata(&path) {
        Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
            Err(ZdevError::new(format!(
                "Derived ownership path is not a regular file: {value}"
            )))
        }
        Ok(_) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound && !must_exist => Ok(()),
        Err(error) => Err(ZdevError::io(
            format!("Cannot inspect derived ownership path {}", path.display()),
            error,
        )),
    }
}

fn validate_split_ownership(
    root: &Path,
    tasks: &[TaskDraft],
    ownership: &SplitOwnership,
) -> Result<(), ZdevError> {
    let task_keys = tasks
        .iter()
        .map(|task| task.key.as_str())
        .collect::<BTreeSet<_>>();
    let child_keys = ownership
        .child_future_paths
        .iter()
        .map(|child| child.key.as_str())
        .collect::<BTreeSet<_>>();
    if child_keys.len() != ownership.child_future_paths.len() || child_keys != task_keys {
        return Err(ZdevError::new(
            "Split ownership must name every proposed task key exactly once",
        ));
    }
    let mut paths = BTreeSet::new();
    for path in &ownership.retained_parent_paths {
        if !paths.insert(path.as_str()) {
            return Err(ZdevError::new(format!(
                "Duplicate split ownership path: {path}"
            )));
        }
        validate_derived_path(root, path, true)?;
    }
    for child in &ownership.child_future_paths {
        if child.paths.is_empty() {
            return Err(ZdevError::new(format!(
                "Split ownership for {} contains no future paths",
                child.key
            )));
        }
        for path in &child.paths {
            if !paths.insert(path.as_str()) {
                return Err(ZdevError::new(format!(
                    "Split ownership path is duplicated or overlaps another owner: {path}"
                )));
            }
            validate_derived_path(root, path, false)?;
        }
    }
    Ok(())
}

fn git_nul_paths(root: &Path, arguments: &[&str]) -> Result<BTreeSet<String>, ZdevError> {
    let output = ProcessCommand::new("git")
        .args(arguments)
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot inspect Git paths for derived proposal", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Cannot inspect Git paths for derived proposal: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    let stdout = std::str::from_utf8(&output.stdout)
        .map_err(|error| ZdevError::new(format!("Git returned a non-UTF-8 path: {error}")))?;
    Ok(stdout
        .split('\0')
        .filter(|path| !path.is_empty())
        .map(str::to_owned)
        .collect())
}

fn derived_mechanical_ineligibility(
    root: &Path,
    proposal: &DerivedProposal,
) -> Result<Option<String>, ZdevError> {
    let (area, _) = load_area(root, &proposal.area)?;
    if area.lifecycle == AreaLifecycle::Closed {
        return Ok(Some(format!("area {} is closed", proposal.area)));
    }
    let tasks = load_tasks(root, &proposal.area)?;
    let source = tasks
        .iter()
        .find(|task| task.header.id == proposal.source_task)
        .expect("validated derived source task");
    if source.header.status != TaskStatus::Open {
        return Ok(Some(format!(
            "source task {} is not open",
            proposal.source_task
        )));
    }
    if task_state(source, &read_task_statuses(root, &proposal.area, &tasks)?) != "ready" {
        return Ok(Some(format!(
            "source task {} is not in the ready frontier",
            proposal.source_task
        )));
    }
    if let Err(error) = require_task_work_area_link(root, &proposal.area) {
        return Ok(Some(error.to_string()));
    }
    if proposal.proposal == DerivedProposalKind::InvestigationFollowUp
        && let Err(error) = require_hypothesis_completion(root, &proposal.area, source)
    {
        return Ok(Some(error.to_string()));
    }
    if let Some(ownership) = &proposal.split_ownership {
        let staged = git_nul_paths(root, &["diff", "--cached", "--name-only", "-z"])?;
        if !staged.is_empty() {
            return Ok(Some(
                "the index is not empty, so split ownership needs manual review".to_owned(),
            ));
        }
        let mut unstaged = git_nul_paths(root, &["diff", "--name-only", "-z"])?;
        unstaged.extend(git_nul_paths(
            root,
            &["ls-files", "--others", "--exclude-standard", "-z"],
        )?);
        let retained = ownership
            .retained_parent_paths
            .iter()
            .cloned()
            .collect::<BTreeSet<_>>();
        if unstaged != retained {
            return Ok(Some(
                "retained parent paths do not equal the checkout's complete unstaged path set"
                    .to_owned(),
            ));
        }
    }
    Ok(None)
}

fn derived_approval_id(proposal: &DerivedProposal) -> Result<String, ZdevError> {
    let canonical = serde_json::to_vec(proposal)
        .map_err(|error| ZdevError::new(format!("Cannot fingerprint derived proposal: {error}")))?;
    let hash = canonical.iter().fold(0xcbf29ce484222325_u64, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
    });
    Ok(format!("D{hash:016x}"))
}

fn derived_review_store(root: &Path, area: &str) -> Result<PathBuf, ZdevError> {
    let name = format!("zdev/derived-reviews/{area}");
    let path = PathBuf::from(git_output(root, &["rev-parse", "--git-path", &name])?);
    Ok(if path.is_absolute() {
        path
    } else {
        root.join(path)
    })
}

fn derived_review_id(fingerprint: &str) -> String {
    format!("R{}", fingerprint.strip_prefix('D').unwrap_or(fingerprint))
}

fn render_derived_review_with_bundle(
    proposal: &DerivedProposal,
    rendered_bundle: &str,
) -> Result<String, ZdevError> {
    let ownership = proposal
        .split_ownership
        .as_ref()
        .map(serde_json::to_string_pretty)
        .transpose()
        .map_err(|error| ZdevError::new(format!("Cannot render split ownership: {error}")))?
        .unwrap_or_else(|| "None".to_owned());
    Ok(format!(
        "# Derived Task Review\n\n## Area\n{}\n\n## Source task\n{}\n\n## Proposal kind\n{}\n\n## Source result\n\nStatus: {}\n\nSummary: {}\n\nValidation:\n{}\n\n## Split ownership\n\n{}\n\n## Proposed tasks\n\n{}",
        proposal.area,
        proposal.source_task,
        proposal.proposal.as_str(),
        proposal.source_result.status,
        proposal.source_result.summary,
        approval_list(&proposal.source_result.validation),
        ownership,
        rendered_bundle,
    ))
}

fn render_derived_review(
    proposal: &DerivedProposal,
    bundle: &TaskBundle,
) -> Result<String, ZdevError> {
    render_derived_review_with_bundle(proposal, &render_task_bundle_approval(bundle))
}

fn legacy_derived_review(
    proposal: &DerivedProposal,
    bundle: &TaskBundle,
) -> Result<Option<String>, ZdevError> {
    legacy_task_bundle_approval(bundle)
        .map(|rendered| render_derived_review_with_bundle(proposal, &rendered))
        .transpose()
}

fn read_derived_review(
    root: &Path,
    area: &str,
    expected_review: Option<&str>,
) -> Result<DerivedReview, ZdevError> {
    let store = derived_review_store(root, area)?;
    let current_path = store.join("current");
    let current_metadata = fs::symlink_metadata(&current_path).map_err(|error| {
        if error.kind() == io::ErrorKind::NotFound {
            ZdevError::new(format!(
                "No stored derived review exists for area {area}; run `zdev tasks derive review {area} --from <PATH_OR_DASH>`"
            ))
        } else {
            ZdevError::io(
                format!(
                    "Cannot inspect derived review pointer {}",
                    current_path.display()
                ),
                error,
            )
        }
    })?;
    if !current_metadata.file_type().is_file() {
        return Err(ZdevError::new(format!(
            "Stored derived review pointer for area {area} is corrupt; run `zdev tasks derive review {area} --from <PATH_OR_DASH>` again"
        )));
    }
    let current_bytes = fs::read(&current_path).map_err(|error| {
        ZdevError::io(
            format!(
                "Cannot read derived review pointer {}",
                current_path.display()
            ),
            error,
        )
    })?;
    let current = std::str::from_utf8(&current_bytes)
        .ok()
        .and_then(|value| value.strip_suffix('\n'));
    let Some(current) = current.filter(|value| valid_task_review_id(value)) else {
        return Err(ZdevError::new(format!(
            "Stored derived review pointer for area {area} is corrupt; run `zdev tasks derive review {area} --from <PATH_OR_DASH>` again"
        )));
    };
    if expected_review.is_some_and(|expected| expected != current) {
        return Err(ZdevError::new(format!(
            "Derived review {} was replaced by {current}; show and approve the current review before applying",
            expected_review.expect("checked")
        )));
    }
    let directory = store.join(current);
    let metadata_bytes = read_regular_file(&directory.join("metadata.json"), area)?;
    let metadata: DerivedReviewMetadata =
        serde_json::from_slice(&metadata_bytes).map_err(|error| {
            ZdevError::new(format!(
                "Stored derived review for area {area} is corrupt: {error}. Run `zdev tasks derive review {area} --from <PATH_OR_DASH>` again"
            ))
        })?;
    let proposal_bytes = read_regular_file(&directory.join("proposal.json"), area)?;
    let proposal: DerivedProposal = serde_json::from_slice(&proposal_bytes).map_err(|error| {
        ZdevError::new(format!(
            "Stored derived proposal for area {area} is corrupt: {error}. Run `zdev tasks derive review {area} --from <PATH_OR_DASH>` again"
        ))
    })?;
    let markdown_path = directory.join("review.md");
    let markdown = String::from_utf8(read_regular_file(&markdown_path, area)?).map_err(|_| {
        ZdevError::new(format!(
            "Stored derived review Markdown for area {area} is not valid UTF-8"
        ))
    })?;
    let bundle = validate_derived_proposal(root, &proposal, area).map_err(|error| {
        ZdevError::new(format!(
            "Stored derived review for area {area} is no longer valid: {error}"
        ))
    })?;
    let fingerprint = derived_approval_id(&proposal)?;
    let review = derived_review_id(&fingerprint);
    let markdown_matches = markdown == render_derived_review(&proposal, &bundle)?
        || legacy_derived_review(&proposal, &bundle)?.as_deref() == Some(markdown.as_str());
    if metadata.schema_version != SCHEMA_VERSION
        || metadata.area != area
        || metadata.source_task != proposal.source_task
        || metadata.proposal != proposal.proposal
        || metadata.review != current
        || metadata.review != review
        || metadata.fingerprint != fingerprint
        || !markdown_matches
    {
        return Err(ZdevError::new(format!(
            "Stored derived review for area {area} does not match its proposal; run `zdev tasks derive review {area} --from <PATH_OR_DASH>` again"
        )));
    }
    Ok(DerivedReview {
        metadata,
        proposal,
        markdown,
        markdown_path,
    })
}

pub(super) fn review_derived(
    root: &Path,
    area: &str,
    source: &Path,
) -> Result<CommandOutput, ZdevError> {
    let input = read_derived_proposal(source)?;
    let proposal = input.proposal;
    let bundle = validate_derived_proposal(root, &proposal, area)?;
    let fingerprint = derived_approval_id(&proposal)?;
    let review = derived_review_id(&fingerprint);
    let markdown = render_derived_review(&proposal, &bundle)?;
    let metadata = DerivedReviewMetadata {
        schema_version: SCHEMA_VERSION,
        area: area.to_owned(),
        source_task: proposal.source_task.clone(),
        proposal: proposal.proposal,
        review: review.clone(),
        fingerprint,
    };
    let mut metadata_bytes = serde_json::to_vec_pretty(&metadata)
        .map_err(|error| ZdevError::new(format!("Cannot serialize derived review: {error}")))?;
    metadata_bytes.push(b'\n');
    let _lock = ZdevStateLock::acquire(root)?;
    let bundle = validate_derived_proposal(root, &proposal, area)?;
    let reason = derived_mechanical_ineligibility(root, &proposal)?;
    let store = derived_review_store(root, area)?;
    let directory = store.join(&review);
    fs::create_dir_all(&directory).map_err(|error| {
        ZdevError::io(
            format!(
                "Cannot create derived review directory {}",
                directory.display()
            ),
            error,
        )
    })?;
    write_atomic(&directory.join("proposal.json"), &input.json)?;
    write_atomic(&directory.join("metadata.json"), &metadata_bytes)?;
    write_atomic(&directory.join("review.md"), markdown.as_bytes())?;
    write_atomic(&store.join("current"), format!("{review}\n").as_bytes())?;
    if let Ok(entries) = fs::read_dir(&store) {
        for entry in entries.flatten() {
            if entry.file_name() != OsStr::new(&review)
                && entry.file_type().is_ok_and(|kind| kind.is_dir())
            {
                let _ = fs::remove_dir_all(entry.path());
            }
        }
    }
    let mechanically_eligible = reason.is_none();
    let mut result = json!({
        "schema_version": SCHEMA_VERSION,
        "status": "reviewed",
        "area": area,
        "source_task": proposal.source_task,
        "proposal": proposal.proposal.as_str(),
        "review": review,
        "path": task_review_path_value(root, &directory.join("review.md")),
        "mechanically_eligible": mechanically_eligible,
        "coordinator_authority_required": true,
    });
    if let Some(reason) = reason {
        result["reason"] = Value::String(reason);
    }
    Ok(CommandOutput::new(
        render_derived_review(&proposal, &bundle)?,
        result,
    ))
}

pub(super) fn show_derived_review(root: &Path, area: &str) -> Result<CommandOutput, ZdevError> {
    load_area(root, area)?;
    let _lock = ZdevStateLock::acquire(root)?;
    let artifact = read_derived_review(root, area, None)?;
    Ok(CommandOutput::new(
        artifact.markdown.clone(),
        json!({
            "schema_version": SCHEMA_VERSION,
            "status": "reviewed",
            "area": area,
            "source_task": artifact.metadata.source_task,
            "proposal": artifact.metadata.proposal.as_str(),
            "review": artifact.metadata.review,
            "path": task_review_path_value(root, &artifact.markdown_path),
            "markdown": artifact.markdown,
        }),
    ))
}

pub(super) fn apply_derived(
    root: &Path,
    area: &str,
    source: Option<&Path>,
    reviewed: Option<&str>,
    approval: Option<&str>,
) -> Result<CommandOutput, ZdevError> {
    let direct = source.map(read_derived_proposal).transpose()?;
    if let Some(input) = &direct {
        validate_derived_proposal(root, &input.proposal, area)?;
        if let Some(approval) = approval {
            let fingerprint = derived_approval_id(&input.proposal)?;
            if approval != fingerprint {
                return Err(ZdevError::new(
                    "Derived proposal differs from the reviewed content; run `zdev tasks derive review` again before applying it",
                ));
            }
        }
    }

    let _lock = ZdevStateLock::acquire(root)?;
    let stored = reviewed
        .map(|review| read_derived_review(root, area, Some(review)))
        .transpose()?;
    let proposal = if let Some(stored) = &stored {
        &stored.proposal
    } else {
        &direct
            .as_ref()
            .expect("clap requires --from or --reviewed")
            .proposal
    };
    let bundle = validate_derived_proposal(root, proposal, area)?;
    if let Some(reason) = derived_mechanical_ineligibility(root, proposal)? {
        let message = if reviewed.is_some() {
            format!(
                "Cannot apply reviewed derived proposal: {reason}. Refresh the handoff and store a new review"
            )
        } else {
            format!(
                "Cannot apply derived proposal automatically: {reason}. Use `zdev tasks derive review` for manual review"
            )
        };
        return Err(ZdevError::new(message));
    }
    if let Some(operation) = git_operation(root)? {
        return Err(ZdevError::new(format!(
            "Cannot apply derived proposal while a {operation} is in progress. Finish or abort it, then retry"
        )));
    }
    git_output(root, &["rev-parse", "--verify", "HEAD"]).map_err(|_| {
        ZdevError::new("Cannot apply derived proposal before the repository has a commit")
    })?;

    let (metadata, area_dir) = load_area(root, area)?;
    require_checked_out_area_branch(root, &metadata)?;
    let existing = load_tasks(root, area)?;
    let source_task = find_task(&existing, &proposal.source_task)?;
    if proposal.proposal == DerivedProposalKind::ImplementationSplit {
        for draft in &bundle.tasks {
            if draft.slice.as_ref() != source_task.header.slice.as_ref() && draft.slice.is_some() {
                return Err(ZdevError::new(format!(
                    "Split task {} must inherit source task slice {}",
                    draft.key,
                    source_task.header.slice.as_deref().unwrap_or("None")
                )));
            }
        }
    }

    let prior_index = git_output(root, &["write-tree"])?;
    let prior_staged = git_nul_paths(root, &["diff", "--cached", "--name-only", "-z"])?;
    let mut unstaged = git_nul_paths(root, &["diff", "--name-only", "-z"])?;
    unstaged.extend(git_nul_paths(
        root,
        &["ls-files", "--others", "--exclude-standard", "-z"],
    )?);
    if proposal.proposal == DerivedProposalKind::InvestigationFollowUp {
        for path in &prior_staged {
            validate_derived_path(root, path, true).map_err(|error| {
                ZdevError::new(format!(
                    "Cannot treat staged path {path} as a verified investigation artifact: {error}"
                ))
            })?;
        }
        if !unstaged.is_empty() {
            return Err(ZdevError::new(
                "Cannot apply investigation follow-up with unstaged or untracked paths; stage only its verified task-owned artifact paths first",
            ));
        }
    }

    let existing_ids = existing
        .iter()
        .map(|task| task.header.id.as_str())
        .collect::<BTreeSet<_>>();
    let existing_keys = existing
        .iter()
        .map(|task| task.header.key.as_str())
        .collect::<BTreeSet<_>>();
    for task in &bundle.tasks {
        if existing_keys.contains(task.key.as_str()) {
            return Err(ZdevError::new(format!("Duplicate task key: {}", task.key)));
        }
    }
    let mut next_number = existing
        .iter()
        .filter_map(|task| task.header.id.rsplit_once('-')?.1.parse::<u64>().ok())
        .max()
        .unwrap_or(0);
    let mut allocated = BTreeMap::new();
    for task in &bundle.tasks {
        next_number += 1;
        allocated.insert(task.key.as_str(), format!("{area}-{next_number:03}"));
    }

    let ownership_paths = proposal.split_ownership.as_ref().map(|ownership| {
        ownership
            .child_future_paths
            .iter()
            .map(|child| (child.key.as_str(), child.paths.as_slice()))
            .collect::<BTreeMap<_, _>>()
    });
    let mut writes = Vec::new();
    for draft in &bundle.tasks {
        let id = allocated[draft.key.as_str()].clone();
        let blockers = draft
            .blocked_by
            .iter()
            .map(|blocker| {
                if let Some(id) = allocated.get(blocker.as_str()) {
                    Ok(id.clone())
                } else if existing_ids.contains(blocker.as_str()) {
                    Ok(blocker.clone())
                } else {
                    Err(ZdevError::new(format!(
                        "Task {} has unknown blocker {blocker}",
                        draft.key
                    )))
                }
            })
            .collect::<Result<Vec<_>, _>>()?;
        let header = TaskHeader {
            schema_version: SCHEMA_VERSION,
            id: id.clone(),
            key: draft.key.clone(),
            area: area.to_owned(),
            status: TaskStatus::Open,
            complexity: draft.complexity,
            afk: draft.afk,
            priority: draft.priority,
            slice: match proposal.proposal {
                DerivedProposalKind::InvestigationFollowUp => draft.slice.clone(),
                DerivedProposalKind::ImplementationSplit => source_task.header.slice.clone(),
            },
            blocked_by: blockers,
            requires_code: draft.requires_code.clone(),
            hypothesis: resolve_hypothesis(draft.hypothesis.as_ref(), &allocated),
            research_results: Vec::new(),
        };
        let path = area_dir.join("tasks").join(format!(
            "{number:03}-{}.md",
            slug(&draft.title),
            number = parse_number(&id)?
        ));
        let mut rendered = draft.clone();
        if let Some(paths) = ownership_paths
            .as_ref()
            .and_then(|paths| paths.get(draft.key.as_str()))
        {
            let paths = serde_json::to_string(paths).map_err(|error| {
                ZdevError::new(format!("Cannot render derived ownership paths: {error}"))
            })?;
            rendered.boundaries.push(format!(
                "Initial task-owned path allocation: {paths}. Coordination may extend it only after checking retained parent edits and sibling assignments."
            ));
        }
        writes.push((path, render_draft(&header, &rendered)?));
    }

    let mut source_header = source_task.header.clone();
    let source_body = match proposal.proposal {
        DerivedProposalKind::InvestigationFollowUp => {
            require_hypothesis_completion(root, area, source_task)?;
            source_header.status = TaskStatus::Done;
            let mut body = replace_markdown_section(
                &source_task.body,
                "Done when",
                &source_task.path,
                |section| section.replace("- [ ] ", "- [x] "),
            )?;
            if !body.ends_with('\n') {
                body.push('\n');
            }
            body.push_str("\n## Result\n\n");
            body.push_str(&proposal.source_result.summary);
            body.push_str("\n\nValidation:\n\n");
            for item in &proposal.source_result.validation {
                body.push_str(&format!("- {item}\n"));
            }
            body
        }
        DerivedProposalKind::ImplementationSplit => {
            source_header.blocked_by.extend(
                bundle
                    .tasks
                    .iter()
                    .map(|task| allocated[task.key.as_str()].clone()),
            );
            source_header.blocked_by.sort();
            source_header.blocked_by.dedup();
            source_task.body.clone()
        }
    };
    let source_content = format!(
        "+++\n{}+++\n{}",
        toml::to_string(&source_header)
            .map_err(|error| ZdevError::new(format!("Cannot render source task: {error}")))?,
        source_body
    );

    let mut hypothetical = existing.clone();
    let source_slot = hypothetical
        .iter_mut()
        .find(|task| task.header.id == proposal.source_task)
        .expect("validated source task");
    *source_slot = parse_task(&source_content, &source_task.path, area)?;
    for (path, content) in &writes {
        hypothetical.push(parse_task(content, path, area)?);
    }
    hypothetical.sort_by(compare_tasks_by_id);
    validate_graph(root, area, &hypothetical)?;
    let statuses = read_task_statuses(root, area, &hypothetical)?;
    let index_content = render_index(area, &hypothetical, &statuses);
    let dependent_indexes = if source_header.status == source_task.header.status {
        Vec::new()
    } else {
        render_dependent_indexes(root, area, &proposal.source_task, source_header.status)?
    };
    let dependent_index_paths = dependent_indexes
        .iter()
        .map(|(path, _)| path.clone())
        .collect::<Vec<_>>();
    let ready = hypothetical
        .iter()
        .filter(|task| task_state(task, &statuses) == "ready")
        .map(|task| task.header.id.clone())
        .collect::<Vec<_>>();

    let index_path = area_dir.join("TASKS.md");
    let original_source = fs::read(&source_task.path).map_err(|error| {
        ZdevError::io(format!("Cannot read {}", source_task.path.display()), error)
    })?;
    let original_index = fs::read(&index_path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", index_path.display()), error))?;
    let original_dependent_indexes = read_originals(&dependent_indexes)?;
    let retained = proposal
        .split_ownership
        .as_ref()
        .map(|ownership| {
            ownership
                .retained_parent_paths
                .iter()
                .map(|path| {
                    fs::read(root.join(path))
                        .map(|bytes| (path.clone(), bytes))
                        .map_err(|error| {
                            ZdevError::io(format!("Cannot read retained path {path}"), error)
                        })
                })
                .collect::<Result<Vec<_>, _>>()
        })
        .transpose()?
        .unwrap_or_default();
    let staged_artifacts = prior_staged
        .iter()
        .map(|path| {
            fs::read(root.join(path))
                .map(|bytes| (path.clone(), bytes))
                .map_err(|error| {
                    ZdevError::io(format!("Cannot read staged artifact {path}"), error)
                })
        })
        .collect::<Result<Vec<_>, _>>()?;
    let mut created = Vec::new();
    let apply = (|| -> Result<(String, String, Vec<PathBuf>), ZdevError> {
        write_atomic(&source_task.path, source_content.as_bytes())?;
        for (path, content) in &writes {
            let mut file = OpenOptions::new()
                .create_new(true)
                .write(true)
                .open(path)
                .map_err(|error| {
                    ZdevError::io(format!("Cannot create {}", path.display()), error)
                })?;
            created.push(path.clone());
            file.write_all(content.as_bytes())
                .and_then(|()| file.sync_all())
                .map_err(|error| {
                    ZdevError::io(format!("Cannot write {}", path.display()), error)
                })?;
        }
        write_atomic(&index_path, index_content.as_bytes())?;
        for (path, bytes) in &dependent_indexes {
            write_atomic(path, bytes)?;
        }
        for (path, bytes) in &retained {
            if fs::read(root.join(path)).ok().as_deref() != Some(bytes.as_slice()) {
                return Err(ZdevError::new(format!(
                    "Retained parent path changed before commit: {path}"
                )));
            }
        }
        for (path, bytes) in &staged_artifacts {
            if fs::read(root.join(path)).ok().as_deref() != Some(bytes.as_slice()) {
                return Err(ZdevError::new(format!(
                    "Staged investigation artifact changed before commit: {path}"
                )));
            }
        }
        let mut paths = prior_staged
            .iter()
            .map(|path| root.join(path))
            .collect::<Vec<_>>();
        paths.push(source_task.path.clone());
        paths.extend(created.iter().cloned());
        paths.push(index_path.clone());
        paths.extend(dependent_index_paths.iter().cloned());
        let (revision, change_id) = commit_task_import(root, area, &paths)?;
        Ok((revision, change_id, paths))
    })();

    let (revision, change_id, paths) = match apply {
        Ok(result) => result,
        Err(error) => {
            let mut rollback_errors = Vec::new();
            for path in &created {
                if let Err(rollback) = fs::remove_file(path)
                    && rollback.kind() != io::ErrorKind::NotFound
                {
                    rollback_errors.push(format!("cannot remove {}: {rollback}", path.display()));
                }
            }
            if let Err(rollback) = write_atomic(&source_task.path, &original_source) {
                rollback_errors.push(format!("cannot restore source task: {rollback}"));
            }
            if let Err(rollback) = write_atomic(&index_path, &original_index) {
                rollback_errors.push(format!("cannot restore task index: {rollback}"));
            }
            for (path, original) in dependent_index_paths
                .iter()
                .zip(&original_dependent_indexes)
            {
                if let Err(rollback) = write_atomic(path, original) {
                    rollback_errors.push(format!(
                        "cannot restore dependent task index {}: {rollback}",
                        path.display()
                    ));
                }
            }
            if let Err(rollback) = git_read_tree(root, &prior_index) {
                rollback_errors.push(format!("cannot restore Git index: {rollback}"));
            }
            for (path, bytes) in &retained {
                if fs::read(root.join(path)).ok().as_deref() != Some(bytes.as_slice())
                    && let Err(rollback) = write_atomic(&root.join(path), bytes)
                {
                    rollback_errors.push(format!("cannot restore {path}: {rollback}"));
                }
            }
            for (path, bytes) in &staged_artifacts {
                if fs::read(root.join(path)).ok().as_deref() != Some(bytes.as_slice())
                    && let Err(rollback) = write_atomic(&root.join(path), bytes)
                {
                    rollback_errors.push(format!("cannot restore {path}: {rollback}"));
                }
            }
            if rollback_errors.is_empty() {
                return Err(ZdevError::new(format!(
                    "Could not apply derived proposal; all task, index, and retained bytes were restored. {error}"
                )));
            }
            return Err(ZdevError::new(format!(
                "Could not apply derived proposal, and rollback was incomplete. {error}. {}",
                rollback_errors.join("; ")
            )));
        }
    };

    let ids = bundle
        .tasks
        .iter()
        .map(|task| allocated[task.key.as_str()].clone())
        .collect::<Vec<_>>();
    let mut value = json!({
        "schema_version": SCHEMA_VERSION,
        "status": "committed",
        "area": area,
        "source_task": proposal.source_task,
        "proposal": proposal.proposal.as_str(),
        "source_result": proposal.source_result,
        "tasks": ids,
        "ready": ready,
        "commit": revision,
        "change_id": change_id,
        "paths": relative_paths(root, &paths)?,
        "dependent_indexes": relative_paths(root, &dependent_index_paths)?,
    });
    if let Some(ownership) = &proposal.split_ownership {
        value
            .as_object_mut()
            .expect("JSON object")
            .insert("split_ownership".to_owned(), json!(ownership));
    }
    Ok(CommandOutput::new(
        format!("Applied derived tasks to {area} ({revision})"),
        value,
    ))
}

fn git_read_tree(root: &Path, tree: &str) -> Result<(), ZdevError> {
    let output = ProcessCommand::new("git")
        .args(["read-tree", tree])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot restore Git index", error))?;
    if output.status.success() {
        Ok(())
    } else {
        Err(ZdevError::new(format!(
            "Cannot restore Git index: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )))
    }
}

pub(crate) struct GeneratedBundle {
    pub ids: Vec<String>,
    pub files: Vec<(PathBuf, Vec<u8>)>,
}

/// Validate and allocate the exact ordinary graph. Caller holds the state lock.
pub(crate) fn prepare_generated_bundle(
    root: &Path,
    area: &str,
    bundle: &TaskBundle,
) -> Result<GeneratedBundle, ZdevError> {
    validate_task_bundle(root, bundle, area)?;
    let (writes, _) = allocate_bundle(root, area, bundle)?;
    let ids = writes
        .iter()
        .map(|(path, content)| parse_task(content, path, area).map(|task| task.header.id))
        .collect::<Result<Vec<_>, _>>()?;
    let mut hypothetical = load_tasks(root, area)?;
    for (path, content) in &writes {
        hypothetical.push(parse_task(content, path, area)?);
    }
    hypothetical.sort_by(compare_tasks_by_id);
    let statuses = read_task_statuses(root, area, &hypothetical)?;
    let mut files = writes
        .into_iter()
        .map(|(path, content)| (path, content.into_bytes()))
        .collect::<Vec<_>>();
    files.push((
        root.join(format!(".zdev/{area}/TASKS.md")),
        render_index(area, &hypothetical, &statuses).into_bytes(),
    ));
    Ok(GeneratedBundle { ids, files })
}

pub(crate) fn generated_bundle_fingerprint(bundle: &TaskBundle) -> Result<String, ZdevError> {
    task_bundle_approval_id(bundle)
}

type BundleWrites = (Vec<(PathBuf, String)>, Vec<String>);

fn allocate_bundle(
    root: &Path,
    area: &str,
    bundle: &TaskBundle,
) -> Result<BundleWrites, ZdevError> {
    let (_, area_dir) = load_area(root, area)?;
    let existing = load_tasks(root, area)?;
    let existing_ids = existing
        .iter()
        .map(|task| task.header.id.as_str())
        .collect::<BTreeSet<_>>();
    let existing_keys = existing
        .iter()
        .map(|task| task.header.key.as_str())
        .collect::<BTreeSet<_>>();
    for task in &bundle.tasks {
        if existing_keys.contains(task.key.as_str()) {
            return Err(ZdevError::new(format!("Duplicate task key: {}", task.key)));
        }
    }
    let mut next_number = existing
        .iter()
        .filter_map(|task| task.header.id.rsplit_once('-')?.1.parse::<u64>().ok())
        .max()
        .unwrap_or(0);
    let mut allocated = BTreeMap::new();
    for task in &bundle.tasks {
        next_number += 1;
        allocated.insert(task.key.as_str(), format!("{area}-{next_number:03}"));
    }
    let mut writes = Vec::new();
    for draft in &bundle.tasks {
        let id = allocated[&draft.key.as_str()].clone();
        let blockers = draft
            .blocked_by
            .iter()
            .map(|blocker| {
                if let Some(id) = allocated.get(blocker.as_str()) {
                    Ok((*id).clone())
                } else if existing_ids.contains(blocker.as_str())
                    || task_exists_in_other_area(root, area, blocker)?
                {
                    Ok(blocker.clone())
                } else {
                    Err(unknown_blocker_error(root, area, &draft.key, blocker))
                }
            })
            .collect::<Result<Vec<_>, _>>()?;
        if blockers.iter().any(|blocker| blocker == &id) {
            return Err(ZdevError::new(format!("Task {} blocks itself", draft.key)));
        }
        let header = TaskHeader {
            schema_version: SCHEMA_VERSION,
            id: id.clone(),
            key: draft.key.clone(),
            area: area.to_owned(),
            status: TaskStatus::Open,
            complexity: draft.complexity,
            afk: draft.afk,
            priority: draft.priority,
            slice: draft.slice.clone(),
            blocked_by: blockers,
            requires_code: draft.requires_code.clone(),
            hypothesis: resolve_hypothesis(draft.hypothesis.as_ref(), &allocated),
            research_results: Vec::new(),
        };
        let path = area_dir.join("tasks").join(format!(
            "{next:03}-{}.md",
            slug(&draft.title),
            next = parse_number(&id)?
        ));
        let body = render_draft(&header, draft)?;
        writes.push((path, body));
    }
    let mut hypothetical = existing.clone();
    for (path, content) in &writes {
        hypothetical.push(parse_task(content, path, area)?);
    }
    hypothetical.sort_by(compare_tasks_by_id);
    validate_graph(root, area, &hypothetical)?;
    let statuses = read_task_statuses(root, area, &hypothetical)?;
    let ready = hypothetical
        .iter()
        .filter(|task| task_state(task, &statuses) == "ready")
        .map(|task| task.header.id.clone())
        .collect::<Vec<_>>();
    Ok((writes, ready))
}

pub(super) fn import(
    root: &Path,
    area: &str,
    source: Option<&Path>,
    reviewed: Option<&str>,
    commit_changes: bool,
    approval: Option<&str>,
) -> Result<CommandOutput, ZdevError> {
    let direct_bundle = if let Some(source) = source {
        let bundle = read_task_bundle(source)?;
        validate_task_bundle(root, &bundle, area)?;
        if let Some(approval) = approval {
            let actual = task_bundle_approval_id(&bundle)?;
            if approval != actual {
                return Err(ZdevError::new(
                    "Task bundle differs from the reviewed content; run `zdev tasks review` again before importing it",
                ));
            }
        }
        Some(bundle)
    } else {
        None
    };
    let _lock = ZdevStateLock::acquire(root)?;
    let bundle = if let Some(reviewed) = reviewed {
        read_task_review(root, area, Some(reviewed))?.bundle
    } else {
        direct_bundle.expect("clap requires --from or --reviewed")
    };
    validate_task_bundle(root, &bundle, area)?;
    let (metadata, area_dir) = load_area(root, area)?;
    super::project::validate_area_relationships(root, &list_areas(root)?)?;
    if metadata.lifecycle == AreaLifecycle::Closed {
        return Err(ZdevError::new(format!(
            "Cannot add tasks to closed area {area}. Run `zdev area reopen {area}` first"
        )));
    }
    let committable_paths = if commit_changes {
        require_checked_out_area_branch(root, &metadata)?;
        require_committable_task_import(root, area)?
    } else {
        Vec::new()
    };
    let (writes, ready) = allocate_bundle(root, area, &bundle)?;
    let index_path = area_dir.join("TASKS.md");
    let previous_index = fs::read(&index_path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", index_path.display()), error))?;
    let mut created = Vec::new();
    for (path, content) in &writes {
        match OpenOptions::new().create_new(true).write(true).open(path) {
            Ok(mut file) => {
                created.push(path.clone());
                if let Err(error) = file
                    .write_all(content.as_bytes())
                    .and_then(|()| file.sync_all())
                {
                    let write_error =
                        ZdevError::io(format!("Cannot write {}", path.display()), error);
                    drop(file);
                    return Err(import_rollback_error(write_error, &created, None));
                }
            }
            Err(error) => {
                let create_error =
                    ZdevError::io(format!("Cannot create {}", path.display()), error);
                return Err(import_rollback_error(create_error, &created, None));
            }
        }
    }
    if let Err(error) = write_index(root, area) {
        return Err(import_rollback_error(
            error,
            &created,
            commit_changes.then_some((index_path.as_path(), previous_index.as_slice())),
        ));
    }
    let ids = writes
        .iter()
        .map(|(_, content)| {
            parse_task(content, Path::new("task.md"), area).map(|task| task.header.id)
        })
        .collect::<Result<Vec<_>, _>>()?;
    if commit_changes {
        let mut paths = committable_paths;
        paths.extend(
            writes
                .iter()
                .map(|(path, _)| path.clone())
                .chain(std::iter::once(index_path.clone())),
        );
        return match commit_task_import(root, area, &paths) {
            Ok((revision, change_id)) => Ok(CommandOutput::new(
                format!(
                    "Added and committed {} tasks to {area} ({revision})",
                    ids.len()
                ),
                json!({"schema_version": SCHEMA_VERSION, "status": "committed", "area": area, "tasks": ids, "ready": ready, "commit": revision, "change_id": change_id, "paths": relative_paths(root, &paths)?}),
            )),
            Err(error) => Err(import_rollback_error(
                rollback_task_import_index(root, &paths, error),
                &created,
                Some((index_path.as_path(), previous_index.as_slice())),
            )),
        };
    }
    Ok(CommandOutput::new(
        format!("Added {} tasks to {area}", ids.len()),
        json!({"schema_version": SCHEMA_VERSION, "status": "created", "area": area, "tasks": ids, "ready": ready}),
    ))
}

fn import_rollback_error(
    error: ZdevError,
    created: &[PathBuf],
    restore_index: Option<(&Path, &[u8])>,
) -> ZdevError {
    let mut cleanup_errors = created
        .iter()
        .filter_map(|path| {
            fs::remove_file(path)
                .err()
                .map(|cleanup| format!("cannot remove {}: {cleanup}", path.display()))
        })
        .collect::<Vec<_>>();
    if let Some((path, contents)) = restore_index
        && let Err(restore) = write_atomic(path, contents)
    {
        cleanup_errors.push(format!("cannot restore {}: {restore}", path.display()));
    }
    if cleanup_errors.is_empty() {
        ZdevError::new(format!(
            "Could not add tasks; the import was rolled back and no imported task changes were kept. {error}"
        ))
    } else {
        ZdevError::new(format!(
            "Could not add tasks, and cleanup was incomplete. {error}. Resolve these paths before retrying: {}",
            cleanup_errors.join("; "),
        ))
    }
}

fn require_committable_task_import(root: &Path, area: &str) -> Result<Vec<PathBuf>, ZdevError> {
    if let Some(operation) = git_operation(root)? {
        return Err(ZdevError::new(format!(
            "Cannot add and commit tasks while a {operation} is in progress. Finish or abort it, then retry"
        )));
    }
    git_output(root, &["rev-parse", "--verify", "HEAD"]).map_err(|_| {
        ZdevError::new(
            "Cannot add and commit tasks before the repository has a commit. Create the initial commit, then retry",
        )
    })?;
    let config = read_config(root)?;
    let area_path = format!(".zdev/{area}");
    let tracked = git_output(root, &["ls-files", "--", &area_path])?;
    if tracked.is_empty() {
        return require_committable_initial_task_import(root, area, config.project.record);
    }
    let tracked_paths = tracked.lines().collect::<BTreeSet<_>>();
    let required_tracked =
        ["area.toml", "brief.md", "TASKS.md"].map(|name| format!("{area_path}/{name}"));
    if required_tracked
        .iter()
        .any(|path| !tracked_paths.contains(path.as_str()))
    {
        return Err(ZdevError::new(format!(
            "Cannot add and commit tasks: {area_path} is ambiguously partially tracked. Commit or resolve its planning files first"
        )));
    }
    let brief_relative = format!("{area_path}/brief.md");
    let unstaged = git_output(root, &["diff", "--name-only", "--", &area_path])?;
    let staged = git_output(root, &["diff", "--cached", "--name-only", "--", &area_path])?;
    let untracked = git_output(
        root,
        &[
            "ls-files",
            "--others",
            "--exclude-standard",
            "--",
            &area_path,
        ],
    )?;
    let ignored = git_output(
        root,
        &[
            "ls-files",
            "--others",
            "--ignored",
            "--exclude-standard",
            "--",
            &area_path,
        ],
    )?;
    let brief_changed = unstaged == brief_relative;
    if !staged.is_empty()
        || !untracked.is_empty()
        || !ignored.is_empty()
        || (!unstaged.is_empty() && !brief_changed)
    {
        return Err(ZdevError::new(format!(
            "Cannot add and commit tasks: {area_path} already has local changes. Commit or resolve them first"
        )));
    }
    if !brief_changed {
        return Ok(Vec::new());
    }
    let brief = root.join(&brief_relative);
    let metadata = fs::symlink_metadata(&brief)
        .map_err(|error| ZdevError::io(format!("Cannot inspect {}", brief.display()), error))?;
    if !metadata.file_type().is_file() {
        return Err(ZdevError::new(format!(
            "Cannot add and commit tasks: {} must be a tracked regular file",
            brief.display()
        )));
    }
    git_output(
        root,
        &["ls-files", "--error-unmatch", "--", &brief_relative],
    )
    .map_err(|_| {
        ZdevError::new(format!(
            "Cannot add and commit tasks: {} must already be tracked",
            brief.display()
        ))
    })?;
    validate_brief(&brief)?;
    Ok(vec![brief])
}

fn require_committable_initial_task_import(
    root: &Path,
    area: &str,
    record: RecordPolicy,
) -> Result<Vec<PathBuf>, ZdevError> {
    if record == RecordPolicy::Personal {
        return Err(ZdevError::new(
            "Cannot add and commit initial tasks for a personal record. Import without --commit to keep the tasks local",
        ));
    }

    let config_relative = ".zdev/config.toml";
    let config_path = root.join(config_relative);
    require_clean_regular_planning_file(root, config_relative)?;

    let area_relative = format!(".zdev/{area}");
    let area_dir = root.join(&area_relative);
    let mut paths = vec![config_path];
    collect_initial_area_paths(root, &area_dir, &area_relative, &mut paths)?;

    let (metadata, _) = load_area(root, area)?;
    if let Some(parent) = metadata.parent {
        let parent_metadata = format!(".zdev/{parent}/area.toml");
        git_output(
            root,
            &["ls-files", "--error-unmatch", "--", &parent_metadata],
        )
        .map_err(|_| {
            ZdevError::new(format!(
                "Cannot add and commit initial tasks: parent area {parent} must already be tracked"
            ))
        })?;
    }

    if !git_output(root, &["ls-files", "--", config_relative])?.is_empty() {
        paths.remove(0);
    }
    validate_brief(&area_dir.join("brief.md"))?;
    Ok(paths)
}

fn require_clean_regular_planning_file(root: &Path, relative: &str) -> Result<(), ZdevError> {
    let path = root.join(relative);
    let metadata = fs::symlink_metadata(&path)
        .map_err(|error| ZdevError::io(format!("Cannot inspect {}", path.display()), error))?;
    if !metadata.file_type().is_file() {
        return Err(ZdevError::new(format!(
            "Cannot add and commit initial tasks: {} must be a regular file",
            path.display()
        )));
    }
    let staged = git_output(root, &["diff", "--cached", "--name-only", "--", relative])?;
    let unstaged = git_output(root, &["diff", "--name-only", "--", relative])?;
    if !staged.is_empty() || !unstaged.is_empty() {
        return Err(ZdevError::new(format!(
            "Cannot add and commit initial tasks: {relative} has staged or modified tracked content"
        )));
    }
    Ok(())
}

fn collect_initial_area_paths(
    root: &Path,
    directory: &Path,
    relative_directory: &str,
    paths: &mut Vec<PathBuf>,
) -> Result<(), ZdevError> {
    let metadata = fs::symlink_metadata(directory)
        .map_err(|error| ZdevError::io(format!("Cannot inspect {}", directory.display()), error))?;
    if !metadata.file_type().is_dir() {
        return Err(ZdevError::new(format!(
            "Cannot add and commit initial tasks: {} must be a regular directory",
            directory.display()
        )));
    }
    let staged = git_output(
        root,
        &["diff", "--cached", "--name-only", "--", relative_directory],
    )?;
    if !staged.is_empty() {
        return Err(ZdevError::new(format!(
            "Cannot add and commit initial tasks: {relative_directory} has unexpectedly staged content"
        )));
    }

    let mut entries = fs::read_dir(directory)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", directory.display()), error))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| ZdevError::io(format!("Cannot read {}", directory.display()), error))?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let relative = format!("{relative_directory}/{name}");
        let file_type = entry.file_type().map_err(|error| {
            ZdevError::io(format!("Cannot inspect {}", entry.path().display()), error)
        })?;
        match name.as_ref() {
            "area.toml" | "brief.md" if file_type.is_file() => {
                paths.push(entry.path());
            }
            "TASKS.md" if file_type.is_file() => {}
            "tasks" if file_type.is_dir() => {
                if fs::read_dir(entry.path())
                    .map_err(|error| {
                        ZdevError::io(format!("Cannot read {}", entry.path().display()), error)
                    })?
                    .next()
                    .is_some()
                {
                    return Err(ZdevError::new(format!(
                        "Cannot add and commit initial tasks: {relative} must be empty before import"
                    )));
                }
            }
            "slices" if file_type.is_dir() => {
                let mut slices = fs::read_dir(entry.path())
                    .map_err(|error| {
                        ZdevError::io(format!("Cannot read {}", entry.path().display()), error)
                    })?
                    .collect::<Result<Vec<_>, _>>()
                    .map_err(|error| {
                        ZdevError::io(format!("Cannot read {}", entry.path().display()), error)
                    })?;
                slices.sort_by_key(|entry| entry.file_name());
                for slice in slices {
                    let slice_type = slice.file_type().map_err(|error| {
                        ZdevError::io(format!("Cannot inspect {}", slice.path().display()), error)
                    })?;
                    if !slice_type.is_file() || slice.path().extension() != Some(OsStr::new("md")) {
                        return Err(ZdevError::new(format!(
                            "Cannot add and commit initial tasks: {} is not a regular slice brief",
                            slice.path().display()
                        )));
                    }
                    paths.push(slice.path());
                }
            }
            _ => {
                return Err(ZdevError::new(format!(
                    "Cannot add and commit initial tasks: unexpected owning-area path {relative}"
                )));
            }
        }
    }
    for required in ["area.toml", "brief.md", "TASKS.md"] {
        if !directory.join(required).is_file() {
            return Err(ZdevError::new(format!(
                "Cannot add and commit initial tasks: missing {relative_directory}/{required}"
            )));
        }
    }
    Ok(())
}

fn relative_paths(root: &Path, paths: &[PathBuf]) -> Result<Vec<String>, ZdevError> {
    paths
        .iter()
        .map(|path| {
            path.strip_prefix(root)
                .map(|path| path.to_string_lossy().replace('\\', "/"))
                .map_err(|_| {
                    ZdevError::new(format!("Path is outside repository: {}", path.display()))
                })
        })
        .collect()
}

fn commit_task_import(
    root: &Path,
    area: &str,
    paths: &[PathBuf],
) -> Result<(String, String), ZdevError> {
    let relative = relative_paths(root, paths)?;
    let mut add = ProcessCommand::new("git");
    add.args(["add", "-f", "--"]);
    add.args(&relative);
    let output = add
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot stage imported task paths", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Could not stage the new task files. Resolve the Git error, then retry: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }

    let change_id = generate_change_id()?;
    let mut command = ProcessCommand::new("git");
    command
        .args(["commit", "--only", "-m"])
        .arg(format!("Add tasks to {area}"))
        .args(["-m", &format!("{CHANGE_ID_TRAILER}: {change_id}"), "--"])
        .args(&relative);
    let output = command
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot commit imported task paths", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Could not commit the new task files. Resolve the Git error, then retry: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    Ok((git_output(root, &["rev-parse", "HEAD"])?, change_id))
}

fn rollback_task_import_index(root: &Path, paths: &[PathBuf], error: ZdevError) -> ZdevError {
    let relative = match relative_paths(root, paths) {
        Ok(relative) => relative,
        Err(rollback) => {
            return ZdevError::new(format!(
                "{error}; cannot identify staged task paths during rollback: {rollback}"
            ));
        }
    };
    let mut reset = ProcessCommand::new("git");
    reset.args(["reset", "-q", "HEAD", "--"]).args(&relative);
    match reset
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
    {
        Ok(output) if output.status.success() => error,
        Ok(output) => ZdevError::new(format!(
            "{error}; cannot unstage imported task paths during rollback: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )),
        Err(rollback) => ZdevError::new(format!(
            "{error}; cannot run Git to unstage imported task paths during rollback: {rollback}"
        )),
    }
}

fn render_draft(header: &TaskHeader, draft: &TaskDraft) -> Result<String, ZdevError> {
    let context = draft
        .context
        .as_deref()
        .map_or_else(String::new, |context| {
            format!("\n\n## Context\n\n{}", context.trim())
        });
    let boundaries = if draft.boundaries.is_empty() {
        String::new()
    } else {
        format!(
            "\n\n## Boundaries\n\n{}",
            draft
                .boundaries
                .iter()
                .map(|item| format!("- {item}"))
                .collect::<Vec<_>>()
                .join("\n")
        )
    };
    let validation = if draft.validation.is_empty() {
        "- Let the verifier choose the smallest useful checks.".to_owned()
    } else {
        draft
            .validation
            .iter()
            .map(|item| format!("- {item}"))
            .collect::<Vec<_>>()
            .join("\n")
    };
    Ok(format!(
        "+++\n{}+++\n# {}\n\n## Outcome\n\n{}{}{}\n\n## Done when\n\n{}\n\n## Validation\n\n{}\n",
        toml::to_string(header)
            .map_err(|error| ZdevError::new(format!("Cannot render task: {error}")))?,
        draft.title,
        draft.outcome,
        context,
        boundaries,
        draft
            .done_when
            .iter()
            .map(|item| format!("- [ ] {item}"))
            .collect::<Vec<_>>()
            .join("\n"),
        validation,
    ))
}

fn load_tasks(root: &Path, area: &str) -> Result<Vec<Task>, ZdevError> {
    let tasks = read_area_tasks(root, area)?;
    validate_graph(root, area, &tasks)?;
    validate_research_tasks(&tasks, load_area(root, area)?.0.research.is_some())?;
    for task in &tasks {
        validate_code_prerequisites(&task.header.requires_code, &tasks)?;
    }
    Ok(tasks)
}

/// Parses one area's task files, sorted by ID, without validating its dependency
/// graph, so that graph validation can read the areas its blockers name.
fn read_area_tasks(root: &Path, area: &str) -> Result<Vec<Task>, ZdevError> {
    let (_, area_dir) = load_area(root, area)?;
    let tasks_dir = area_dir.join("tasks");
    if !tasks_dir.is_dir() {
        return Err(ZdevError::new(format!(
            "Area {area} has no tasks directory: {}",
            tasks_dir.display()
        )));
    }
    let mut tasks = Vec::new();
    for entry in fs::read_dir(&tasks_dir)
        .map_err(|error| ZdevError::io(format!("Cannot list {}", tasks_dir.display()), error))?
    {
        let entry = entry.map_err(|error| ZdevError::io("Cannot inspect task", error))?;
        let path = entry.path();
        if path.extension() != Some(OsStr::new("md")) {
            continue;
        }
        let content = fs::read_to_string(&path)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))?;
        tasks.push(parse_task(&content, &path, area)?);
    }
    validate_task_slices(root, area, &tasks)?;
    tasks.sort_by(compare_tasks_by_id);
    Ok(tasks)
}

fn parse_task(content: &str, path: &Path, area: &str) -> Result<Task, ZdevError> {
    let rest = content.strip_prefix("+++\n").ok_or_else(|| {
        ZdevError::new(format!("Task lacks TOML frontmatter: {}", path.display()))
    })?;
    let (frontmatter, body) = rest.split_once("+++\n").ok_or_else(|| {
        ZdevError::new(format!("Task has unclosed frontmatter: {}", path.display()))
    })?;
    let header: TaskHeader = toml::from_str(frontmatter)
        .map_err(|error| ZdevError::new(format!("Invalid task {}: {error}", path.display())))?;
    if header.schema_version != SCHEMA_VERSION || header.area != area {
        return Err(ZdevError::new(format!(
            "Task has invalid area or schema: {}",
            path.display()
        )));
    }
    validate_segment(&header.key, "Task key")?;
    if let Some(slice) = &header.slice {
        validate_segment(slice, "Slice key")?;
    }
    let expected_prefix = format!("{area}-");
    if !header.id.starts_with(&expected_prefix) || parse_number(&header.id).is_err() {
        return Err(ZdevError::new(format!("Invalid task ID: {}", header.id)));
    }
    let title = body
        .lines()
        .find_map(|line| line.strip_prefix("# "))
        .filter(|title| !title.trim().is_empty())
        .ok_or_else(|| ZdevError::new(format!("Task lacks a title: {}", path.display())))?
        .to_owned();
    validate_task_body(body, header.status, path)?;
    if let Some(hypothesis) = &header.hypothesis {
        hypothesis.validate()?;
        validate_evidence(
            &header.research_results,
            header.status == TaskStatus::Done,
            None,
        )?;
    } else if !header.research_results.is_empty() {
        return Err(ZdevError::new(
            "Ordinary tasks cannot contain research results",
        ));
    }
    Ok(Task {
        header,
        title,
        body: body.to_owned(),
        path: path.to_path_buf(),
    })
}

fn validate_code_prerequisites(ids: &[String], tasks: &[Task]) -> Result<(), ZdevError> {
    let mut seen = BTreeSet::new();
    for id in ids {
        if !seen.insert(id) {
            return Err(ZdevError::new(format!(
                "Duplicate retained-code prerequisite: {id}"
            )));
        }
        let task = find_task(tasks, id)?;
        let result = task
            .header
            .research_results
            .last()
            .filter(|result| {
                task.header.status == TaskStatus::Done
                    && result.decision == super::research::Decision::Accepted
                    && result
                        .verification
                        .as_ref()
                        .is_some_and(|verification| verification.passed)
            })
            .ok_or_else(|| {
                ZdevError::new(format!(
                    "Retained-code prerequisite {id} requires completed verified acceptance"
                ))
            })?;
        result
            .retained_candidate
            .as_deref()
            .ok_or_else(|| ZdevError::new("Missing retained candidate"))?;
    }
    Ok(())
}

fn require_retained_code(root: &Path, ids: &[String], tasks: &[Task]) -> Result<(), ZdevError> {
    validate_code_prerequisites(ids, tasks)?;
    for id in ids {
        let task = find_task(tasks, id)?;
        let result = task.header.research_results.last().unwrap();
        let retained = result.retained_candidate.as_deref().unwrap();
        let measured = task
            .header
            .research_results
            .iter()
            .flat_map(|record| &record.observations)
            .last()
            .map(|observation| observation.candidate_revision.as_str())
            .ok_or_else(|| ZdevError::new("Missing verified candidate revision"))?;
        let revision = match git_output(
            root,
            &["rev-parse", "--verify", &format!("{retained}^{{commit}}")],
        ) {
            Ok(revision) => revision,
            Err(_) => git_output(root, &["rev-parse", "--verify", &format!("{measured}^{{commit}}")])
                .map_err(|_| ZdevError::new(format!(
                    "Retained-code prerequisite {id} is unavailable locally. Fetch {retained} from the source clone before admitting this task"
                )))?,
        };
        if measured != revision {
            return Err(ZdevError::new(format!(
                "Retained-code prerequisite {id} does not resolve to its verified candidate"
            )));
        }
    }
    Ok(())
}

fn validate_research_tasks(tasks: &[Task], enabled: bool) -> Result<(), ZdevError> {
    for task in tasks {
        if let Some(hypothesis) = &task.header.hypothesis {
            if !enabled {
                return Err(ZdevError::new(
                    "Hypothesis tasks require research settings on their area",
                ));
            }
            for context in &hypothesis.context_tasks {
                if context == &task.header.id
                    || !tasks.iter().any(|task| &task.header.id == context)
                {
                    return Err(ZdevError::new(format!(
                        "Hypothesis {} has unknown or self context task {context}",
                        task.header.id
                    )));
                }
            }
        }
    }
    Ok(())
}

fn resolve_hypothesis(
    hypothesis: Option<&Hypothesis>,
    allocated: &BTreeMap<&str, String>,
) -> Option<Hypothesis> {
    hypothesis.map(|hypothesis| Hypothesis {
        mechanism: hypothesis.mechanism.clone(),
        context_tasks: hypothesis
            .context_tasks
            .iter()
            .map(|context| {
                allocated
                    .get(context.as_str())
                    .cloned()
                    .unwrap_or_else(|| context.clone())
            })
            .collect(),
    })
}

fn validate_task_slices(root: &Path, area: &str, tasks: &[Task]) -> Result<(), ZdevError> {
    let slices = slice_briefs(root, area)?;
    let keys = slices
        .iter()
        .map(|slice| slice.key.as_str())
        .collect::<BTreeSet<_>>();
    for task in tasks {
        if let Some(slice) = &task.header.slice
            && !keys.contains(slice.as_str())
        {
            return Err(ZdevError::new(format!(
                "Task {} references unknown slice {slice}: {}",
                task.header.id,
                task.path.display()
            )));
        }
    }
    Ok(())
}

fn markdown_section<'a>(
    body: &'a str,
    heading: &str,
    path: &Path,
) -> Result<Option<&'a str>, ZdevError> {
    let marker = format!("\n## {heading}\n");
    let matches = body.match_indices(&marker).collect::<Vec<_>>();
    let start = match matches.as_slice() {
        [] => return Ok(None),
        [(start, _)] => start + marker.len(),
        _ => {
            return Err(ZdevError::new(format!(
                "Task repeats ## {heading}: {}",
                path.display()
            )));
        }
    };
    let end = body[start..]
        .find("\n## ")
        .map_or(body.len(), |offset| start + offset);
    Ok(Some(body[start..end].trim()))
}

fn required_markdown_section<'a>(
    body: &'a str,
    heading: &str,
    path: &Path,
) -> Result<&'a str, ZdevError> {
    markdown_section(body, heading, path)?
        .ok_or_else(|| ZdevError::new(format!("Task lacks ## {heading}: {}", path.display())))
}

fn validate_bullet_section(section: &str, heading: &str, path: &Path) -> Result<(), ZdevError> {
    if section.is_empty()
        || section.lines().any(|line| {
            !line.trim().is_empty()
                && line
                    .strip_prefix("- ")
                    .is_none_or(|item| item.trim().is_empty())
        })
    {
        return Err(ZdevError::new(format!(
            "Task ## {heading} must contain a non-empty bullet list: {}",
            path.display()
        )));
    }
    Ok(())
}

fn validate_task_body(body: &str, status: TaskStatus, path: &Path) -> Result<(), ZdevError> {
    let outcome = required_markdown_section(body, "Outcome", path)?;
    if outcome.is_empty() {
        return Err(ZdevError::new(format!(
            "Task ## Outcome is empty: {}",
            path.display()
        )));
    }
    if let Some(boundaries) = markdown_section(body, "Boundaries", path)? {
        validate_bullet_section(boundaries, "Boundaries", path)?;
    }
    let done_when = required_markdown_section(body, "Done when", path)?;
    let conditions = done_when
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect::<Vec<_>>();
    if conditions.is_empty()
        || conditions.iter().any(|line| {
            ["- [ ] ", "- [x] ", "- [X] "]
                .iter()
                .find_map(|prefix| line.strip_prefix(prefix))
                .is_none_or(|item| item.trim().is_empty())
        })
    {
        return Err(ZdevError::new(format!(
            "Task ## Done when must contain only checklist items: {}",
            path.display()
        )));
    }
    if status == TaskStatus::Done && conditions.iter().any(|line| line.starts_with("- [ ] ")) {
        return Err(ZdevError::new(format!(
            "Done task has unchecked conditions: {}",
            path.display()
        )));
    }
    let validation = required_markdown_section(body, "Validation", path)?;
    validate_bullet_section(validation, "Validation", path)?;
    if status == TaskStatus::Done {
        let result = required_markdown_section(body, "Result", path)?;
        if result.is_empty() {
            return Err(ZdevError::new(format!(
                "Done task has an empty ## Result: {}",
                path.display()
            )));
        }
    }
    Ok(())
}

fn replace_markdown_section(
    body: &str,
    heading: &str,
    path: &Path,
    replace: impl FnOnce(&str) -> String,
) -> Result<String, ZdevError> {
    let marker = format!("\n## {heading}\n");
    let start = body
        .find(&marker)
        .ok_or_else(|| ZdevError::new(format!("Task lacks ## {heading}: {}", path.display())))?
        + marker.len();
    let end = body[start..]
        .find("\n## ")
        .map_or(body.len(), |offset| start + offset);
    let mut updated = String::with_capacity(body.len());
    updated.push_str(&body[..start]);
    updated.push_str(&replace(&body[start..end]));
    updated.push_str(&body[end..]);
    Ok(updated)
}

fn parse_number(id: &str) -> Result<u64, ZdevError> {
    id.rsplit_once('-')
        .and_then(|(_, number)| number.parse().ok())
        .ok_or_else(|| ZdevError::new(format!("Task ID has no numeric suffix: {id}")))
}

fn compare_tasks_by_id(left: &Task, right: &Task) -> std::cmp::Ordering {
    parse_number(&left.header.id)
        .expect("task IDs are validated before sorting")
        .cmp(&parse_number(&right.header.id).expect("task IDs are validated before sorting"))
        .then_with(|| left.header.id.cmp(&right.header.id))
}

/// Validates one area's tasks as part of the project graph: every blocker names a
/// task in this area or another, and no dependency cycle passes through the area,
/// including cycles through the other areas its blockers reach.
fn validate_graph(root: &Path, area: &str, tasks: &[Task]) -> Result<(), ZdevError> {
    let ids = tasks
        .iter()
        .map(|task| task.header.id.as_str())
        .collect::<BTreeSet<_>>();
    if ids.len() != tasks.len() {
        return Err(ZdevError::new("Task IDs must be unique"));
    }
    let keys = tasks
        .iter()
        .map(|task| task.header.key.as_str())
        .collect::<BTreeSet<_>>();
    if keys.len() != tasks.len() {
        return Err(ZdevError::new("Task keys must be unique"));
    }
    let blocking_tasks = read_blocking_area_tasks(root, area, tasks)?;
    let by_id = blocking_tasks
        .iter()
        .chain(tasks)
        .map(|task| (task.header.id.as_str(), task))
        .collect::<BTreeMap<_, _>>();
    for task in tasks {
        let mut seen = BTreeSet::new();
        for blocker in &task.header.blocked_by {
            if blocker == &task.header.id || !seen.insert(blocker) {
                return Err(ZdevError::new(format!(
                    "Invalid blocker on {}",
                    task.header.id
                )));
            }
            if !by_id.contains_key(blocker.as_str()) {
                return Err(ZdevError::new(format!(
                    "Task {} has missing blocker {blocker}{}",
                    task.header.id,
                    missing_blocker_detail(root, area, blocker)?
                )));
            }
        }
    }
    if let Some(cycle) = find_cycle(tasks, &by_id) {
        return Err(ZdevError::new(format!(
            "Task dependency cycle: {} (each task is blocked by the next)",
            cycle.join(" -> ")
        )));
    }
    Ok(())
}

/// Tasks of the other areas reached from `tasks` through `blocked_by`, read without
/// validating those areas' own graphs. Blockers in absent areas reach nothing.
fn read_blocking_area_tasks(
    root: &Path,
    area: &str,
    tasks: &[Task],
) -> Result<Vec<Task>, ZdevError> {
    let mut reached = BTreeSet::from([area.to_owned()]);
    let mut pending = blocker_areas(tasks);
    let mut blocking_tasks = Vec::new();
    while let Some(next) = pending.pop() {
        if !reached.insert(next.clone()) || !area_has_tasks(root, &next) {
            continue;
        }
        let area_tasks = read_area_tasks(root, &next)?;
        pending.extend(blocker_areas(&area_tasks));
        blocking_tasks.extend(area_tasks);
    }
    Ok(blocking_tasks)
}

/// One area's parsed tasks.
struct AreaTasks {
    tag: String,
    tasks: Vec<Task>,
}

/// The other areas in the checkout with a task whose `blocked_by` names `id`, in
/// area-tag order, read without validating their graphs. This is the inverse of
/// [`read_blocking_area_tasks`]: these areas' readiness and `TASKS.md` show the
/// status of `id`.
fn read_dependent_areas(root: &Path, area: &str, id: &str) -> Result<Vec<AreaTasks>, ZdevError> {
    let mut dependents = Vec::new();
    for metadata in list_areas(root)? {
        if metadata.tag == area || !area_has_tasks(root, &metadata.tag) {
            continue;
        }
        let tasks = read_area_tasks(root, &metadata.tag)?;
        if tasks.iter().any(|task| is_blocked_by(task, id)) {
            dependents.push(AreaTasks {
                tag: metadata.tag,
                tasks,
            });
        }
    }
    Ok(dependents)
}

/// The tags of the other areas in the checkout with a task whose `blocked_by`
/// names `id`, in area-tag order.
pub(super) fn dependent_areas(root: &Path, area: &str, id: &str) -> Result<Vec<String>, ZdevError> {
    Ok(read_dependent_areas(root, area, id)?
        .into_iter()
        .map(|dependent| dependent.tag)
        .collect())
}

fn is_blocked_by(task: &Task, id: &str) -> bool {
    task.header.blocked_by.iter().any(|blocker| blocker == id)
}

/// Whether `task` is done and lists `id` as a blocker, which keeps `id` from being
/// reopened.
fn is_completed_dependent(task: &Task, id: &str) -> bool {
    task.header.status == TaskStatus::Done && is_blocked_by(task, id)
}

/// Renders the `TASKS.md` of each area in the checkout that depends on `id`, a
/// task in `area`, as it reads once `id` has `status`. Only direct dependents
/// change: an index shows the status of its tasks' own blockers.
fn render_dependent_indexes(
    root: &Path,
    area: &str,
    id: &str,
    status: TaskStatus,
) -> Result<Vec<(PathBuf, Vec<u8>)>, ZdevError> {
    read_dependent_areas(root, area, id)?
        .into_iter()
        .map(|dependent| {
            validate_graph(root, &dependent.tag, &dependent.tasks)?;
            let statuses =
                read_task_statuses(root, &dependent.tag, &dependent.tasks)?.with_status(id, status);
            let index = render_index(&dependent.tag, &dependent.tasks, &statuses);
            let path = root.join(".zdev").join(&dependent.tag).join("TASKS.md");
            Ok((path, index.into_bytes()))
        })
        .collect()
}

fn blocker_areas(tasks: &[Task]) -> Vec<String> {
    tasks
        .iter()
        .flat_map(|task| &task.header.blocked_by)
        .filter_map(|blocker| task_id_area(blocker))
        .map(str::to_owned)
        .collect()
}

/// The area a task ID belongs to: everything before its last `-` when the rest
/// is a number. Area tags may themselves contain hyphens.
fn task_id_area(id: &str) -> Option<&str> {
    let (area, number) = id.rsplit_once('-')?;
    let is_number = !number.is_empty() && number.bytes().all(|byte| byte.is_ascii_digit());
    (is_number && validate_segment(area, "Area tag").is_ok()).then_some(area)
}

fn area_exists(root: &Path, area: &str) -> bool {
    root.join(".zdev").join(area).join("area.toml").is_file()
}

fn area_has_tasks(root: &Path, area: &str) -> bool {
    area_exists(root, area) && root.join(".zdev").join(area).join("tasks").is_dir()
}

/// Whether `id` names an existing task in an area other than `area`.
fn task_exists_in_other_area(root: &Path, area: &str, id: &str) -> Result<bool, ZdevError> {
    let Some(blocker_area) = task_id_area(id) else {
        return Ok(false);
    };
    if blocker_area == area || !area_has_tasks(root, blocker_area) {
        return Ok(false);
    }
    Ok(read_area_tasks(root, blocker_area)?
        .iter()
        .any(|task| task.header.id == id))
}

/// The error for a bundle task whose blocker is neither a bundle key nor an
/// existing task ID.
fn unknown_blocker_error(root: &Path, area: &str, key: &str, blocker: &str) -> ZdevError {
    match missing_blocker_detail(root, area, blocker) {
        Ok(detail) => ZdevError::new(format!("Task {key} has unknown blocker {blocker}{detail}")),
        Err(error) => error,
    }
}

/// Explains, for an error message, where a blocker that names no task was
/// expected. A dependent in an isolated area may predate a blocker created on
/// trunk, so its message also suggests rebasing the area.
fn missing_blocker_detail(root: &Path, area: &str, blocker: &str) -> Result<String, ZdevError> {
    let Some(blocker_area) = task_id_area(blocker) else {
        return Ok(" (not a task ID)".to_owned());
    };
    let mut detail = if area_exists(root, blocker_area) {
        format!(" (expected in area {blocker_area})")
    } else {
        format!(" (expected area {blocker_area} does not exist)")
    };
    if blocker_area != area && load_area(root, area)?.0.mode == AreaMode::Isolated {
        detail.push_str(&format!(
            "; if it was created after area {area} branched, run `zdev area rebase {area}`"
        ));
    }
    Ok(detail)
}

/// The first dependency cycle reachable from `starts`, as task IDs from a task
/// through its blockers back to itself. Blockers absent from `by_id` end a path.
fn find_cycle<'a>(starts: &'a [Task], by_id: &BTreeMap<&'a str, &'a Task>) -> Option<Vec<&'a str>> {
    fn visit<'a>(
        id: &'a str,
        by_id: &BTreeMap<&'a str, &'a Task>,
        path: &mut Vec<&'a str>,
        visited: &mut BTreeSet<&'a str>,
    ) -> Option<Vec<&'a str>> {
        if let Some(start) = path.iter().position(|step| *step == id) {
            let mut cycle = path[start..].to_vec();
            cycle.push(id);
            return Some(cycle);
        }
        if visited.contains(id) {
            return None;
        }
        let task = by_id.get(id)?;
        path.push(id);
        for blocker in &task.header.blocked_by {
            if let Some(cycle) = visit(blocker, by_id, path, visited) {
                return Some(cycle);
            }
        }
        path.pop();
        visited.insert(id);
        None
    }
    let mut path = Vec::new();
    let mut visited = BTreeSet::new();
    starts
        .iter()
        .find_map(|task| visit(&task.header.id, by_id, &mut path, &mut visited))
}

/// The recorded status of every task that readiness in one area depends on: the
/// area's own tasks and the tasks of each other area its blockers name, as read
/// from the current checkout. Every readiness decision goes through it, so a
/// cross-area blocker counts as done exactly when its task file here says so.
#[derive(Default)]
struct TaskStatuses(BTreeMap<String, TaskStatus>);

impl TaskStatuses {
    fn status(&self, id: &str) -> Option<TaskStatus> {
        self.0.get(id).copied()
    }

    /// These statuses with `id` given `status`, for rendering before a status
    /// change is written.
    fn with_status(mut self, id: &str, status: TaskStatus) -> Self {
        self.0.insert(id.to_owned(), status);
        self
    }
}

/// Reads the statuses that readiness of `tasks`, the current or prospective tasks
/// of `area`, depends on. A blocker that names no task in the checkout has no
/// status and keeps its dependent blocked.
fn read_task_statuses(root: &Path, area: &str, tasks: &[Task]) -> Result<TaskStatuses, ZdevError> {
    let mut statuses = BTreeMap::new();
    let blocking_areas = blocker_areas(tasks)
        .into_iter()
        .filter(|blocker_area| blocker_area != area)
        .collect::<BTreeSet<_>>();
    for blocking_area in blocking_areas {
        if !area_has_tasks(root, &blocking_area) {
            continue;
        }
        for task in read_area_tasks(root, &blocking_area)? {
            statuses.insert(task.header.id, task.header.status);
        }
    }
    for task in tasks {
        statuses.insert(task.header.id.clone(), task.header.status);
    }
    Ok(TaskStatuses(statuses))
}

/// How a blocker of a task in `area` is shown: a same-area blocker by its ID, and
/// a blocker in another area also with that area and its status, such as
/// `platform-009 (platform: open)`.
fn blocker_label(area: &str, blocker: &str, statuses: &TaskStatuses) -> String {
    CrossAreaBlocker::of(area, blocker, statuses)
        .map_or_else(|| blocker.to_owned(), |cross_area| cross_area.label())
}

/// A blocker of a task in one area that names a task in another area, with that
/// task's status in the current checkout: `open`, `done`, or `missing`.
#[derive(Clone, Serialize)]
pub(super) struct CrossAreaBlocker {
    id: String,
    area: String,
    status: &'static str,
}

impl CrossAreaBlocker {
    /// `blocker` as a cross-area blocker of a task in `area`, or `None` when it
    /// names a task in `area` itself.
    fn of(area: &str, blocker: &str, statuses: &TaskStatuses) -> Option<Self> {
        let blocker_area = task_id_area(blocker).filter(|blocker_area| *blocker_area != area)?;
        Some(Self {
            id: blocker.to_owned(),
            area: blocker_area.to_owned(),
            status: statuses
                .status(blocker)
                .map_or("missing", TaskStatus::as_str),
        })
    }

    /// The blocker as `platform-009 (platform: open)`.
    fn label(&self) -> String {
        format!("{} ({}: {})", self.id, self.area, self.status)
    }
}

/// The cross-area blockers of `task`, a task in `area`, that are not done yet.
fn pending_cross_area_blockers(
    area: &str,
    task: &Task,
    statuses: &TaskStatuses,
) -> Vec<CrossAreaBlocker> {
    if task.header.status == TaskStatus::Done {
        return Vec::new();
    }
    task.header
        .blocked_by
        .iter()
        .filter(|blocker| statuses.status(blocker) != Some(TaskStatus::Done))
        .filter_map(|blocker| CrossAreaBlocker::of(area, blocker, statuses))
        .collect()
}

/// `  blocked by platform-009 (platform: open), ...` for a task waiting on other
/// areas, or nothing.
fn pending_blockers_annotation(blockers: &[CrossAreaBlocker]) -> String {
    if blockers.is_empty() {
        return String::new();
    }
    let labels = blockers
        .iter()
        .map(CrossAreaBlocker::label)
        .collect::<Vec<_>>();
    format!("  blocked by {}", labels.join(", "))
}

/// An open task waiting on a blocker in another area that is not done.
#[derive(Clone, Serialize)]
pub(super) struct CrossAreaWait {
    task: String,
    blocker: CrossAreaBlocker,
}

impl std::fmt::Display for CrossAreaWait {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            formatter,
            "{} blocked by {}",
            self.task,
            self.blocker.label()
        )
    }
}

/// Every wait of an open task in `area` on another area, in task and authored
/// blocker order.
fn cross_area_waits(area: &str, tasks: &[Task], statuses: &TaskStatuses) -> Vec<CrossAreaWait> {
    tasks
        .iter()
        .flat_map(|task| {
            pending_cross_area_blockers(area, task, statuses)
                .into_iter()
                .map(|blocker| CrossAreaWait {
                    task: task.header.id.clone(),
                    blocker,
                })
        })
        .collect()
}

/// Adds `waits` to a JSON object as `cross_area_waits` when there are any,
/// leaving projections of areas without cross-area waits unchanged.
pub(super) fn insert_cross_area_waits(value: &mut Value, waits: &[CrossAreaWait]) {
    if waits.is_empty() {
        return;
    }
    value
        .as_object_mut()
        .expect("command projections are JSON objects")
        .insert("cross_area_waits".to_owned(), json!(waits));
}

/// The waits as indented lines, one per blocker, for command text.
pub(super) fn render_cross_area_waits(waits: &[CrossAreaWait]) -> String {
    waits.iter().map(|wait| format!("\n  {wait}")).collect()
}

/// An open task in another area that lists an open task of the area being
/// closed as a blocker.
pub(super) struct WaitingDependent {
    blocker: String,
    task: String,
    area: String,
}

impl std::fmt::Display for WaitingDependent {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            formatter,
            "{} blocks {} ({})",
            self.blocker, self.task, self.area
        )
    }
}

/// The open tasks of other areas that wait on an open task of `area`, in area
/// and task order.
pub(super) fn read_waiting_dependents(
    root: &Path,
    area: &str,
) -> Result<Vec<WaitingDependent>, ZdevError> {
    let open_tasks = read_area_tasks(root, area)?
        .into_iter()
        .filter(|task| task.header.status == TaskStatus::Open)
        .map(|task| task.header.id)
        .collect::<BTreeSet<_>>();
    let mut dependents = Vec::new();
    for metadata in list_areas(root)? {
        if metadata.tag == area || !area_has_tasks(root, &metadata.tag) {
            continue;
        }
        for task in read_area_tasks(root, &metadata.tag)? {
            if task.header.status != TaskStatus::Open {
                continue;
            }
            for blocker in task
                .header
                .blocked_by
                .iter()
                .filter(|id| open_tasks.contains(*id))
            {
                dependents.push(WaitingDependent {
                    blocker: blocker.clone(),
                    task: task.header.id.clone(),
                    area: metadata.tag.clone(),
                });
            }
        }
    }
    Ok(dependents)
}

fn task_state(task: &Task, statuses: &TaskStatuses) -> &'static str {
    if task.header.status == TaskStatus::Done {
        return "done";
    }
    if task
        .header
        .blocked_by
        .iter()
        .all(|id| statuses.status(id) == Some(TaskStatus::Done))
    {
        "ready"
    } else {
        "blocked"
    }
}

fn views<'a>(
    root: &Path,
    area: &str,
    tasks: &'a [Task],
    statuses: &TaskStatuses,
) -> Vec<TaskView<'a>> {
    tasks
        .iter()
        .map(|task| TaskView {
            id: &task.header.id,
            title: &task.title,
            status: task.header.status.as_str(),
            state: task_state(task, statuses),
            complexity: task.complexity(),
            afk: task.header.afk,
            priority: task.priority(),
            blocked_by: &task.header.blocked_by,
            cross_area_blockers: pending_cross_area_blockers(area, task, statuses),
            requires_code: &task.header.requires_code,
            slice: task.header.slice.as_deref(),
            slice_brief: task_slice_brief_path(root, task),
            path: relative(root, &task.path),
            hypothesis: task.header.hypothesis.as_ref(),
            research_results: &task.header.research_results,
        })
        .collect()
}

pub(super) fn list(root: &Path, area: Option<&str>) -> Result<CommandOutput, ZdevError> {
    let Some(area) = area else {
        return list_area_summary(root);
    };
    let tasks = load_tasks(root, area)?;
    let task_views = views(root, area, &tasks, &read_task_statuses(root, area, &tasks)?);
    let text = if task_views.is_empty() {
        format!("No tasks in {area}")
    } else {
        task_views
            .iter()
            .map(|task| {
                let slice = task
                    .slice
                    .map(|slice| format!("  slice:{slice}"))
                    .unwrap_or_default();
                format!(
                    "{}  {:7}  {}  complexity:{}{slice}",
                    task.id,
                    task.state,
                    task.title,
                    task.complexity.as_str()
                ) + if task.hypothesis.is_some() {
                    "  hypothesis"
                } else {
                    ""
                } + &pending_blockers_annotation(&task.cross_area_blockers)
            })
            .collect::<Vec<_>>()
            .join("\n")
    };
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "area": area, "tasks": task_views}),
    ))
}

fn list_area_summary(root: &Path) -> Result<CommandOutput, ZdevError> {
    let mut areas = list_areas(root)?
        .into_iter()
        .map(|area| {
            let open_tasks = load_tasks(root, &area.tag)?
                .iter()
                .filter(|task| task.header.status == TaskStatus::Open)
                .count();
            Ok((area, open_tasks))
        })
        .collect::<Result<Vec<_>, ZdevError>>()?;
    areas.sort_by(|(left, _), (right, _)| {
        (left.lifecycle == AreaLifecycle::Closed)
            .cmp(&(right.lifecycle == AreaLifecycle::Closed))
            .then_with(|| left.tag.cmp(&right.tag))
    });

    let guidance = areas
        .iter()
        .map(|(area, open_tasks)| {
            let noun = if *open_tasks == 1 { "task" } else { "tasks" };
            let closed = if area.lifecycle == AreaLifecycle::Closed {
                "  closed"
            } else {
                ""
            };
            format!("{}  {} open {noun}{closed}", area.tag, open_tasks)
        })
        .collect::<Vec<_>>()
        .join("\n");
    let areas = areas
        .iter()
        .map(|(area, open_tasks)| {
            json!({
                "area": area.tag,
                "lifecycle": area.lifecycle.as_str(),
                "open_tasks": open_tasks,
            })
        })
        .collect::<Vec<_>>();
    let message = if guidance.is_empty() {
        "No areas are available".to_owned()
    } else {
        format!("Available areas:\n{guidance}")
    };
    Ok(CommandOutput::new(
        message,
        json!({"schema_version": SCHEMA_VERSION, "areas": areas}),
    ))
}

fn next_task<'a>(tasks: &'a [Task], statuses: &TaskStatuses) -> Option<&'a Task> {
    tasks
        .iter()
        .filter(|task| task_state(task, statuses) == "ready")
        .min_by(|left, right| {
            (!left.header.afk)
                .cmp(&!right.header.afk)
                .then_with(|| left.priority().rank().cmp(&right.priority().rank()))
                .then_with(|| compare_tasks_by_id(left, right))
        })
}

#[derive(Clone, Copy, Debug, Serialize)]
#[serde(rename_all = "lowercase")]
pub(super) enum QueueState {
    Empty,
    Ready,
    Blocked,
    Exhausted,
}

impl QueueState {
    pub(super) fn as_str(self) -> &'static str {
        match self {
            Self::Empty => "empty",
            Self::Ready => "ready",
            Self::Blocked => "blocked",
            Self::Exhausted => "exhausted",
        }
    }
}

fn select_area(root: &Path, requested: Option<&str>) -> Result<String, ZdevError> {
    if let Some(area) = requested {
        load_area(root, area)?;
        return Ok(area.to_owned());
    }
    let config = read_config(root)?;
    if let Some(area) = config.project.default_area {
        load_area(root, &area)?;
        return Ok(area);
    }
    let mut active = Vec::new();
    for area in list_areas(root)? {
        if area.lifecycle == AreaLifecycle::Open {
            active.push(area.tag);
        }
    }
    match active.as_slice() {
        [only] => Ok(only.clone()),
        [] => Err(ZdevError::new(
            "No area is open. Run `zdev area reopen <area>` before selecting work",
        )),
        _ => Err(ZdevError::new(format!(
            "Specify an area with `zdev next <area>`. Open areas: {}",
            active.join(", ")
        ))),
    }
}

pub(super) fn next(root: &Path, requested: Option<&str>) -> Result<CommandOutput, ZdevError> {
    let area = select_area(root, requested)?;
    let metadata = load_area(root, &area)?.0;
    if metadata.lifecycle == AreaLifecycle::Closed {
        validate_brief(&root.join(".zdev").join(&area).join("brief.md"))?;
        super::project::validate_area_relationships(root, &list_areas(root)?)?;
        super::project::validate_slices(root, &area)?;
        validate_index(root, &area)?;
        let summary = summary(root, &area)?;
        validate_area_lifecycle(&metadata, &summary)?;
        let queue = summary.queue().as_str();
        return Ok(CommandOutput::new(
            format!(
                "Area {area} is closed. Run `zdev area reopen {area}` before adding or selecting work"
            ),
            json!({"schema_version": SCHEMA_VERSION, "area": area, "lifecycle": "closed", "queue": queue, "task": Value::Null}),
        ));
    }
    let branch = require_task_work_area_link(root, &area)?;
    let tasks = load_tasks(root, &area)?;
    let Some(task) = next_task(&tasks, &read_task_statuses(root, &area, &tasks)?) else {
        let summary = summary(root, &area)?;
        validate_area_lifecycle(&metadata, &summary)?;
        let queue = summary.queue();
        let mut text = match queue {
            QueueState::Empty => format!(
                "No tasks are recorded in open area {area}. Add approved tasks or run `zdev area close {area}`"
            ),
            QueueState::Exhausted => format!(
                "The task queue is exhausted in open area {area}. Add approved tasks, reopen a task, or run `zdev area close {area}`"
            ),
            QueueState::Blocked => format!(
                "Every open task in area {area} waits on another area. Work here becomes ready when these blockers are done:{}",
                render_cross_area_waits(&summary.cross_area_waits)
            ),
            QueueState::Ready => {
                return Err(ZdevError::new(
                    "Area summary has a ready task that selection did not find",
                ));
            }
        };
        if let Some(advisory) = &branch.advisory {
            text.push('\n');
            text.push_str(advisory);
        }
        let mut value = json!({"schema_version": SCHEMA_VERSION, "area": area, "mode": metadata.mode.as_str(), "branch": branch.branch_status["branch"], "branch_matches": branch.branch_status["branch_matches"], "lifecycle": "open", "queue": queue.as_str(), "task": Value::Null, "branch_status": branch.branch_status, "advisory": branch.advisory});
        insert_cross_area_waits(&mut value, &summary.cross_area_waits);
        return Ok(CommandOutput::new(text, value));
    };
    require_retained_code(root, &task.header.requires_code, &tasks)?;
    let view = TaskView {
        id: &task.header.id,
        title: &task.title,
        status: task.header.status.as_str(),
        state: "ready",
        complexity: task.complexity(),
        afk: task.header.afk,
        priority: task.priority(),
        blocked_by: &task.header.blocked_by,
        cross_area_blockers: Vec::new(),
        requires_code: &task.header.requires_code,
        slice: task.header.slice.as_deref(),
        slice_brief: task_slice_brief_path(root, task),
        path: relative(root, &task.path),
        hypothesis: task.header.hypothesis.as_ref(),
        research_results: &task.header.research_results,
    };
    let mut text = format!(
        "Area: {area}\nLifecycle: open\nQueue: ready\n\n{}  {}\nComplexity: {}\n{}",
        task.header.id,
        task.title,
        task.complexity().as_str(),
        task.path.display()
    );
    if task.header.hypothesis.is_some() {
        text.push_str("\nKind: hypothesis (use an explicitly authorized Codex or Claude Code research run, or the local experiment commands)");
    }
    if let (Some(slice), Some(path)) = (&task.header.slice, &view.slice_brief) {
        text.push_str(&format!("\nSlice: {slice}\nSlice brief: {path}"));
    }
    if let Some(advisory) = &branch.advisory {
        text.push('\n');
        text.push_str(advisory);
    }
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "area": area, "mode": metadata.mode.as_str(), "branch": branch.branch_status["branch"], "branch_matches": branch.branch_status["branch_matches"], "lifecycle": "open", "queue": "ready", "task": view, "branch_status": branch.branch_status, "advisory": branch.advisory}),
    ))
}

pub(super) fn next_any(root: &Path) -> Result<CommandOutput, ZdevError> {
    let config = read_config(root)?;
    let areas = list_areas(root)?;
    super::project::validate_area_relationships(root, &areas)?;
    let by_tag = areas
        .iter()
        .map(|area| (area.tag.as_str(), area))
        .collect::<BTreeMap<_, _>>();
    let mut candidates = Vec::new();
    let mut skipped = Vec::new();
    let mut waiting_areas = Vec::new();
    let mut unsafe_open_work = false;
    let closed_areas = areas
        .iter()
        .filter(|area| area.lifecycle == AreaLifecycle::Closed)
        .map(|area| area.tag.clone())
        .collect::<Vec<_>>();
    let checked_out = if closed_areas.len() == areas.len() {
        None
    } else {
        current_branch(root)?
    };

    for area in &areas {
        if area.lifecycle == AreaLifecycle::Closed {
            let summary = summary(root, &area.tag)?;
            validate_area_lifecycle(area, &summary)?;
            continue;
        }
        let tasks = load_tasks(root, &area.tag)?;
        let branch_status =
            area_branch_status(root, &config, area, &by_tag, checked_out.as_deref());
        let structurally_safe = branch_status["task_work"]["structurally_safe"]
            .as_bool()
            .unwrap_or(false);
        let open = tasks
            .iter()
            .any(|task| task.header.status == TaskStatus::Open);

        if !structurally_safe {
            unsafe_open_work |= open;
            skipped.push(json!({
                "area": area.tag,
                "branch": branch_status["branch"],
                "area_mode": area.mode.as_str(),
                "branch_matches": branch_status["branch_matches"],
                "diagnostics": branch_status["diagnostics"],
                "branch_status": branch_status,
            }));
            continue;
        }

        let statuses = read_task_statuses(root, &area.tag, &tasks)?;
        if let Some(task) = next_task(&tasks, &statuses) {
            candidates.push((area, task.clone(), branch_status));
            continue;
        }
        let waits = cross_area_waits(&area.tag, &tasks, &statuses);
        if !waits.is_empty() {
            waiting_areas.push(WaitingArea {
                area: area.tag.clone(),
                cross_area_waits: waits,
            });
        }
    }

    candidates.sort_by(|left, right| {
        let left_matches = left.2["branch_matches"] == Value::Bool(true);
        let right_matches = right.2["branch_matches"] == Value::Bool(true);
        right_matches
            .cmp(&left_matches)
            .then_with(|| left.0.tag.cmp(&right.0.tag))
    });

    let Some((area, task, branch_status)) = candidates.into_iter().next() else {
        let selection = if unsafe_open_work { "unsafe" } else { "none" };
        let mut text = match selection {
            "unsafe" => format!(
                "No safe task is ready. Unsafe areas: {}",
                skipped_areas_text(&skipped)
            ),
            _ if closed_areas.len() == areas.len() => {
                "No area is open. Run `zdev area reopen <area>` before selecting work".to_owned()
            }
            _ => "No open area has ready work. Open task queues are empty or exhausted".to_owned(),
        };
        append_waiting_areas(&mut text, &waiting_areas);
        append_closed_areas(&mut text, &closed_areas);
        let reason = if selection == "none" {
            Some(if closed_areas.len() == areas.len() {
                "no-open-area"
            } else {
                "no-ready-open-area"
            })
        } else {
            None
        };
        let mut value = if let Some(reason) = reason {
            json!({
                "schema_version": SCHEMA_VERSION,
                "mode": "any",
                "selection": selection,
                "reason": reason,
                "task": Value::Null,
                "skipped": skipped,
                "closed_areas": closed_areas,
            })
        } else {
            json!({
                "schema_version": SCHEMA_VERSION,
                "mode": "any",
                "selection": selection,
                "task": Value::Null,
                "skipped": skipped,
                "closed_areas": closed_areas,
            })
        };
        if !waiting_areas.is_empty() {
            value["waiting_areas"] = json!(waiting_areas);
        }
        return Ok(CommandOutput::new(text, value));
    };
    require_task_code(root, &area.tag, &task.header.id)?;

    let branch_matches = branch_status["branch_matches"] == Value::Bool(true);
    let required_branch = branch_status["branch"].as_str().unwrap_or("unbound");
    let branch_note = if branch_matches {
        " (checked out)".to_owned()
    } else if let Some(checked_out) = &checked_out {
        format!(" (not checked out; current branch: {checked_out})")
    } else {
        " (not checked out; HEAD is detached)".to_owned()
    };
    let view = TaskView {
        id: &task.header.id,
        title: &task.title,
        status: task.header.status.as_str(),
        state: "ready",
        complexity: task.complexity(),
        afk: task.header.afk,
        priority: task.priority(),
        blocked_by: &task.header.blocked_by,
        cross_area_blockers: Vec::new(),
        requires_code: &task.header.requires_code,
        slice: task.header.slice.as_deref(),
        slice_brief: task_slice_brief_path(root, &task),
        path: relative(root, &task.path),
        hypothesis: task.header.hypothesis.as_ref(),
        research_results: &task.header.research_results,
    };
    let mut text = format!(
        "Selection: ready\n\n{}  {}\nComplexity: {}\nArea: {}\nRequired branch: {}{}\nTask: {}",
        task.header.id,
        task.title,
        task.complexity().as_str(),
        area.tag,
        required_branch,
        branch_note,
        view.path
    );
    if task.header.hypothesis.is_some() {
        text.push_str("\nKind: hypothesis (use an explicitly authorized Codex or Claude Code research run, or the local experiment commands)");
    }
    if let (Some(slice), Some(path)) = (&task.header.slice, &view.slice_brief) {
        text.push_str(&format!("\nSlice: {slice}\nSlice brief: {path}"));
    }
    if !skipped.is_empty() {
        text.push_str(&format!(
            "\nSkipped unsafe areas: {}",
            skipped_areas_text(&skipped)
        ));
    }
    append_closed_areas(&mut text, &closed_areas);
    Ok(CommandOutput::new(
        text,
        json!({
            "schema_version": SCHEMA_VERSION,
            "mode": "any",
            "selection": "ready",
            "area": area.tag,
            "area_mode": area.mode.as_str(),
            "lifecycle": "open",
            "queue": "ready",
            "branch": branch_status["branch"],
            "branch_matches": branch_matches,
            "task": view,
            "branch_status": branch_status,
            "skipped": skipped,
            "closed_areas": closed_areas,
        }),
    ))
}

/// A safe open area whose open tasks all wait, directly or through its own
/// tasks, on other areas.
#[derive(Serialize)]
struct WaitingArea {
    area: String,
    cross_area_waits: Vec<CrossAreaWait>,
}

fn append_waiting_areas(text: &mut String, areas: &[WaitingArea]) {
    if areas.is_empty() {
        return;
    }
    text.push_str("\nWaiting on other areas:");
    for area in areas {
        for wait in &area.cross_area_waits {
            text.push_str(&format!("\n  {}: {wait}", area.area));
        }
    }
}

fn append_closed_areas(text: &mut String, closed_areas: &[String]) {
    if !closed_areas.is_empty() {
        text.push_str("\nExcluded closed areas: ");
        text.push_str(&closed_areas.join(", "));
    }
}

fn skipped_areas_text(skipped: &[Value]) -> String {
    skipped
        .iter()
        .map(|area| {
            let tag = area["area"].as_str().unwrap_or("unknown");
            let diagnostics = area["diagnostics"]
                .as_array()
                .map(|items| {
                    items
                        .iter()
                        .filter_map(Value::as_str)
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .unwrap_or_default();
            format!("{tag} [{diagnostics}]")
        })
        .collect::<Vec<_>>()
        .join("; ")
}

pub(super) fn show(root: &Path, area: &str, id: &str) -> Result<CommandOutput, ZdevError> {
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    let content = fs::read_to_string(&task.path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", task.path.display()), error))?;
    let slice_brief = task_slice_brief_path(root, task);
    let text = match (&task.header.slice, &slice_brief) {
        (Some(slice), Some(path)) => format!(
            "Complexity: {}\nSlice: {slice}\nSlice brief: {path}\n\n{content}",
            task.complexity().as_str()
        ),
        _ => format!("Complexity: {}\n\n{content}", task.complexity().as_str()),
    };
    let mut value = json!({
        "schema_version": SCHEMA_VERSION,
        "area": area,
        "id": task.header.id,
        "title": task.title,
        "status": task.header.status.as_str(),
        "state": task_state(task, &read_task_statuses(root, area, &tasks)?),
        "complexity": task.complexity(),
        "afk": task.header.afk,
        "priority": task.priority(),
        "blocked_by": task.header.blocked_by,
        "requires_code": task.header.requires_code,
        "slice": task.header.slice,
        "slice_brief": slice_brief,
        "path": relative(root, &task.path),
        "body": task.body,
    });
    if let Some(hypothesis) = &task.header.hypothesis {
        value["hypothesis"] = json!(hypothesis);
        value["research_results"] = json!(task.header.research_results);
    }
    Ok(CommandOutput::new(text, value))
}

fn task_slice_brief_path(root: &Path, task: &Task) -> Option<String> {
    task.header.slice.as_deref().map(|slice| {
        relative(
            root,
            &root
                .join(".zdev")
                .join(&task.header.area)
                .join("slices")
                .join(format!("{slice}.md")),
        )
    })
}

fn find_task<'a>(tasks: &'a [Task], id: &str) -> Result<&'a Task, ZdevError> {
    tasks
        .iter()
        .find(|task| task.header.id == id)
        .ok_or_else(|| ZdevError::new(format!("Unknown task: {id}")))
}

fn require_hypothesis_completion(root: &Path, area: &str, task: &Task) -> Result<(), ZdevError> {
    if task.header.hypothesis.is_some() {
        let settings = load_area(root, area)?
            .0
            .research
            .ok_or_else(|| ZdevError::new("Hypothesis completion requires research settings"))?;
        if super::research::experiment::exists(root, area, &task.header.id)? {
            super::research::experiment::require_completion(
                root,
                area,
                &task.header.id,
                &task.header.research_results,
            )?;
        } else {
            validate_evidence(&task.header.research_results, true, Some(&settings))?;
        }
    }
    Ok(())
}

pub(super) fn research_result(
    root: &Path,
    area: &str,
    id: &str,
    source: Option<&Path>,
) -> Result<CommandOutput, ZdevError> {
    if let Some(source) = source {
        let result: ResultRecord = super::research::read_json(source)?;
        let _lock = ZdevStateLock::acquire(root)?;
        require_task_work_area_link(root, area)?;
        let metadata = load_area(root, area)?.0;
        if metadata.lifecycle != AreaLifecycle::Open {
            return Err(ZdevError::new("Cannot record research in a closed area"));
        }
        let settings = metadata
            .research
            .ok_or_else(|| ZdevError::new("Area has no research settings"))?;
        let tasks = load_tasks(root, area)?;
        let task = find_task(&tasks, id)?;
        if task.header.hypothesis.is_none()
            || task_state(task, &read_task_statuses(root, area, &tasks)?) != "ready"
        {
            return Err(ZdevError::new(
                "Research results require a ready open hypothesis task",
            ));
        }
        if super::research::run::active(root, area)? {
            return Err(ZdevError::new(
                "Active research runs record observations through the bound experiment lifecycle",
            ));
        }
        if super::research::experiment::exists(root, area, id)? {
            return Err(ZdevError::new(
                "Managed experiments record evidence through research experiment evaluate/finalize",
            ));
        }
        if result.comparison != settings.comparison
            || result.attempt_limit != settings.attempt_limit
        {
            return Err(ZdevError::new(
                "Research result differs from current research settings",
            ));
        }
        append_research_record(root, area, id, &result)?;
    }
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    let hypothesis = task
        .header
        .hypothesis
        .as_ref()
        .ok_or_else(|| ZdevError::new("Task is not a hypothesis"))?;
    let value = json!({"schema_version": SCHEMA_VERSION, "area": area, "task_id": id, "hypothesis": hypothesis, "research_results": task.header.research_results});
    Ok(CommandOutput::new(
        serde_json::to_string_pretty(&value).unwrap(),
        value,
    ))
}

/// Caller holds the state lock; managed experiments also publish recovered observations here.
pub(super) fn append_research_record(
    root: &Path,
    area: &str,
    id: &str,
    result: &ResultRecord,
) -> Result<(), ZdevError> {
    append_research_record_with_checkpoint(root, area, id, result, |_| Ok(()))
}

pub(super) fn append_research_record_with_checkpoint(
    root: &Path,
    area: &str,
    id: &str,
    result: &ResultRecord,
    checkpoint: impl FnOnce(&PlannedWrites<'_>) -> Result<(), ZdevError>,
) -> Result<(), ZdevError> {
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    if task.header.hypothesis.is_none()
        || task_state(task, &read_task_statuses(root, area, &tasks)?) != "ready"
    {
        return Err(ZdevError::new(
            "Research results require a ready open hypothesis task",
        ));
    }
    let mut header = task.header.clone();
    header.research_results.push(result.clone());
    validate_evidence(&header.research_results, false, None)?;
    let content = format!(
        "+++\n{}+++\n{}",
        toml::to_string(&header).unwrap(),
        task.body
    );
    publish_task_and_index_with_checkpoint(root, area, task, &content, checkpoint)?;
    Ok(())
}

pub(super) fn complete(
    root: &Path,
    area: &str,
    id: &str,
    summary: &str,
    validation: &[String],
) -> Result<CommandOutput, ZdevError> {
    validate_nonempty_line(summary, "Completion summary")?;
    for item in validation {
        validate_nonempty_line(item, "Validation result")?;
    }
    let _lock = ZdevStateLock::acquire(root)?;
    complete_with_checkpoint(root, area, id, summary, validation, |_| Ok(()))
}

pub(super) fn complete_with_checkpoint(
    root: &Path,
    area: &str,
    id: &str,
    summary: &str,
    validation: &[String],
    checkpoint: impl FnOnce(&PlannedWrites<'_>) -> Result<(), ZdevError>,
) -> Result<CommandOutput, ZdevError> {
    let branch = require_task_work_area_link(root, area)?;
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    if task.header.status == TaskStatus::Done {
        return Ok(CommandOutput::new(
            format!("Task {id} is already done"),
            json!({"schema_version": SCHEMA_VERSION, "status": "unchanged", "area": area, "task": id, "dependent_indexes": []}),
        ));
    }
    if task_state(task, &read_task_statuses(root, area, &tasks)?) != "ready" {
        return Err(ZdevError::new(format!(
            "Cannot complete task {id}: it is blocked. Complete its blockers first"
        )));
    }
    require_retained_code(root, &task.header.requires_code, &tasks)?;
    require_hypothesis_completion(root, area, task)?;
    if task.header.hypothesis.is_none() {
        super::research::run::require_supporting_reservation(root, area, id)?;
    }
    let mut header = task.header.clone();
    header.status = TaskStatus::Done;
    let mut body = replace_markdown_section(&task.body, "Done when", &task.path, |section| {
        section.replace("- [ ] ", "- [x] ")
    })?;
    if !body.ends_with('\n') {
        body.push('\n');
    }
    body.push_str("\n## Result\n\n");
    body.push_str(summary);
    body.push_str("\n\nValidation:\n\n");
    for item in validation {
        body.push_str(&format!("- {item}\n"));
    }
    let content = format!("+++\n{}+++\n{}", toml::to_string(&header).unwrap(), body);
    let dependent_indexes = relative_paths(
        root,
        &publish_task_and_index_with_checkpoint(root, area, task, &content, checkpoint)?,
    )?;
    let mut text = format!("Completed task {id}");
    append_dependent_indexes(&mut text, &dependent_indexes);
    if let Some(advisory) = &branch.advisory {
        text.push('\n');
        text.push_str(advisory);
    }
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "status": "done", "area": area, "task": id, "branch_status": branch.branch_status, "advisory": branch.advisory, "dependent_indexes": dependent_indexes}),
    ))
}

pub(super) fn reopen(root: &Path, area: &str, id: &str) -> Result<CommandOutput, ZdevError> {
    let _lock = ZdevStateLock::acquire(root)?;
    super::project::validate_area_relationships(root, &list_areas(root)?)?;
    let metadata = load_area(root, area)?.0;
    if metadata.lifecycle == AreaLifecycle::Closed {
        return Err(ZdevError::new(format!(
            "Cannot reopen task {id} in closed area {area}. Run `zdev area reopen {area}` first"
        )));
    }
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    if task.header.status == TaskStatus::Open {
        return Ok(CommandOutput::new(
            format!("Task {id} is already open"),
            json!({"schema_version": SCHEMA_VERSION, "status": "unchanged", "area": area, "task": id, "dependent_indexes": []}),
        ));
    }
    if task.header.hypothesis.is_some() {
        return Err(ZdevError::new(
            "A completed hypothesis cannot be reopened; create a new context-linked retry",
        ));
    }
    if tasks
        .iter()
        .any(|candidate| is_completed_dependent(candidate, id))
    {
        return Err(ZdevError::new(format!(
            "Cannot reopen {id}: a completed task depends on it. Reopen dependent completed tasks first"
        )));
    }
    for dependent_area in read_dependent_areas(root, area, id)? {
        if let Some(dependent) = dependent_area
            .tasks
            .iter()
            .find(|candidate| is_completed_dependent(candidate, id))
        {
            return Err(ZdevError::new(format!(
                "Cannot reopen {id}: completed task {} in area {} depends on it. Reopen dependent completed tasks first",
                dependent.header.id, dependent_area.tag
            )));
        }
    }
    let mut header = task.header.clone();
    header.status = TaskStatus::Open;
    let body = if let Some((before, result)) = task.body.split_once("\n## Result\n") {
        let mut preserved = before.trim_end().to_owned();
        if preserved.contains("\n## History\n") {
            preserved.push_str("\n\n### Previous completion\n\n");
        } else {
            preserved.push_str("\n\n## History\n\n### Previous completion\n\n");
        }
        preserved.push_str(result.trim());
        preserved.push('\n');
        preserved
    } else {
        task.body.clone()
    };
    let body = replace_markdown_section(&body, "Done when", &task.path, |section| {
        section
            .replace("- [x] ", "- [ ] ")
            .replace("- [X] ", "- [ ] ")
    })?;
    let content = format!("+++\n{}+++\n{}", toml::to_string(&header).unwrap(), body);
    let dependent_indexes =
        relative_paths(root, &publish_task_and_index(root, area, task, &content)?)?;
    let mut text = format!("Reopened task {id}");
    append_dependent_indexes(&mut text, &dependent_indexes);
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "status": "open", "area": area, "task": id, "dependent_indexes": dependent_indexes}),
    ))
}

/// Adds a line naming the other areas' `TASKS.md` files a status change rewrote,
/// so that whoever commits the change also commits them.
fn append_dependent_indexes(text: &mut String, paths: &[String]) {
    if !paths.is_empty() {
        text.push_str(&format!(
            "\nUpdated dependent indexes: {}",
            paths.join(", ")
        ));
    }
}

fn publish_task_and_index(
    root: &Path,
    area: &str,
    current: &Task,
    content: &str,
) -> Result<Vec<PathBuf>, ZdevError> {
    publish_task_and_index_with_checkpoint(root, area, current, content, |_| Ok(()))
}

/// The files a task change is about to write, as passed to its checkpoint.
pub(super) struct PlannedWrites<'a> {
    /// Every file the change writes, with its new bytes, in write order.
    pub files: &'a [(PathBuf, Vec<u8>)],
    /// The other areas' `TASKS.md` paths among `files`, which show the changed
    /// task's new status. Empty when the task's status does not change.
    pub dependent_indexes: &'a [PathBuf],
}

/// Replaces `current` with `content` and regenerates its area's `TASKS.md`. When
/// the task's status changes, also regenerates the `TASKS.md` of every other area
/// that depends on it. Passes the planned writes to `checkpoint` before writing,
/// writes them with rollback, and returns the dependent index paths it wrote.
fn publish_task_and_index_with_checkpoint(
    root: &Path,
    area: &str,
    current: &Task,
    content: &str,
    checkpoint: impl FnOnce(&PlannedWrites<'_>) -> Result<(), ZdevError>,
) -> Result<Vec<PathBuf>, ZdevError> {
    let index_path = root.join(".zdev").join(area).join("TASKS.md");
    let mut tasks = load_tasks(root, area)?;
    let updated = parse_task(content, &current.path, area)?;
    let status = updated.header.status;
    if status == TaskStatus::Done {
        require_hypothesis_completion(root, area, &updated)?;
    }
    let slot = tasks
        .iter_mut()
        .find(|task| task.header.id == current.header.id)
        .ok_or_else(|| ZdevError::new(format!("Unknown task: {}", current.header.id)))?;
    *slot = updated;
    validate_research_tasks(&tasks, load_area(root, area)?.0.research.is_some())?;
    validate_graph(root, area, &tasks)?;
    let index = render_index(area, &tasks, &read_task_statuses(root, area, &tasks)?);
    let dependent_indexes = if status == current.header.status {
        Vec::new()
    } else {
        render_dependent_indexes(root, area, &current.header.id, status)?
    };
    let dependent_index_paths: Vec<PathBuf> = dependent_indexes
        .iter()
        .map(|(path, _)| path.clone())
        .collect();

    let mut writes = vec![
        (current.path.clone(), content.as_bytes().to_vec()),
        (index_path, index.into_bytes()),
    ];
    writes.extend(dependent_indexes);
    let originals = read_originals(&writes)?;
    checkpoint(&PlannedWrites {
        files: &writes,
        dependent_indexes: &dependent_index_paths,
    })?;
    write_with_rollback(&writes, &originals)?;
    Ok(dependent_index_paths)
}

/// The current bytes of each file that `writes` will replace, in the same order.
fn read_originals(writes: &[(PathBuf, Vec<u8>)]) -> Result<Vec<Vec<u8>>, ZdevError> {
    writes
        .iter()
        .map(|(path, _)| {
            fs::read(path)
                .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))
        })
        .collect()
}

/// Writes each file atomically, in order. If a write fails, attempts to restore
/// every file already written to its `originals`, so that either every file
/// changes or none does, and reports each restore that fails. A failed atomic
/// write leaves its own file unchanged.
fn write_with_rollback(
    writes: &[(PathBuf, Vec<u8>)],
    originals: &[Vec<u8>],
) -> Result<(), ZdevError> {
    for (written, (path, bytes)) in writes.iter().enumerate() {
        let Err(error) = write_atomic(path, bytes) else {
            continue;
        };
        let rollback_errors = writes[..written]
            .iter()
            .zip(originals)
            .filter_map(|((path, _), original)| write_atomic(path, original).err())
            .map(|rollback| rollback.to_string())
            .collect::<Vec<_>>();
        if rollback_errors.is_empty() {
            return Err(error);
        }
        return Err(ZdevError::new(format!(
            "{error}; rollback also failed: {}",
            rollback_errors.join("; ")
        )));
    }
    Ok(())
}

/// Renders `TASKS.md` for a task list whose graph the caller has validated.
fn render_index(area: &str, tasks: &[Task], statuses: &TaskStatuses) -> String {
    let ready = tasks
        .iter()
        .filter(|task| task_state(task, statuses) == "ready")
        .count();
    let blocked = tasks
        .iter()
        .filter(|task| task_state(task, statuses) == "blocked")
        .count();
    let done = tasks
        .iter()
        .filter(|task| task.header.status == TaskStatus::Done)
        .count();
    let has_slices = tasks.iter().any(|task| task.header.slice.is_some());
    let columns = if has_slices {
        "| ID | Task | Slice | State | Blocked by |\n| --- | --- | --- | --- | --- |\n"
    } else {
        "| ID | Task | State | Blocked by |\n| --- | --- | --- | --- |\n"
    };
    let mut result = format!(
        "{GENERATED_MARKER}\n\n# Tasks: {area}\n\n- Total: {}\n- Ready: {ready}\n- Blocked: {blocked}\n- Done: {done}\n\n{columns}",
        tasks.len()
    );
    for task in tasks {
        let blockers = if task.header.blocked_by.is_empty() {
            "—".to_owned()
        } else {
            task.header
                .blocked_by
                .iter()
                .map(|blocker| blocker_label(area, blocker, statuses))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let filename = task
            .path
            .file_name()
            .and_then(OsStr::to_str)
            .unwrap_or("task.md");
        let title = if task.header.hypothesis.is_some() {
            format!("{} (hypothesis)", task.title)
        } else {
            task.title.clone()
        };
        if has_slices {
            let slice = task.header.slice.as_deref().unwrap_or("—");
            result.push_str(&format!(
                "| [{}](tasks/{filename}) | {} | {slice} | {} | {blockers} |\n",
                task.header.id,
                table_text(&title),
                task_state(task, statuses),
            ));
        } else {
            result.push_str(&format!(
                "| [{}](tasks/{filename}) | {} | {} | {blockers} |\n",
                task.header.id,
                table_text(&title),
                task_state(task, statuses),
            ));
        }
    }
    result
}

pub(super) fn empty_index(area: &str) -> String {
    render_index(area, &[], &TaskStatuses::default())
}

