pub(super) fn summary_selected(
    root: &Path,
    area: &str,
    selected: Option<&str>,
) -> Result<AreaTaskSummary, ZdevError> {
    let tasks = load_tasks(root, area)?;
    let statuses = read_task_statuses(root, area, &tasks)?;
    let ready = tasks
        .iter()
        .filter(|task| task_state(task, &statuses) == "ready")
        .count();
    let blocked = tasks
        .iter()
        .filter(|task| task_state(task, &statuses) == "blocked")
        .count();
    let done = tasks
        .iter()
        .filter(|task| task.header.status == TaskStatus::Done)
        .count();
    let slices = slice_briefs(root, area)?
        .into_iter()
        .map(|slice| {
            let slice_tasks = tasks
                .iter()
                .filter(|task| task.header.slice.as_deref() == Some(slice.key.as_str()))
                .collect::<Vec<_>>();
            SliceTaskSummary {
                key: slice.key,
                title: slice.title,
                path: relative(root, &slice.path),
                ready: slice_tasks
                    .iter()
                    .filter(|task| task_state(task, &statuses) == "ready")
                    .count(),
                blocked: slice_tasks
                    .iter()
                    .filter(|task| task_state(task, &statuses) == "blocked")
                    .count(),
                done: slice_tasks
                    .iter()
                    .filter(|task| task.header.status == TaskStatus::Done)
                    .count(),
            }
        })
        .collect();
    let next = match selected {
        Some(id) => {
            let task = tasks
                .iter()
                .find(|task| task.header.id == id)
                .ok_or_else(|| ZdevError::new(format!("Unknown task {id}")))?;
            if task_state(task, &statuses) != "ready" {
                return Err(ZdevError::new(format!(
                    "Task {id} is not in the ready frontier"
                )));
            }
            Some(task)
        }
        None => next_task(&tasks, &statuses),
    };
    Ok(AreaTaskSummary {
        total: tasks.len(),
        ready,
        blocked,
        done,
        open: tasks.len() - done,
        next: next.map(|task| task.header.id.clone()),
        next_complexity: next.map(Task::complexity),
        slices,
        cross_area_waits: cross_area_waits(area, &tasks, &statuses),
    })
}

pub(super) fn task_is_ready(root: &Path, area: &str, id: &str) -> Result<bool, ZdevError> {
    let tasks = load_tasks(root, area)?;
    let statuses = read_task_statuses(root, area, &tasks)?;
    let task = tasks
        .iter()
        .find(|task| task.header.id == id)
        .filter(|task| task_state(task, &statuses) == "ready");
    if let Some(task) = task {
        require_retained_code(root, &task.header.requires_code, &tasks)?;
    }
    Ok(task.is_some())
}

pub(super) fn require_task_code(root: &Path, area: &str, id: &str) -> Result<(), ZdevError> {
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    require_retained_code(root, &task.header.requires_code, &tasks)
}

pub(super) fn validate_index(root: &Path, area: &str) -> Result<(), ZdevError> {
    let tasks = load_tasks(root, area)?;
    let expected = render_index(area, &tasks, &read_task_statuses(root, area, &tasks)?);
    let path = root.join(".zdev").join(area).join("TASKS.md");
    let actual = fs::read_to_string(&path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))?;
    if actual != expected {
        return Err(ZdevError::new(format!(
            "Generated task summary is stale: {}. Run `zdev tasks index {area}` to regenerate it",
            path.display()
        )));
    }
    Ok(())
}

fn slug(value: &str) -> String {
    let mut slug = String::new();
    let mut separator = false;
    for byte in value.bytes() {
        if byte.is_ascii_alphanumeric() {
            if separator && !slug.is_empty() {
                slug.push('-');
            }
            slug.push(char::from(byte.to_ascii_lowercase()));
            separator = false;
        } else if !slug.is_empty() {
            separator = true;
        }
    }
    if slug.is_empty() {
        "task".to_owned()
    } else {
        slug.truncate(60);
        slug.trim_end_matches('-').to_owned()
    }
}

fn table_text(value: &str) -> String {
    value.replace('|', "\\|")
}
