fn find_task<'a>(tasks: &'a [Task], id: &str) -> Result<&'a Task, ZdevError> {
    tasks
        .iter()
        .find(|task| task.header.id == id)
        .ok_or_else(|| ZdevError::new(format!("Unknown task: {id}")))
}

fn complete_task(
    root: &Path,
    area: &str,
    id: &str,
    summary: &str,
    validation: &[String],
) -> Result<CommandOutput, ZdevError> {
    require_fresh_area_link(root, area)?;
    validate_nonempty_line(summary, "Completion summary")?;
    for item in validation {
        validate_nonempty_line(item, "Validation result")?;
    }
    let _lock = ZdevStateLock::acquire(root)?;
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    if task.header.status == TaskStatus::Done {
        return Ok(CommandOutput::new(
            format!("Task {id} is already done"),
            json!({"schema_version": SCHEMA_VERSION, "status": "unchanged", "area": area, "task": id}),
        ));
    }
    if task_state(task, &tasks) != "ready" {
        return Err(ZdevError::new(format!(
            "Cannot complete task {id}: it is blocked. Complete its blockers first"
        )));
    }
    let mut header = task.header.clone();
    header.status = TaskStatus::Done;
    let mut body = replace_markdown_section(&task.body, "Done when", &task.path, |section| {
        section.replace("- [ ] ", "- [x] ")
    })?;
    if !body.ends_with('\n') {
        body.push('\n');
    }
    body.push_str("\n## Result\n\n");
    body.push_str(summary);
    body.push_str("\n\nValidation:\n\n");
    for item in validation {
        body.push_str(&format!("- {item}\n"));
    }
    let content = format!("+++\n{}+++\n{}", toml::to_string(&header).unwrap(), body);
    publish_task_and_index(root, area, task, &content)?;
    Ok(CommandOutput::new(
        format!("Completed task {id}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "done", "area": area, "task": id}),
    ))
}

fn reopen_task(root: &Path, area: &str, id: &str) -> Result<CommandOutput, ZdevError> {
    let _lock = ZdevStateLock::acquire(root)?;
    let tasks = load_tasks(root, area)?;
    let task = find_task(&tasks, id)?;
    if task.header.status == TaskStatus::Open {
        return Ok(CommandOutput::new(
            format!("Task {id} is already open"),
            json!({"schema_version": SCHEMA_VERSION, "status": "unchanged", "area": area, "task": id}),
        ));
    }
    if tasks.iter().any(|candidate| {
        candidate.header.status == TaskStatus::Done
            && candidate
                .header
                .blocked_by
                .iter()
                .any(|blocker| blocker == id)
    }) {
        return Err(ZdevError::new(format!(
            "Cannot reopen {id}: a completed task depends on it. Reopen dependent completed tasks first"
        )));
    }
    let mut header = task.header.clone();
    header.status = TaskStatus::Open;
    let body = task
        .body
        .split("\n## Result\n")
        .next()
        .unwrap_or(&task.body);
    let body = replace_markdown_section(body, "Done when", &task.path, |section| {
        section
            .replace("- [x] ", "- [ ] ")
            .replace("- [X] ", "- [ ] ")
    })?;
    let content = format!("+++\n{}+++\n{}", toml::to_string(&header).unwrap(), body);
    publish_task_and_index(root, area, task, &content)?;
    Ok(CommandOutput::new(
        format!("Reopened task {id}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "open", "area": area, "task": id}),
    ))
}

fn publish_task_and_index(
    root: &Path,
    area: &str,
    current: &Task,
    content: &str,
) -> Result<(), ZdevError> {
    let index_path = root.join(".zdev").join(area).join("TASKS.md");
    let original_task = fs::read(&current.path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", current.path.display()), error))?;
    let original_index = fs::read(&index_path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", index_path.display()), error))?;
    let mut tasks = load_tasks(root, area)?;
    let updated = parse_task(content, &current.path, area)?;
    let slot = tasks
        .iter_mut()
        .find(|task| task.header.id == current.header.id)
        .ok_or_else(|| ZdevError::new(format!("Unknown task: {}", current.header.id)))?;
    *slot = updated;
    let index = render_index(area, &tasks)?;

    write_atomic(&current.path, content.as_bytes())?;
    if let Err(error) = write_atomic(&index_path, index.as_bytes()) {
        let task_rollback = write_atomic(&current.path, &original_task);
        let index_rollback = write_atomic(&index_path, &original_index);
        if let Err(rollback) = task_rollback.and(index_rollback) {
            return Err(ZdevError::new(format!(
                "{error}; rollback also failed: {rollback}"
            )));
        }
        return Err(error);
    }
    Ok(())
}

fn render_index(area: &str, tasks: &[Task]) -> Result<String, ZdevError> {
    validate_graph(tasks)?;
    let ready = tasks
        .iter()
        .filter(|task| task_state(task, tasks) == "ready")
        .count();
    let blocked = tasks
        .iter()
        .filter(|task| task_state(task, tasks) == "blocked")
        .count();
    let done = tasks
        .iter()
        .filter(|task| task.header.status == TaskStatus::Done)
        .count();
    let mut result = format!(
        "{GENERATED_MARKER}\n\n# Tasks: {area}\n\n- Total: {}\n- Ready: {ready}\n- Blocked: {blocked}\n- Done: {done}\n\n| ID | Task | State | Blocked by |\n| --- | --- | --- | --- |\n",
        tasks.len()
    );
    for task in tasks {
        let blockers = if task.header.blocked_by.is_empty() {
            "—".to_owned()
        } else {
            task.header.blocked_by.join(", ")
        };
        let filename = task
            .path
            .file_name()
            .and_then(OsStr::to_str)
            .unwrap_or("task.md");
        result.push_str(&format!(
            "| [{}](tasks/{filename}) | {} | {} | {blockers} |\n",
            task.header.id,
            table_text(&task.title),
            task_state(task, tasks),
        ));
    }
    Ok(result)
}

fn write_index(root: &Path, area: &str) -> Result<PathBuf, ZdevError> {
    let (_, area_dir) = load_area(root, area)?;
    let tasks = load_tasks(root, area)?;
    let path = area_dir.join("TASKS.md");
    write_atomic(&path, render_index(area, &tasks)?.as_bytes())?;
    Ok(path)
}

fn write_index_output(root: &Path, area: &str) -> Result<CommandOutput, ZdevError> {
    let _lock = ZdevStateLock::acquire(root)?;
    let path = write_index(root, area)?;
    Ok(CommandOutput::new(
        format!("Updated {}", relative(root, &path)),
        json!({"schema_version": SCHEMA_VERSION, "status": "updated", "area": area, "path": relative(root, &path)}),
    ))
}

fn local_branch_exists(root: &Path, branch: &str) -> bool {
    ProcessCommand::new("git")
        .args([
            "show-ref",
            "--verify",
            "--quiet",
            &format!("refs/heads/{branch}"),
        ])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .status()
        .is_ok_and(|status| status.success())
}

fn base_is_ancestor(root: &Path, base: &str, branch: &str) -> Option<bool> {
    commit_is_ancestor(
        root,
        &format!("refs/heads/{base}"),
        &format!("refs/heads/{branch}"),
    )
}

fn commit_is_ancestor(root: &Path, ancestor: &str, descendant: &str) -> Option<bool> {
    let status = ProcessCommand::new("git")
        .args(["merge-base", "--is-ancestor", ancestor, descendant])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .status()
        .ok()?;
    match status.code() {
        Some(0) => Some(true),
        Some(1) => Some(false),
        _ => None,
    }
}

fn area_branch_status(
    root: &Path,
    config: &Config,
    area: &AreaMetadata,
    areas: &BTreeMap<&str, &AreaMetadata>,
    checked_out: Option<&str>,
) -> Value {
    let mut diagnostics = Vec::new();
    let branch_matches = checked_out.map(|checked_out| area.branch == checked_out);
    if branch_matches == Some(false) {
        diagnostics.push("wrong-branch");
    } else if checked_out.is_none() {
        diagnostics.push("detached-head");
    }

    let (base_kind, base_area, effective_base) = if let Some(parent) = &area.parent {
        match areas.get(parent.as_str()) {
            Some(parent_area) => (
                "area",
                Some(parent.as_str()),
                Some(parent_area.branch.as_str()),
            ),
            None => {
                diagnostics.push("parent-area-missing");
                ("area", Some(parent.as_str()), None)
            }
        }
    } else {
        ("trunk", None, config.project.trunk.as_deref())
    };
    if effective_base.is_none() {
        diagnostics.push(if base_kind == "trunk" {
            "project-trunk-unbound"
        } else {
            "effective-base-unbound"
        });
    }
    if area.base_commit.is_none() {
        diagnostics.push("base-anchor-unbound");
    } else if area
        .base_commit
        .as_deref()
        .is_some_and(|anchor| !commit_exists(root, anchor))
    {
        diagnostics.push("base-anchor-missing");
    }

    let anchor_valid = match area.base_commit.as_deref() {
        Some(anchor) if local_branch_exists(root, &area.branch) => Some(
            commit_exists(root, anchor)
                && commit_is_ancestor(root, anchor, &format!("refs/heads/{}", area.branch))
                    == Some(true),
        ),
        _ => None,
    };
    if anchor_valid == Some(false) {
        diagnostics.push("base-anchor-not-contained");
    }
    let mut finalized = None;
    let fresh = match effective_base {
        Some(base) => {
            let branch = area.branch.as_str();
            let base_exists = local_branch_exists(root, base);
            let branch_exists = local_branch_exists(root, branch);
            if !base_exists {
                diagnostics.push("effective-base-missing");
            }
            if !branch_exists {
                diagnostics.push("area-branch-missing");
            }
            if base_exists && branch_exists {
                if area.base_commit.as_deref().is_some_and(|anchor| {
                    child_side_has_merges(root, anchor, branch).unwrap_or(false)
                }) {
                    diagnostics.push("merge-history");
                }
                let fresh = base_is_ancestor(root, base, branch);
                finalized = branch_tip(root, base).ok().flatten().map(|base_tip| {
                    fresh == Some(true) && area.base_commit.as_deref() == Some(base_tip.as_str())
                });
                match fresh {
                    Some(true) => {
                        diagnostics.push("fresh");
                        if finalized == Some(false) {
                            diagnostics.push("base-anchor-needs-finalization");
                        }
                    }
                    Some(false) => diagnostics.push("stale"),
                    None => diagnostics.push("ancestry-unavailable"),
                }
                fresh
            } else {
                None
            }
        }
        None => None,
    };

    json!({
        "branch": area.branch,
        "checked_out_branch": checked_out,
        "branch_matches": branch_matches,
        "parent_area": area.parent,
        "base_commit": area.base_commit,
        "effective_base": {
            "kind": base_kind,
            "area": base_area,
            "branch": effective_base,
        },
        "fresh": fresh,
        "anchor_valid": anchor_valid,
        "finalized": finalized,
        "diagnostics": diagnostics,
    })
}

fn render_area_branch_line(area: &AreaMetadata, status: &Value) -> String {
    let branch = &area.branch;
    let base = status["effective_base"]["branch"]
        .as_str()
        .unwrap_or("unbound");
    let relationship = match area.parent.as_deref() {
        Some(parent) => format!("parent {parent} on {base}"),
        None => format!("trunk {base}"),
    };
    let diagnostics = status["diagnostics"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect::<Vec<_>>()
        .join(", ");
    format!("{}: {branch} -> {relationship} [{diagnostics}]", area.tag)
}

fn status_output(root: &Path, requested: Option<&str>) -> Result<CommandOutput, ZdevError> {
    let config = read_config(root)?;
    let all_areas = list_areas(root)?;
    let by_tag = all_areas
        .iter()
        .map(|area| (area.tag.as_str(), area))
        .collect::<BTreeMap<_, _>>();
    let checked_out = current_branch(root)?;
    let selected = match requested {
        Some(area) => Some(area.to_owned()),
        None => config.project.default_area.clone(),
    };
    if let Some(area) = selected {
        let metadata = load_area(root, &area)?.0;
        let tasks = load_tasks(root, &area)?;
        let task_views = views(root, &tasks);
        let ready = task_views
            .iter()
            .filter(|task| task.state == "ready")
            .count();
        let blocked = task_views
            .iter()
            .filter(|task| task.state == "blocked")
            .count();
        let done = task_views
            .iter()
            .filter(|task| task.state == "done")
            .count();
        let branch_status =
            area_branch_status(root, &config, &metadata, &by_tag, checked_out.as_deref());
        let branch_line = render_area_branch_line(&metadata, &branch_status);
        return Ok(CommandOutput::new(
            format!(
                "{}: {ready} ready, {blocked} blocked, {done} done\n{branch_line}",
                metadata.title,
            ),
            json!({"schema_version": SCHEMA_VERSION, "project": config.project.name, "trunk": config.project.trunk, "area": metadata, "branch_status": branch_status, "counts": {"total": tasks.len(), "ready": ready, "blocked": blocked, "done": done}, "next": next_task(&tasks).map(|task| task.header.id.as_str())}),
        ));
    }
    let mut summaries = Vec::new();
    let mut branch_lines = Vec::new();
    for area in &all_areas {
        let tasks = load_tasks(root, &area.tag)?;
        let branch_status =
            area_branch_status(root, &config, area, &by_tag, checked_out.as_deref());
        branch_lines.push(render_area_branch_line(area, &branch_status));
        summaries.push(json!({
            "tag": area.tag,
            "title": area.title,
            "branch_status": branch_status,
            "open": tasks.iter().filter(|task| task.header.status == TaskStatus::Open).count(),
            "done": tasks.iter().filter(|task| task.header.status == TaskStatus::Done).count(),
        }));
    }
    let trunk = config.project.trunk.as_deref().unwrap_or("unbound");
    let mut text = format!(
        "{}: {} areas (trunk: {trunk})",
        config.project.name,
        summaries.len()
    );
    if !branch_lines.is_empty() {
        text.push('\n');
        text.push_str(&branch_lines.join("\n"));
    }
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "project": config.project.name, "trunk": config.project.trunk, "checked_out_branch": checked_out, "areas": summaries}),
    ))
}

fn check_output(root: &Path, requested: Option<&str>) -> Result<CommandOutput, ZdevError> {
    read_config(root)?;
    validate_area_relationships(&list_areas(root)?)?;
    let areas = if let Some(area) = requested {
        vec![load_area(root, area)?.0]
    } else {
        list_areas(root)?
    };
    let mut checked = Vec::new();
    for area in areas {
        validate_brief(&root.join(".zdev").join(&area.tag).join("brief.md"))?;
        let tasks = load_tasks(root, &area.tag)?;
        let expected = render_index(&area.tag, &tasks)?;
        let path = root.join(".zdev").join(&area.tag).join("TASKS.md");
        let actual = fs::read_to_string(&path)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))?;
        if actual != expected {
            return Err(ZdevError::new(format!(
                "Generated task summary is stale: {}",
                path.display()
            )));
        }
        checked.push(area.tag);
    }
    Ok(CommandOutput::new(
        format!("Checked {} areas", checked.len()),
        json!({"schema_version": SCHEMA_VERSION, "status": "ok", "areas": checked}),
    ))
}

fn validate_brief(path: &Path) -> Result<(), ZdevError> {
    let content = fs::read_to_string(path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))?;
    required_brief_section(&content, "Objective", path)?;
    let testing = required_brief_section(&content, "Testing", path)?.to_ascii_lowercase();
    let levels = [
        "no new tests",
        "existing checks only",
        "focused coverage",
        "broader regression coverage",
    ];
    if !levels.iter().any(|level| testing.contains(level)) {
        return Err(ZdevError::new(format!(
            "Brief ## Testing must state one of: no new tests, existing checks only, focused coverage, or broader regression coverage: {}",
            path.display()
        )));
    }
    Ok(())
}

fn required_brief_section<'a>(
    content: &'a str,
    heading: &str,
    path: &Path,
) -> Result<&'a str, ZdevError> {
    let marker = format!("## {heading}");
    let mut found = false;
    let mut start = 0;
    let mut end = content.len();
    let mut offset = 0;

    for line in content.split_inclusive('\n') {
        let text = line.trim_end_matches(['\r', '\n']);
        if text.starts_with("## ") {
            if found && end == content.len() {
                end = offset;
            }
            if text == marker {
                if found {
                    return Err(ZdevError::new(format!(
                        "Brief repeats ## {heading}: {}",
                        path.display()
                    )));
                }
                found = true;
                start = offset + line.len();
                end = content.len();
            }
        }
        offset += line.len();
    }

    if !found {
        return Err(ZdevError::new(format!(
            "Brief lacks ## {heading}: {}",
            path.display()
        )));
    }
    let section = content[start..end].trim();
    if section.is_empty() {
        return Err(ZdevError::new(format!(
            "Brief has empty ## {heading}: {}",
            path.display()
        )));
    }
    Ok(section)
}

struct SkillIntegration {
    harness: Harness,
    version: &'static str,
    layout: IntegrationLayout,
    files: Vec<IntegrationFile>,
}

#[derive(Clone, Copy)]
enum IntegrationLayout {
    ExactTree,
    SharedRoot,
}

struct IntegrationFile {
    path: String,
    content: String,
}

struct ResolvedIntegrationDestination {
    path: PathBuf,
    scope: &'static str,
}

struct InstallResult {
    status: &'static str,
    destination: PathBuf,
}

struct GuidanceStatus {
    mode: String,
    status: &'static str,
    source: String,
    present: bool,
    readable: bool,
    marked_block_current: Option<bool>,
    content: Option<String>,
}

impl GuidanceStatus {
    fn healthy(&self) -> bool {
        matches!(self.status, "ok" | "created")
    }

    fn value(&self) -> Value {
        json!({
            "mode": self.mode,
            "status": self.status,
            "source": self.source,
            "present": self.present,
            "readable": self.readable,
            "marked_block_current": self.marked_block_current,
        })
    }
}

fn run_skill_command(
    requested_root: Option<&Path>,
    command: &SkillCommand,
) -> Result<CommandOutput, ZdevError> {
    let (harness, scope, requested, guidance) = match command {
        SkillCommand::Install {
            harness,
            scope,
            to,
            guidance,
            ..
        }
        | SkillCommand::Check {
            harness,
            scope,
            to,
            guidance,
        } => (*harness, *scope, to.as_deref(), guidance.as_deref()),
    };
    if scope != InstallationScope::Project && guidance.is_some() {
        return Err(ZdevError::new(
            "--guidance is available only with --scope project",
        ));
    }
    let project_root = if scope == InstallationScope::Project {
        Some(resolve_root(requested_root)?)
    } else {
        None
    };
    let destination =
        resolve_integration_destination(harness, scope, requested, project_root.as_deref())?;
    let warnings = integration_warnings(harness, scope, requested);
    let guidance_selection = if let Some(root) = project_root.as_deref() {
        guidance
            .map(str::to_owned)
            .or(read_recorded_guidance(root)?)
            .unwrap_or_else(|| "auto".to_owned())
    } else {
        "auto".to_owned()
    };
    match command {
        SkillCommand::Install { force, .. } => {
            if let Some(root) = project_root.as_deref() {
                read_config(root).map_err(|error| {
                    ZdevError::new(format!(
                        "Initialize zdev with `zdev init --record <personal|project|pull-request>` before installing a project integration: {error}"
                    ))
                })?;
            }
            let guidance = project_root
                .as_deref()
                .map(|root| inspect_guidance(root, &guidance_selection, true, true))
                .transpose()?;
            let guidance_view = guidance.as_ref().and_then(|guidance| {
                guidance
                    .content
                    .as_deref()
                    .map(|content| (guidance.source.as_str(), content))
            });
            let integration = harness.integration(guidance_view);
            let result = publish_integration(&integration, &destination.path, *force)?;
            if let (Some(root), Some(guidance)) = (project_root.as_deref(), guidance.as_ref()) {
                let recorded = if guidance_selection == "agents" {
                    "agents"
                } else {
                    &guidance.source
                };
                record_guidance(root, recorded)?;
            }
            Ok(install_integration_output(
                integration,
                destination,
                result,
                guidance,
                &warnings,
            ))
        }
        SkillCommand::Check { .. } => {
            let guidance = project_root
                .as_deref()
                .map(|root| inspect_guidance(root, &guidance_selection, false, false))
                .transpose()?;
            let guidance_view = guidance.as_ref().and_then(|guidance| {
                guidance
                    .content
                    .as_deref()
                    .map(|content| (guidance.source.as_str(), content))
            });
            check_integration(
                harness.integration(guidance_view),
                destination,
                guidance,
                project_root.as_ref().map(|_| guidance_selection.as_str()),
                &warnings,
            )
        }
    }
}

fn integration_warnings(
    harness: Harness,
    scope: InstallationScope,
    requested: Option<&Path>,
) -> Vec<&'static str> {
    if harness == Harness::Omp
        && scope == InstallationScope::User
        && requested.is_none()
        && env::var_os("PI_CODING_AGENT_DIR").is_some_and(|value| !value.is_empty())
    {
        vec![OMP_RELOCATED_USER_WARNING]
    } else {
        Vec::new()
    }
}

fn resolve_integration_destination(
    harness: Harness,
    scope: InstallationScope,
    requested: Option<&Path>,
    project_root: Option<&Path>,
) -> Result<ResolvedIntegrationDestination, ZdevError> {
    if let Some(path) = requested {
        let path = if path.is_absolute() {
            path.to_path_buf()
        } else {
            env::current_dir()
                .map_err(|error| ZdevError::io("Cannot read current directory", error))?
                .join(path)
        };
        return Ok(ResolvedIntegrationDestination {
            path,
            scope: "explicit",
        });
    }
    let path = match scope {
        InstallationScope::Project => {
            let root = project_root.ok_or_else(|| {
                ZdevError::new("Cannot resolve the project integration destination")
            })?;
            match harness {
                Harness::Codex => root.join(".codex/skills/zdev"),
                Harness::Claude => root.join(".claude/skills/zdev"),
                Harness::Opencode => root.join(".opencode"),
                Harness::Pi => root.join(".pi"),
                Harness::Omp => root.join(".omp"),
            }
        }
        InstallationScope::User => {
            let configured = match harness {
                Harness::Codex => env::var_os("CODEX_HOME"),
                Harness::Claude => env::var_os("CLAUDE_CONFIG_DIR"),
                Harness::Opencode => env::var_os("XDG_CONFIG_HOME")
                    .filter(|value| !value.is_empty())
                    .map(|value| PathBuf::from(value).join("opencode").into_os_string()),
                Harness::Pi => env::var_os("PI_CODING_AGENT_DIR"),
                Harness::Omp => env::var_os("PI_CODING_AGENT_DIR"),
            }
            .filter(|value| !value.is_empty());
            let config_home = if let Some(configured) = configured {
                PathBuf::from(configured)
            } else {
                let home = env::var_os("HOME")
                    .or_else(|| env::var_os("USERPROFILE"))
                    .filter(|value| !value.is_empty())
                    .ok_or_else(|| {
                        let variable = match harness {
                            Harness::Codex => "CODEX_HOME",
                            Harness::Claude => "CLAUDE_CONFIG_DIR",
                            Harness::Opencode => "XDG_CONFIG_HOME",
                            Harness::Pi => "PI_CODING_AGENT_DIR",
                            Harness::Omp => "PI_CODING_AGENT_DIR",
                        };
                        ZdevError::new(format!(
                            "Cannot locate the {} home; set {variable} or pass --to",
                            harness.display_name()
                        ))
                    })?;
                PathBuf::from(home).join(match harness {
                    Harness::Codex => ".codex",
                    Harness::Claude => ".claude",
                    Harness::Opencode => ".config/opencode",
                    Harness::Pi => ".pi/agent",
                    Harness::Omp => ".omp/agent",
                })
            };
            match harness {
                Harness::Codex | Harness::Claude => config_home.join("skills/zdev"),
                Harness::Opencode | Harness::Pi | Harness::Omp => config_home,
            }
        }
    };
    Ok(ResolvedIntegrationDestination {
        path,
        scope: scope.as_str(),
    })
}

fn read_recorded_guidance(root: &Path) -> Result<Option<String>, ZdevError> {
    if !root.join(".zdev/config.toml").is_file() {
        return Ok(None);
    }
    Ok(read_config(root)?.project.guidance)
}

fn record_guidance(root: &Path, source: &str) -> Result<(), ZdevError> {
    let mut config = read_config(root)?;
    if config.project.guidance.as_deref() == Some(source) {
        return Ok(());
    }
    config.project.guidance = Some(source.to_owned());
    fs::create_dir_all(root.join(".zdev"))
        .map_err(|error| ZdevError::io("Cannot create .zdev", error))?;
    write_config(root, &config)
}

fn inspect_guidance(
    root: &Path,
    selection: &str,
    scaffold: bool,
    installing: bool,
) -> Result<GuidanceStatus, ZdevError> {
    let agents = root.join("AGENTS.md");
    let fallback = root.join(".zdev/guidance.md");
    let (mode, path, marked, may_scaffold) = match selection {
        "auto" => {
            if fs::symlink_metadata(&agents).is_ok() {
                ("auto", agents, false, false)
            } else {
                ("auto", fallback, false, true)
            }
        }
        "agents" => ("agents", agents, true, false),
        "zdev" => ("zdev", fallback, false, true),
        custom => (
            "custom",
            resolve_custom_guidance_path(root, custom)?,
            false,
            false,
        ),
    };
    let mut created = false;
    if !path.exists() && scaffold && may_scaffold {
        let parent = path.parent().ok_or_else(|| {
            ZdevError::new(format!("Guidance path has no parent: {}", path.display()))
        })?;
        fs::create_dir_all(parent)
            .map_err(|error| ZdevError::io(format!("Cannot create {}", parent.display()), error))?;
        write_atomic(&path, GUIDANCE_TEMPLATE.as_bytes())?;
        created = true;
    }
    if !path.exists() {
        if installing && !may_scaffold {
            return Err(ZdevError::new(format!(
                "Selected guidance file does not exist: {}",
                path.display()
            )));
        }
        return Ok(GuidanceStatus {
            mode: mode.to_owned(),
            status: "missing",
            source: relative(root, &path),
            present: false,
            readable: false,
            marked_block_current: marked.then_some(false),
            content: None,
        });
    }
    let metadata = fs::symlink_metadata(&path)
        .map_err(|error| ZdevError::io(format!("Cannot inspect {}", path.display()), error))?;
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Err(ZdevError::new(format!(
            "Guidance must be a regular file and not a symlink: {}",
            path.display()
        )));
    }
    let bytes = match fs::read(&path) {
        Ok(bytes) => bytes,
        Err(error) if installing => {
            return Err(ZdevError::io(
                format!("Cannot read selected guidance {}", path.display()),
                error,
            ));
        }
        Err(_) => {
            return Ok(GuidanceStatus {
                mode: mode.to_owned(),
                status: "unreadable",
                source: relative(root, &path),
                present: true,
                readable: false,
                marked_block_current: marked.then_some(false),
                content: None,
            });
        }
    };
    let Ok(content) = String::from_utf8(bytes) else {
        if installing {
            return Err(ZdevError::new(format!(
                "Selected guidance is not UTF-8: {}",
                path.display()
            )));
        }
        return Ok(GuidanceStatus {
            mode: mode.to_owned(),
            status: "unreadable",
            source: relative(root, &path),
            present: true,
            readable: false,
            marked_block_current: marked.then_some(false),
            content: None,
        });
    };
    let marked_block_current = marked.then(|| guidance_markers_are_current(&content));
    if installing && marked_block_current == Some(false) {
        return Err(ZdevError::new(format!(
            "AGENTS.md does not contain one current zdev guidance marker block ({GUIDANCE_START_MARKER} ... {GUIDANCE_END_MARKER})"
        )));
    }
    let status = if marked_block_current == Some(false) {
        "unmarked"
    } else if created {
        "created"
    } else {
        "ok"
    };
    let rendered_content = if marked {
        marked_guidance_content(&content).map(str::to_owned)
    } else {
        Some(content)
    };
    Ok(GuidanceStatus {
        mode: mode.to_owned(),
        status,
        source: relative(root, &path),
        present: true,
        readable: true,
        marked_block_current,
        content: rendered_content,
    })
}

fn resolve_custom_guidance_path(root: &Path, selection: &str) -> Result<PathBuf, ZdevError> {
    let requested = Path::new(selection);
    if requested.is_absolute()
        || requested.extension().and_then(OsStr::to_str) != Some("md")
        || requested
            .components()
            .any(|component| matches!(component, Component::ParentDir))
    {
        return Err(ZdevError::new(
            "Custom guidance must be a repository-relative .md file",
        ));
    }
    let path = normalize_path(&root.join(requested));
    if !path.starts_with(root) || path == root {
        return Err(ZdevError::new(
            "Custom guidance must remain inside the repository",
        ));
    }
    if path.exists() {
        let canonical = fs::canonicalize(&path)
            .map_err(|error| ZdevError::io(format!("Cannot resolve {}", path.display()), error))?;
        if !canonical.starts_with(root) {
            return Err(ZdevError::new(
                "Custom guidance must remain inside the repository",
            ));
        }
    }
    Ok(path)
}

fn guidance_markers_are_current(content: &str) -> bool {
    marked_guidance_content(content).is_some()
}

fn marked_guidance_content(content: &str) -> Option<&str> {
    let starts = content
        .match_indices(GUIDANCE_START_MARKER)
        .collect::<Vec<_>>();
    let ends = content
        .match_indices(GUIDANCE_END_MARKER)
        .collect::<Vec<_>>();
    match (starts.as_slice(), ends.as_slice()) {
        ([(start, marker)], [(end, _)]) if start < end => {
            Some(content[start + marker.len()..*end].trim())
        }
        _ => None,
    }
}

fn installed_integration_matches(
    integration: &SkillIntegration,
    destination: &Path,
) -> Result<bool, ZdevError> {
    if matches!(integration.layout, IntegrationLayout::SharedRoot) {
        for expected in &integration.files {
            let file = destination.join(&expected.path);
            if !file.is_file() {
                return Ok(false);
            }
            let bytes = fs::read(&file)
                .map_err(|error| ZdevError::io(format!("Cannot read {}", file.display()), error))?;
            if bytes != expected.content.as_bytes() {
                return Ok(false);
            }
        }
        return Ok(true);
    }
    let mut actual_files = Vec::new();
    let mut actual_directories = BTreeSet::new();
    let mut pending = vec![destination.to_path_buf()];
    while let Some(directory) = pending.pop() {
        for entry in fs::read_dir(&directory).map_err(|error| {
            ZdevError::io(format!("Cannot inspect {}", directory.display()), error)
        })? {
            let entry = entry.map_err(|error| ZdevError::io("Cannot inspect skill", error))?;
            let kind = entry
                .file_type()
                .map_err(|error| ZdevError::io("Cannot inspect skill entry", error))?;
            if kind.is_dir() {
                actual_directories.insert(
                    entry
                        .path()
                        .strip_prefix(destination)
                        .map_err(|_| {
                            ZdevError::new("Integration directory escaped its destination")
                        })?
                        .to_path_buf(),
                );
                pending.push(entry.path());
            } else if kind.is_file() {
                actual_files.push(
                    entry
                        .path()
                        .strip_prefix(destination)
                        .map_err(|_| ZdevError::new("Skill file escaped its destination"))?
                        .to_path_buf(),
                );
            } else {
                return Ok(false);
            }
        }
    }
    actual_files.sort();
    let mut expected_files = integration
        .files
        .iter()
        .map(|file| PathBuf::from(&file.path))
        .collect::<Vec<_>>();
    expected_files.sort();
    let expected_directories = expected_files
        .iter()
        .flat_map(|path| path.ancestors().skip(1))
        .filter(|path| !path.as_os_str().is_empty())
        .map(Path::to_path_buf)
        .collect::<BTreeSet<_>>();
    if actual_files != expected_files || actual_directories != expected_directories {
        return Ok(false);
    }
    for expected in &integration.files {
        let file = destination.join(&expected.path);
        let bytes = fs::read(&file)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", file.display()), error))?;
        if bytes != expected.content.as_bytes() {
            return Ok(false);
        }
    }
    Ok(true)
}

fn install_integration_output(
    integration: SkillIntegration,
    resolved: ResolvedIntegrationDestination,
    result: InstallResult,
    guidance: Option<GuidanceStatus>,
    warnings: &[&str],
) -> CommandOutput {
    let mut text = if result.status == "unchanged" {
        format!(
            "{} zdev integration is already current at {}",
            integration.harness.display_name(),
            result.destination.display()
        )
    } else {
        format!(
            "Installed zdev integration for {} at {}",
            integration.harness.display_name(),
            result.destination.display()
        )
    };
    if let Some(guidance) = &guidance {
        text.push_str(&format!(
            "; guidance: {} ({})",
            guidance.source, guidance.status
        ));
    }
    for warning in warnings {
        text.push_str("\nWarning: ");
        text.push_str(warning);
    }
    CommandOutput::new(
        text,
        json!({
            "schema_version": SCHEMA_VERSION,
            "harness": integration.harness.as_str(),
            "bundle_version": integration.version,
            "scope": resolved.scope,
            "status": result.status,
            "path": result.destination,
            "files": integration.files.len(),
            "bundle": {
                "status": result.status,
                "path": result.destination,
                "files": integration.files.len(),
                "version": integration.version,
            },
            "guidance": guidance.as_ref().map(GuidanceStatus::value),
            "warnings": warnings,
        }),
    )
}

fn check_integration(
    integration: SkillIntegration,
    resolved: ResolvedIntegrationDestination,
    guidance: Option<GuidanceStatus>,
    guidance_selection: Option<&str>,
    warnings: &[&str],
) -> Result<CommandOutput, ZdevError> {
    let integration_status = if !resolved.path.exists() {
        "missing"
    } else if resolved.path.is_dir() && installed_integration_matches(&integration, &resolved.path)?
    {
        "ok"
    } else {
        "conflict"
    };
    let status =
        if integration_status == "ok" && guidance.as_ref().is_none_or(GuidanceStatus::healthy) {
            "ok"
        } else if integration_status != "ok" {
            integration_status
        } else {
            "guidance-incomplete"
        };
    let mut install_command = match resolved.scope {
        "user" | "project" => format!(
            "zdev skill install {} --scope {}",
            integration.harness.as_str(),
            resolved.scope
        ),
        _ => format!(
            "zdev skill install {} --to {}",
            integration.harness.as_str(),
            resolved.path.display()
        ),
    };
    if let Some(selection) = guidance_selection {
        install_command.push_str(&format!(" --guidance {selection}"));
    }
    let mut text = match status {
        "guidance-incomplete" => format!(
            "{} zdev integration files are current at {}, but the selected guidance is not ready",
            integration.harness.display_name(),
            resolved.path.display()
        ),
        "ok" => format!(
            "{} zdev integration is ready at {}",
            integration.harness.display_name(),
            resolved.path.display()
        ),
        "missing" => format!(
            "{} zdev integration is missing at {}. Install it with `{install_command}`",
            integration.harness.display_name(),
            resolved.path.display()
        ),
        _ => format!(
            "{} zdev integration differs from this version at {}. Replace it with `{install_command} --force`",
            integration.harness.display_name(),
            resolved.path.display()
        ),
    };
    if let Some(guidance) = &guidance {
        text.push_str(&format!(
            "; guidance: {} ({})",
            guidance.source, guidance.status
        ));
        if status == "guidance-incomplete" {
            text.push_str(&format!(
                ". Fix the guidance source, then rerun `{install_command} --force`"
            ));
        }
    }
    for warning in warnings {
        text.push_str("\nWarning: ");
        text.push_str(warning);
    }
    let mut output = CommandOutput::new(
        text,
        json!({
            "schema_version": SCHEMA_VERSION,
            "harness": integration.harness.as_str(),
            "bundle_version": integration.version,
            "scope": resolved.scope,
            "status": status,
            "path": resolved.path,
            "files": integration.files.len(),
            "bundle": {
                "status": integration_status,
                "path": resolved.path,
                "files": integration.files.len(),
                "version": integration.version,
            },
            "guidance": guidance.as_ref().map(GuidanceStatus::value),
            "warnings": warnings,
        }),
    );
    if status != "ok" {
        output.exit_code = 1;
    }
    Ok(output)
}

fn publish_integration(
    integration: &SkillIntegration,
    destination: &Path,
    force: bool,
) -> Result<InstallResult, ZdevError> {
    if matches!(integration.layout, IntegrationLayout::SharedRoot) {
        return publish_shared_root_integration(integration, destination, force);
    }
    if destination.is_dir() && installed_integration_matches(integration, destination)? {
        return Ok(InstallResult {
            status: "unchanged",
            destination: destination.to_path_buf(),
        });
    }
    if destination.exists() {
        if !destination.is_dir() {
            return Err(ZdevError::new(format!(
                "The zdev integration destination for {} is not a directory: {}",
                integration.harness.display_name(),
                destination.display()
            )));
        }
        if !force {
            return Err(ZdevError::new(format!(
                "A different zdev integration for {} exists at {}; inspect it or rerun with --force",
                integration.harness.display_name(),
                destination.display()
            )));
        }
    }
    let parent = destination.parent().ok_or_else(|| {
        ZdevError::new(format!(
            "Integration destination has no parent: {}",
            destination.display()
        ))
    })?;
    fs::create_dir_all(parent)
        .map_err(|error| ZdevError::io(format!("Cannot create {}", parent.display()), error))?;
    let stage = tempfile::Builder::new()
        .prefix(".zdev-integration-")
        .tempdir_in(parent)
        .map_err(|error| ZdevError::io("Cannot stage the zdev integration", error))?;
    for file in &integration.files {
        let output = stage.path().join(&file.path);
        if let Some(directory) = output.parent() {
            fs::create_dir_all(directory).map_err(|error| {
                ZdevError::io(format!("Cannot create {}", directory.display()), error)
            })?;
        }
        fs::write(&output, &file.content)
            .map_err(|error| ZdevError::io(format!("Cannot write {}", output.display()), error))?;
    }
    let replaced = destination.exists();
    if replaced {
        let backup = tempfile::Builder::new()
            .prefix(".zdev-integration-backup-")
            .tempdir_in(parent)
            .map_err(|error| ZdevError::io("Cannot stage the existing integration", error))?;
        let previous = backup.path().join("previous");
        fs::rename(destination, &previous).map_err(|error| {
            ZdevError::io(format!("Cannot preserve {}", destination.display()), error)
        })?;
        if let Err(error) = fs::rename(stage.keep(), destination) {
            let _ = fs::rename(&previous, destination);
            return Err(ZdevError::io(
                format!("Cannot publish {}", destination.display()),
                error,
            ));
        }
    } else {
        fs::rename(stage.keep(), destination).map_err(|error| {
            ZdevError::io(format!("Cannot publish {}", destination.display()), error)
        })?;
    }
    let status = if replaced { "replaced" } else { "created" };
    Ok(InstallResult {
        status,
        destination: destination.to_path_buf(),
    })
}

fn publish_shared_root_integration(
    integration: &SkillIntegration,
    destination: &Path,
    force: bool,
) -> Result<InstallResult, ZdevError> {
    if destination.exists() && !destination.is_dir() {
        return Err(ZdevError::new(format!(
            "The zdev integration destination for {} is not a directory: {}",
            integration.harness.display_name(),
            destination.display()
        )));
    }
    if destination.is_dir() && installed_integration_matches(integration, destination)? {
        return Ok(InstallResult {
            status: "unchanged",
            destination: destination.to_path_buf(),
        });
    }
    let mut replaced = false;
    for expected in &integration.files {
        let path = destination.join(&expected.path);
        if path.exists() {
            replaced = true;
            let matches = path.is_file()
                && fs::read(&path)
                    .map(|bytes| bytes == expected.content.as_bytes())
                    .unwrap_or(false);
            if !matches && !force {
                return Err(ZdevError::new(format!(
                    "A different zdev integration file for {} exists at {}; inspect it or rerun with --force",
                    integration.harness.display_name(),
                    path.display()
                )));
            }
        }
    }
    fs::create_dir_all(destination).map_err(|error| {
        ZdevError::io(format!("Cannot create {}", destination.display()), error)
    })?;
    for expected in &integration.files {
        let path = destination.join(&expected.path);
        let parent = path.parent().ok_or_else(|| {
            ZdevError::new(format!(
                "Integration file has no parent: {}",
                path.display()
            ))
        })?;
        fs::create_dir_all(parent)
            .map_err(|error| ZdevError::io(format!("Cannot create {}", parent.display()), error))?;
        write_atomic(&path, expected.content.as_bytes())?;
    }
    Ok(InstallResult {
        status: if replaced { "replaced" } else { "created" },
        destination: destination.to_path_buf(),
    })
}

fn commit(root: &Path, message: &str, body: &[String]) -> Result<CommandOutput, ZdevError> {
    validate_nonempty_line(message, "Commit message")?;
    if body.iter().any(|paragraph| {
        paragraph.lines().any(|line| {
            line.split_once(':')
                .is_some_and(|(key, _)| key.trim().eq_ignore_ascii_case(CHANGE_ID_TRAILER))
        })
    }) {
        return Err(ZdevError::new(format!(
            "Commit body must not contain a {CHANGE_ID_TRAILER} trailer; zdev adds one automatically"
        )));
    }
    let _lock = ZdevStateLock::acquire(root)?;
    let change_id = generate_change_id()?;
    let mut command = ProcessCommand::new("git");
    command.arg("commit").arg("-m").arg(message);
    for paragraph in body {
        command.arg("-m").arg(paragraph);
    }
    command
        .arg("-m")
        .arg(format!("{CHANGE_ID_TRAILER}: {change_id}"));
    let output = command
        .current_dir(root)
        .output()
        .map_err(|error| ZdevError::io("Cannot run git commit", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "git commit failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    let revision = git_output(root, &["rev-parse", "HEAD"])?;
    Ok(CommandOutput::new(
        format!("Committed {revision} ({change_id}): {message}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "committed", "commit": revision, "change_id": change_id}),
    ))
}

fn generate_change_id() -> Result<String, ZdevError> {
    let mut random = [0_u8; 32];
    getrandom::fill(&mut random)
        .map_err(|error| ZdevError::new(format!("Cannot generate change ID: {error}")))?;
    let mut id = String::from("Z");
    for byte in random {
        use std::fmt::Write as _;
        write!(&mut id, "{byte:02x}").unwrap();
    }
    Ok(id)
}

fn valid_change_id(id: &str) -> bool {
    id.len() == 65
        && id.starts_with('Z')
        && id[1..]
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn inspect_change(root: &Path, revision: &str) -> Result<CommandOutput, ZdevError> {
    let commit = git_output(
        root,
        &["rev-parse", "--verify", &format!("{revision}^{{commit}}")],
    )?;
    let subject = git_output(root, &["show", "-s", "--format=%s", &commit])?;
    let trailers = git_output(
        root,
        &[
            "show",
            "-s",
            &format!("--format=%(trailers:key={CHANGE_ID_TRAILER},valueonly)"),
            &commit,
        ],
    )?;
    let ids = trailers
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect::<Vec<_>>();
    let change_id = match ids.as_slice() {
        [] => None,
        [id] if valid_change_id(id) => Some((*id).to_owned()),
        [id] => return Err(ZdevError::new(format!("Invalid stable change ID: {id}"))),
        _ => return Err(ZdevError::new("Commit has more than one stable change ID")),
    };
    Ok(CommandOutput::new(
        match &change_id {
            Some(id) => format!("{commit}  {id}  {subject}"),
            None => format!("{commit} has no stable change ID"),
        },
        json!({"schema_version": SCHEMA_VERSION, "commit": commit, "subject": subject, "change_id": change_id}),
    ))
}

fn lookup_change(root: &Path, change_id: &str) -> Result<CommandOutput, ZdevError> {
    if !valid_change_id(change_id) {
        return Err(ZdevError::new(
            "Stable change ID must be Z followed by 64 lowercase hexadecimal characters",
        ));
    }
    let format = format!("--format=%H%x00%s%x00%(trailers:key={CHANGE_ID_TRAILER},valueonly)");
    let log = git_output_bytes(root, &["log", "--all", "-z", &format])?;
    let mut matches = Vec::new();
    let mut fields = log.split(|byte| *byte == 0);
    while let Some(commit) = fields.next() {
        if commit.is_empty() {
            break;
        }
        let subject = fields
            .next()
            .ok_or_else(|| ZdevError::new("Git log omitted a commit subject"))?;
        let trailers = fields
            .next()
            .ok_or_else(|| ZdevError::new("Git log omitted commit trailers"))?;
        let commit = String::from_utf8_lossy(commit).into_owned();
        let subject = String::from_utf8_lossy(subject).into_owned();
        if String::from_utf8_lossy(trailers)
            .lines()
            .any(|line| line == change_id)
        {
            matches.push(json!({
                "commit": commit,
                "subject": subject,
            }));
        }
    }
    let text = if matches.is_empty() {
        format!("No reachable commit has {change_id}. Check the ID or fetch the missing history")
    } else {
        matches
            .iter()
            .map(|value| {
                format!(
                    "{}  {}",
                    value["commit"].as_str().unwrap(),
                    value["subject"].as_str().unwrap()
                )
            })
            .collect::<Vec<_>>()
            .join("\n")
    };
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "change_id": change_id, "commits": matches}),
    ))
}

fn git_output(root: &Path, arguments: &[&str]) -> Result<String, ZdevError> {
    let bytes = git_output_bytes(root, arguments)?;
    Ok(String::from_utf8_lossy(&bytes).trim().to_owned())
}

fn git_output_bytes(root: &Path, arguments: &[&str]) -> Result<Vec<u8>, ZdevError> {
    let output = ProcessCommand::new("git")
        .args(arguments)
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot run git", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "git {} failed: {}",
            arguments.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    Ok(output.stdout)
}

fn write_atomic(path: &Path, bytes: &[u8]) -> Result<(), ZdevError> {
    let parent = path
        .parent()
        .ok_or_else(|| ZdevError::new(format!("Path has no parent: {}", path.display())))?;
    let mut stage = tempfile::NamedTempFile::new_in(parent)
        .map_err(|error| ZdevError::io(format!("Cannot stage {}", path.display()), error))?;
    stage
        .write_all(bytes)
        .and_then(|()| stage.as_file().sync_all())
        .map_err(|error| ZdevError::io(format!("Cannot write {}", path.display()), error))?;
    stage.persist(path).map_err(|error| {
        ZdevError::io(format!("Cannot publish {}", path.display()), error.error)
    })?;
    Ok(())
}

fn slug(value: &str) -> String {
    let mut slug = String::new();
    let mut separator = false;
    for byte in value.bytes() {
        if byte.is_ascii_alphanumeric() {
            if separator && !slug.is_empty() {
                slug.push('-');
            }
            slug.push(char::from(byte.to_ascii_lowercase()));
            separator = false;
        } else if !slug.is_empty() {
            separator = true;
        }
    }
    if slug.is_empty() {
        "task".to_owned()
    } else {
        slug.truncate(60);
        slug.trim_end_matches('-').to_owned()
    }
}

fn table_text(value: &str) -> String {
    value.replace('|', "\\|")
}

fn relative(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

#[allow(dead_code)]
fn normalize_path(path: &Path) -> PathBuf {
    let mut normalized = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                normalized.pop();
            }
            other => normalized.push(other.as_os_str()),
        }
    }
    normalized
}
