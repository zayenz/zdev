pub(super) fn goal_tasks(
    root: &Path,
    area: &str,
    selected: Option<&str>,
) -> Result<GoalTasksRead, ZdevError> {
    let tasks = load_tasks(root, area)?;
    let statuses = read_task_statuses(root, area, &tasks)?;
    let ready = tasks
        .iter()
        .filter(|task| task_state(task, &statuses) == "ready")
        .count();
    let blocked = tasks
        .iter()
        .filter(|task| task_state(task, &statuses) == "blocked")
        .count();
    let done = tasks
        .iter()
        .filter(|task| task.header.status == TaskStatus::Done)
        .count();
    let selected_task = if let Some(id) = selected {
        let task = find_task(&tasks, id)?;
        if task_state(task, &statuses) != "ready" {
            return Err(ZdevError::new(format!(
                "Cannot select task {id}: it is not in the ready frontier"
            )));
        }
        Some(task)
    } else {
        next_task(&tasks, &statuses)
    };
    let focus = selected_task
        .map(|task| {
            Ok(GoalTaskRead {
                id: task.header.id.clone(),
                key: task.header.key.clone(),
                title: task.title.clone(),
                complexity: task.complexity(),
                path: task.path.clone(),
                outcome: required_markdown_section(&task.body, "Outcome", &task.path)?.to_owned(),
                context: markdown_section(&task.body, "Context", &task.path)?.map(str::to_owned),
                boundaries: markdown_section(&task.body, "Boundaries", &task.path)?
                    .map(str::to_owned),
                done_when: required_markdown_section(&task.body, "Done when", &task.path)?
                    .to_owned(),
                validation: required_markdown_section(&task.body, "Validation", &task.path)?
                    .to_owned(),
                blocked_by: task.header.blocked_by.clone(),
                requires_code: task.header.requires_code.clone(),
                slice: task.header.slice.clone(),
                hypothesis: task.header.hypothesis.clone(),
                research_results: task.header.research_results.clone(),
            })
        })
        .transpose()?;
    Ok(GoalTasksRead {
        total: tasks.len(),
        open: tasks.len() - done,
        ready,
        blocked,
        done,
        focus,
    })
}

pub(super) fn write_index(root: &Path, area: &str) -> Result<PathBuf, ZdevError> {
    let (_, area_dir) = load_area(root, area)?;
    let tasks = load_tasks(root, area)?;
    let path = area_dir.join("TASKS.md");
    let statuses = read_task_statuses(root, area, &tasks)?;
    write_atomic(&path, render_index(area, &tasks, &statuses).as_bytes())?;
    Ok(path)
}

pub(super) fn index(root: &Path, area: &str) -> Result<CommandOutput, ZdevError> {
    let _lock = ZdevStateLock::acquire(root)?;
    let path = write_index(root, area)?;
    Ok(CommandOutput::new(
        format!("Updated {}", relative(root, &path)),
        json!({"schema_version": SCHEMA_VERSION, "status": "updated", "area": area, "path": relative(root, &path)}),
    ))
}

pub(super) struct AreaTaskSummary {
    pub total: usize,
    pub ready: usize,
    pub blocked: usize,
    pub done: usize,
    pub open: usize,
    pub next: Option<String>,
    pub next_complexity: Option<TaskComplexity>,
    pub slices: Vec<SliceTaskSummary>,
    /// The waits of open tasks on other areas. A `blocked` queue is valid only
    /// while at least one remains.
    pub cross_area_waits: Vec<CrossAreaWait>,
}

impl AreaTaskSummary {
    pub(super) fn queue(&self) -> QueueState {
        if self.total == 0 {
            QueueState::Empty
        } else if self.ready > 0 {
            QueueState::Ready
        } else if self.open > 0 {
            QueueState::Blocked
        } else {
            QueueState::Exhausted
        }
    }
}

/// Checks that a closed area has no open tasks and that an open area without a
/// ready task waits on another area. In a valid acyclic graph every chain of
/// unfinished blockers ends outside the area, so a `blocked` queue without a
/// cross-area wait means the graph is corrupt.
pub(super) fn validate_area_lifecycle(
    area: &AreaMetadata,
    summary: &AreaTaskSummary,
) -> Result<(), ZdevError> {
    if area.lifecycle == AreaLifecycle::Closed && summary.open > 0 {
        return Err(ZdevError::new(format!(
            "Closed area {} has {} open tasks",
            area.tag, summary.open
        )));
    }
    if matches!(summary.queue(), QueueState::Blocked) && summary.cross_area_waits.is_empty() {
        return Err(ZdevError::new(
            "Validated task graph has open work but no ready task",
        ));
    }
    Ok(())
}

