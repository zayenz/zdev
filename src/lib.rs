pub fn run(cli: &Cli) -> Result<CommandOutput, ZdevError> {
    if let Command::Instructions = cli.command {
        return Ok(CommandOutput::new(
            AGENT_INSTRUCTIONS,
            json!({
                "schema_version": SCHEMA_VERSION,
                "agent_instructions": AGENT_INSTRUCTIONS,
            }),
        ));
    }
    if let Command::Skill { command } = &cli.command {
        return run_skill_command(cli.root.as_deref(), command);
    }
    let root = resolve_root(cli.root.as_deref())?;
    match &cli.command {
        Command::Instructions => unreachable!(),
        Command::Init { record } => initialize(&root, *record),
        Command::Cleanup { command } => match command {
            CleanupCommand::Squash => cleanup_squash(&root),
        },
        Command::Config { command } => match command {
            ConfigCommand::Trunk { branch } => configure_trunk(&root, branch.as_deref()),
        },
        Command::Area { command } => match command {
            AreaCommand::Create {
                tag,
                title,
                objective,
                branch,
            } => create_area(&root, tag, title, objective, branch.as_deref()),
            AreaCommand::Bind { area, branch } => bind_area(&root, area, branch.as_deref()),
            AreaCommand::Parent {
                area,
                parent,
                remove,
            } => configure_parent(&root, area, parent.as_deref(), *remove),
            AreaCommand::Rebase {
                area,
                r#continue,
                abort,
            } => rebase_area(&root, area, *r#continue, *abort),
        },
        Command::Tasks { command } => match command {
            TasksCommand::Review { area, source } => review_tasks(&root, area, source),
            TasksCommand::Import {
                area,
                source,
                commit,
                approval,
            } => import_tasks(&root, area, source, *commit, approval.as_deref()),
            TasksCommand::List { area } => list_tasks_output(&root, area),
            TasksCommand::Index { area } => write_index_output(&root, area),
        },
        Command::Task { command } => match command {
            TaskCommand::Show { area, task } => show_task(&root, area, task),
            TaskCommand::Done {
                area,
                task,
                summary,
                validation,
            } => complete_task(&root, area, task, summary, validation),
            TaskCommand::Reopen { area, task } => reopen_task(&root, area, task),
        },
        Command::Next { area } => next_task_output(&root, area.as_deref()),
        Command::Status { area } => status_output(&root, area.as_deref()),
        Command::Check { area } => check_output(&root, area.as_deref()),
        Command::Skill { .. } => unreachable!(),
        Command::Commit { message, body } => commit(&root, message, body),
        Command::ChangeId => {
            let id = generate_change_id()?;
            Ok(CommandOutput::new(
                format!("{CHANGE_ID_TRAILER}: {id}"),
                json!({"schema_version": SCHEMA_VERSION, "change_id": id, "trailer": format!("{CHANGE_ID_TRAILER}: {id}")}),
            ))
        }
        Command::Change { command } => match command {
            ChangeCommand::Inspect { revision } => inspect_change(&root, revision),
            ChangeCommand::Lookup { change_id } => lookup_change(&root, change_id),
        },
    }
}

fn resolve_root(explicit: Option<&Path>) -> Result<PathBuf, ZdevError> {
    let current = env::current_dir()
        .map_err(|error| ZdevError::io("Cannot read current directory", error))?;
    if let Some(path) = explicit {
        let path = if path.is_absolute() {
            path.to_path_buf()
        } else {
            current.join(path)
        };
        return fs::canonicalize(&path)
            .map_err(|error| ZdevError::io(format!("Cannot resolve {}", path.display()), error));
    }
    if let Some(root) = current
        .ancestors()
        .find(|path| path.join(".zdev/config.toml").is_file())
    {
        return Ok(root.to_path_buf());
    }
    let output = ProcessCommand::new("git")
        .args(["rev-parse", "--show-toplevel"])
        .current_dir(&current)
        .output();
    if let Ok(output) = output
        && output.status.success()
    {
        let root = String::from_utf8_lossy(&output.stdout);
        return fs::canonicalize(root.trim())
            .map_err(|error| ZdevError::io("Cannot resolve Git root", error));
    }
    Ok(current)
}

fn initialize(root: &Path, record: RecordPolicy) -> Result<CommandOutput, ZdevError> {
    let state_dir = root.join(".zdev");
    if state_dir.exists() {
        let config = read_config(root)?;
        return Ok(CommandOutput::new(
            format!("zdev is already initialized for {}", config.project.name),
            json!({"schema_version": SCHEMA_VERSION, "status": "unchanged", "root": root}),
        ));
    }
    fs::create_dir(&state_dir)
        .map_err(|error| ZdevError::io(format!("Cannot create {}", state_dir.display()), error))?;
    let name = root
        .file_name()
        .and_then(OsStr::to_str)
        .filter(|name| !name.trim().is_empty())
        .ok_or_else(|| ZdevError::new("Repository has no usable directory name"))?;
    let config = Config {
        schema_version: SCHEMA_VERSION,
        project: ProjectConfig {
            name: name.to_owned(),
            record,
            default_area: None,
            trunk: current_branch(root)?,
            guidance: None,
        },
    };
    write_atomic(
        &state_dir.join("config.toml"),
        toml::to_string_pretty(&config).unwrap().as_bytes(),
    )?;
    let trunk = match config.project.trunk.as_deref() {
        Some(branch) => format!("Recorded {branch} as the project trunk."),
        None => "HEAD is detached, so no project trunk was recorded. Set one with:\n  zdev config trunk <branch>".to_owned(),
    };
    let record_text = match record {
        RecordPolicy::PullRequest => {
            "\nRecord policy: pull-request. .zdev is tracked for pull-request review and must be cleaned with `zdev cleanup squash` before squash merge.\n"
        }
        RecordPolicy::Personal => "\nRecord policy: personal. Keep .zdev local to this clone.\n",
        RecordPolicy::Project => "\nRecord policy: project. Track .zdev as shared project state.\n",
    };
    let record_json = if record == RecordPolicy::PullRequest {
        json!({
            "policy": record.as_str(),
            "tracked_for": "pull-request-review",
            "cleanup_required_before": "squash-merge",
            "cleanup_command": ["cleanup", "squash"],
            "notice": ".zdev is tracked for pull-request review and must be cleaned before squash merge"
        })
    } else {
        json!({"policy": record.as_str()})
    };
    Ok(CommandOutput::new(
        format!(
            "Initialized zdev for {name}.\nCreated .zdev/config.toml. {trunk}{record_text}\nCheck the integration you use:\n  zdev skill check <codex|claude|opencode|pi|omp> --scope user\n\nThen create or switch to a feature branch and run:\n  zdev area create <tag> --title <title> --objective <objective>"
        ),
        json!({
            "schema_version": SCHEMA_VERSION,
            "status": "created",
            "root": root,
            "record": record_json,
            "setup": {
                "status": "check-existing-user-integrations",
                "check_for": "each-requested-harness",
                "check_command": [
                    "skill", "check", "<harness>", "--scope", "user"
                ],
                "reuse_when": {
                    "status": "ok",
                    "action": "reuse-user-integration"
                },
                "install_when": [
                    "missing", "conflict", "project-scope-requested"
                ],
                "project_guidance_options": ["auto", "agents", "zdev", "PATH"],
                "install_command": [
                    "skill", "install", "<harness>", "--scope", "<scope>"
                ]
            }
        }),
    ))
}

fn cleanup_squash(root: &Path) -> Result<CommandOutput, ZdevError> {
    let _lock = ZdevStateLock::acquire(root)?;
    let config = read_config(root)?;
    if config.project.record != RecordPolicy::PullRequest {
        return Err(ZdevError::new(format!(
            "Cannot clean the zdev record for squash: config record policy is {}, not pull-request",
            config.project.record.as_str()
        )));
    }
    if let Some(operation) = git_operation(root)? {
        return Err(ZdevError::new(format!(
            "Cannot clean the zdev record while a {operation} is in progress. Finish or abort it, then retry"
        )));
    }
    let branch = current_branch(root)?.ok_or_else(|| {
        ZdevError::new(
            "Cannot clean the zdev record without a checked-out branch; attach HEAD to the pull-request branch, then retry",
        )
    })?;
    if config.project.trunk.as_deref() == Some(branch.as_str()) {
        return Err(ZdevError::new(format!(
            "Cannot clean the zdev record on configured trunk {branch}; switch to the pull-request branch, then retry"
        )));
    }
    git_output(root, &["rev-parse", "--verify", "HEAD^{commit}"]).map_err(|_| {
        ZdevError::new(
            "Cannot clean the zdev record before the repository has a commit; commit the pull-request branch, then retry",
        )
    })?;
    if !git_output(root, &["status", "--porcelain=v1", "--untracked-files=all"])?.is_empty() {
        return Err(ZdevError::new(
            "Cannot clean the zdev record with local changes. Commit or resolve the index and worktree, then retry",
        ));
    }

    let tracked = git_output_bytes(root, &["ls-files", "-z", "--", ".zdev"])?
        .split(|byte| *byte == 0)
        .filter(|path| !path.is_empty())
        .map(|path| {
            String::from_utf8(path.to_vec()).map_err(|_| {
                ZdevError::new("Cannot clean a tracked .zdev path whose name is not valid UTF-8")
            })
        })
        .collect::<Result<Vec<_>, _>>()?;
    if tracked.is_empty() {
        return Err(ZdevError::new(
            "Cannot clean the zdev record because no tracked .zdev files exist on this branch",
        ));
    }

    let mut remove = ProcessCommand::new("git");
    remove.arg("rm").arg("--");
    remove.args(&tracked);
    let removed = remove
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot run git rm for tracked .zdev files", error))?;
    if !removed.status.success() {
        return Err(ZdevError::new(format!(
            "git rm for tracked .zdev files failed before the cleanup commit: {}",
            String::from_utf8_lossy(&removed.stderr).trim()
        )));
    }

    let committed = ProcessCommand::new("git")
        .args(["commit", "-m", CLEANUP_SQUASH_COMMIT_MESSAGE])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| {
            ZdevError::io(
                "Cannot run the cleanup commit; the tracked .zdev deletion remains staged for inspection and recovery",
                error,
            )
        })?;
    if !committed.status.success() {
        return Err(ZdevError::new(format!(
            "Could not commit the cleanup. The tracked .zdev deletion remains staged for inspection and recovery: {}",
            String::from_utf8_lossy(&committed.stderr).trim()
        )));
    }
    let revision = git_output(root, &["rev-parse", "HEAD"])?;
    Ok(CommandOutput::new(
        format!(
            "Removed {} tracked .zdev files and committed {revision} on {branch}: {CLEANUP_SQUASH_COMMIT_MESSAGE}",
            tracked.len()
        ),
        json!({
            "schema_version": SCHEMA_VERSION,
            "status": "committed",
            "record": "pull-request",
            "cleanup": "squash",
            "branch": branch,
            "commit": revision,
            "message": CLEANUP_SQUASH_COMMIT_MESSAGE,
            "removed": tracked,
        }),
    ))
}

fn read_config(root: &Path) -> Result<Config, ZdevError> {
    let path = root.join(".zdev/config.toml");
    let text = fs::read_to_string(&path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))?;
    let config: Config = toml::from_str(&text)
        .map_err(|error| ZdevError::new(format!("Invalid {}: {error}", path.display())))?;
    if config.schema_version != SCHEMA_VERSION {
        return Err(ZdevError::new(format!(
            "Unsupported zdev schema version {}",
            config.schema_version
        )));
    }
    Ok(config)
}

fn write_config(root: &Path, config: &Config) -> Result<(), ZdevError> {
    write_atomic(
        &root.join(".zdev/config.toml"),
        toml::to_string_pretty(config).unwrap().as_bytes(),
    )
}

fn current_branch(root: &Path) -> Result<Option<String>, ZdevError> {
    let output = ProcessCommand::new("git")
        .args(["symbolic-ref", "--quiet", "--short", "HEAD"])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot inspect the checked-out branch", error))?;
    if output.status.success() {
        let branch = String::from_utf8_lossy(&output.stdout).trim().to_owned();
        return Ok((!branch.is_empty()).then_some(branch));
    }
    Ok(None)
}

fn canonical_branch(root: &Path, branch: &str) -> Result<String, ZdevError> {
    validate_nonempty_line(branch, "Branch")?;
    let output = ProcessCommand::new("git")
        .args(["check-ref-format", "--branch", branch])
        .current_dir(root)
        .output()
        .map_err(|error| ZdevError::io("Cannot validate branch name", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!("Invalid branch name: {branch}")));
    }
    let canonical = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    if canonical.is_empty() {
        return Err(ZdevError::new(format!("Invalid branch name: {branch}")));
    }
    Ok(canonical)
}

fn resolve_requested_branch(
    root: &Path,
    requested: Option<&str>,
) -> Result<Option<String>, ZdevError> {
    match requested {
        Some(branch) => canonical_branch(root, branch).map(Some),
        None => current_branch(root),
    }
}

fn required_requested_branch(root: &Path, requested: Option<&str>) -> Result<String, ZdevError> {
    resolve_requested_branch(root, requested)?
        .ok_or_else(|| ZdevError::new("No branch is checked out; pass an explicit branch name"))
}

fn configure_trunk(root: &Path, requested: Option<&str>) -> Result<CommandOutput, ZdevError> {
    let mut config = read_config(root)?;
    let branch = required_requested_branch(root, requested)?;
    config.project.trunk = Some(branch.clone());
    write_config(root, &config)?;
    Ok(CommandOutput::new(
        format!("Configured project trunk {branch}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "updated", "trunk": branch}),
    ))
}

fn validate_segment(value: &str, what: &str) -> Result<(), ZdevError> {
    if value.is_empty()
        || value.len() > 80
        || value.starts_with('-')
        || value.ends_with('-')
        || !value
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
    {
        return Err(ZdevError::new(format!(
            "{what} must contain lowercase letters, digits, and single hyphens"
        )));
    }
    Ok(())
}

fn area_path(root: &Path, tag: &str) -> Result<PathBuf, ZdevError> {
    validate_segment(tag, "Area tag")?;
    Ok(root.join(".zdev").join(tag))
}

fn create_area(
    root: &Path,
    tag: &str,
    title: &str,
    objective: &str,
    requested_branch: Option<&str>,
) -> Result<CommandOutput, ZdevError> {
    let config = read_config(root)?;
    validate_nonempty_line(title, "Area title")?;
    validate_nonempty_line(objective, "Area objective")?;
    let path = area_path(root, tag)?;
    if path.exists() {
        return Err(ZdevError::new(format!("Area already exists: {tag}")));
    }
    let stage = tempfile::Builder::new()
        .prefix(".area-")
        .tempdir_in(root.join(".zdev"))
        .map_err(|error| ZdevError::io("Cannot stage area", error))?;
    fs::create_dir(stage.path().join("tasks"))
        .map_err(|error| ZdevError::io("Cannot create task directory", error))?;
    let branch = required_requested_branch(root, requested_branch)?;
    ensure_branch_available(root, &branch, None)?;
    let base_commit = config
        .project
        .trunk
        .as_deref()
        .map(|base| compute_base_anchor(root, &branch, base))
        .transpose()?
        .flatten();
    let metadata = AreaMetadata {
        schema_version: SCHEMA_VERSION,
        tag: tag.to_owned(),
        title: title.to_owned(),
        objective: objective.to_owned(),
        branch,
        parent: None,
        base_commit,
    };
    fs::write(
        stage.path().join("area.toml"),
        toml::to_string_pretty(&metadata).unwrap(),
    )
    .map_err(|error| ZdevError::io("Cannot write area metadata", error))?;
    fs::write(
        stage.path().join("brief.md"),
        format!(
            "# {title}\n\n## Objective\n\n{objective}\n\n## Testing\n\nExisting checks only.\n"
        ),
    )
    .map_err(|error| ZdevError::io("Cannot write area brief", error))?;
    let empty = render_index(tag, &[])?;
    fs::write(stage.path().join("TASKS.md"), empty)
        .map_err(|error| ZdevError::io("Cannot write task summary", error))?;
    fs::rename(stage.keep(), &path)
        .map_err(|error| ZdevError::io(format!("Cannot publish area {tag}"), error))?;
    Ok(CommandOutput::new(
        format!("Created area {tag}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "created", "area": tag, "branch": metadata.branch, "path": relative(root, &path)}),
    ))
}

fn validate_nonempty_line(value: &str, what: &str) -> Result<(), ZdevError> {
    if value.trim().is_empty() || value.contains(['\n', '\r']) {
        return Err(ZdevError::new(format!("{what} must be one non-empty line")));
    }
    Ok(())
}

fn load_area(root: &Path, tag: &str) -> Result<(AreaMetadata, PathBuf), ZdevError> {
    let path = area_path(root, tag)?;
    let metadata_path = path.join("area.toml");
    let text = fs::read_to_string(&metadata_path).map_err(|error| {
        ZdevError::io(format!("Cannot read {}", metadata_path.display()), error)
    })?;
    let metadata: AreaMetadata = toml::from_str(&text)
        .map_err(|error| ZdevError::new(format!("Invalid {}: {error}", metadata_path.display())))?;
    if metadata.schema_version != SCHEMA_VERSION || metadata.tag != tag {
        return Err(ZdevError::new(format!("Invalid area identity for {tag}")));
    }
    Ok((metadata, path))
}

fn list_areas(root: &Path) -> Result<Vec<AreaMetadata>, ZdevError> {
    read_config(root)?;
    let mut areas = Vec::new();
    for entry in fs::read_dir(root.join(".zdev"))
        .map_err(|error| ZdevError::io("Cannot list zdev areas", error))?
    {
        let entry = entry.map_err(|error| ZdevError::io("Cannot inspect zdev area", error))?;
        let name = entry.file_name();
        let Some(tag) = name.to_str() else { continue };
        if tag.starts_with('_') || !entry.path().join("area.toml").is_file() {
            continue;
        }
        areas.push(load_area(root, tag)?.0);
    }
    areas.sort_by(|left, right| left.tag.cmp(&right.tag));
    Ok(areas)
}

fn write_area_metadata(root: &Path, area: &AreaMetadata) -> Result<(), ZdevError> {
    let path = area_path(root, &area.tag)?.join("area.toml");
    write_atomic(&path, toml::to_string_pretty(area).unwrap().as_bytes())
}

fn ensure_branch_available(
    root: &Path,
    branch: &str,
    owner: Option<&str>,
) -> Result<(), ZdevError> {
    if let Some(area) = list_areas(root)?
        .into_iter()
        .find(|area| area.branch == branch && owner != Some(area.tag.as_str()))
    {
        return Err(ZdevError::new(format!(
            "Branch {branch} is already owned by area {}",
            area.tag
        )));
    }
    Ok(())
}

fn bind_area(root: &Path, tag: &str, requested: Option<&str>) -> Result<CommandOutput, ZdevError> {
    let config = read_config(root)?;
    let (mut area, _) = load_area(root, tag)?;
    let branch = required_requested_branch(root, requested)?;
    ensure_branch_available(root, &branch, Some(tag))?;
    area.branch = branch.clone();
    if let Some(anchor) = &area.base_commit {
        if local_branch_exists(root, &branch)
            && commit_is_ancestor(root, anchor, &format!("refs/heads/{branch}")) != Some(true)
        {
            return Err(ZdevError::new(format!(
                "Branch {branch} does not contain area {tag}'s recorded base commit {anchor}"
            )));
        }
    } else {
        area.base_commit = configured_effective_base(root, &config, &area)?
            .map(|base| compute_base_anchor(root, &branch, &base))
            .transpose()?
            .flatten();
    }
    write_area_metadata(root, &area)?;
    Ok(CommandOutput::new(
        format!("Bound area {tag} to branch {branch}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "updated", "area": tag, "branch": branch}),
    ))
}

fn validate_area_relationships(areas: &[AreaMetadata]) -> Result<(), ZdevError> {
    let by_tag = areas
        .iter()
        .map(|area| (area.tag.as_str(), area))
        .collect::<BTreeMap<_, _>>();
    let mut branches = BTreeMap::new();
    for area in areas {
        if let Some(other) = branches.insert(area.branch.as_str(), area.tag.as_str()) {
            return Err(ZdevError::new(format!(
                "Branch {} is owned by both {other} and {}",
                area.branch, area.tag
            )));
        }
        if area.parent.as_deref() == Some(area.tag.as_str()) {
            return Err(ZdevError::new(format!(
                "Area {} cannot be its own parent",
                area.tag
            )));
        }
        if let Some(parent) = &area.parent
            && !by_tag.contains_key(parent.as_str())
        {
            return Err(ZdevError::new(format!(
                "Area {} has unknown parent {parent}",
                area.tag
            )));
        }
    }
    for area in areas {
        let mut seen = BTreeSet::new();
        let mut current = area;
        while let Some(parent) = &current.parent {
            if !seen.insert(current.tag.as_str()) {
                return Err(ZdevError::new(format!(
                    "Area dependency cycle includes {}",
                    current.tag
                )));
            }
            current = by_tag[parent.as_str()];
        }
    }
    Ok(())
}

fn configure_parent(
    root: &Path,
    tag: &str,
    requested_parent: Option<&str>,
    remove: bool,
) -> Result<CommandOutput, ZdevError> {
    if !remove && requested_parent.is_none() {
        return Err(ZdevError::new(
            "Pass a parent area or use --remove to clear it",
        ));
    }
    let (mut area, _) = load_area(root, tag)?;
    let previous_parent = area.parent.clone();
    let (parent, parent_area) = if remove {
        (None, None)
    } else {
        let parent = requested_parent.unwrap();
        let parent_area = load_area(root, parent)?.0;
        (Some(parent.to_owned()), Some(parent_area))
    };
    area.parent = parent.clone();
    if let Some(parent_area) = &parent_area {
        let child_branch = area.branch.clone();
        let parent_branch = parent_area.branch.clone();
        require_existing_branch(root, &child_branch, "area")?;
        require_existing_branch(root, &parent_branch, "parent-area")?;
        if previous_parent.is_none()
            && base_is_ancestor(root, &parent_branch, &child_branch) == Some(true)
        {
            area.base_commit = branch_tip(root, &parent_branch)?;
        } else {
            let anchor = require_base_anchor(&area)?;
            if !commit_exists(root, anchor)
                || commit_is_ancestor(root, anchor, &format!("refs/heads/{child_branch}"))
                    != Some(true)
            {
                return Err(ZdevError::new(format!(
                    "Cannot set parent {parent_branch}: area {tag} has no trustworthy base boundary contained in {child_branch}"
                )));
            }
        }
    }
    let mut areas = list_areas(root)?;
    let candidate = areas
        .iter_mut()
        .find(|candidate| candidate.tag == tag)
        .ok_or_else(|| ZdevError::new(format!("Unknown area: {tag}")))?;
    *candidate = area.clone();
    validate_area_relationships(&areas)?;
    write_area_metadata(root, &area)?;
    let text = match &parent {
        Some(parent) => format!("Set parent of {tag} to {parent}"),
        None => format!("Removed parent of {tag}"),
    };
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "status": "updated", "area": tag, "parent": parent}),
    ))
}

fn configured_effective_base(
    root: &Path,
    config: &Config,
    area: &AreaMetadata,
) -> Result<Option<String>, ZdevError> {
    if let Some(parent) = &area.parent {
        let parent_area = load_area(root, parent)?.0;
        return Ok(Some(parent_area.branch));
    }
    Ok(config.project.trunk.clone())
}

fn effective_base(root: &Path, config: &Config, area: &AreaMetadata) -> Result<String, ZdevError> {
    configured_effective_base(root, config, area)?.ok_or_else(|| {
        ZdevError::new("Project trunk is not configured; set it with `zdev config trunk <branch>`")
    })
}

fn branch_tip(root: &Path, branch: &str) -> Result<Option<String>, ZdevError> {
    if !local_branch_exists(root, branch) {
        return Ok(None);
    }
    git_output(
        root,
        &[
            "rev-parse",
            "--verify",
            &format!("refs/heads/{branch}^{{commit}}"),
        ],
    )
    .map(Some)
}

fn compute_base_anchor(root: &Path, branch: &str, base: &str) -> Result<Option<String>, ZdevError> {
    let Some(base_tip) = branch_tip(root, base)? else {
        return Ok(None);
    };
    let Some(branch_tip) = branch_tip(root, branch)? else {
        return Ok(Some(base_tip));
    };
    if base_is_ancestor(root, base, branch) == Some(true) {
        return Ok(Some(base_tip));
    }
    let output = ProcessCommand::new("git")
        .args(["merge-base", &branch_tip, &base_tip])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot determine the incorporated base commit", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Branch {branch} and effective base {base} have no common commit"
        )));
    }
    let anchor = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    Ok((!anchor.is_empty()).then_some(anchor))
}

fn require_base_anchor(area: &AreaMetadata) -> Result<&str, ZdevError> {
    area.base_commit.as_deref().ok_or_else(|| {
        ZdevError::new(format!(
            "Area {} has no recorded base commit; rebind its branch with `zdev area bind {} <branch>`",
            area.tag, area.tag
        ))
    })
}

fn commit_exists(root: &Path, commit: &str) -> bool {
    ProcessCommand::new("git")
        .args(["cat-file", "-e", &format!("{commit}^{{commit}}")])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .status()
        .is_ok_and(|status| status.success())
}

fn require_checked_out_area_branch(root: &Path, area: &AreaMetadata) -> Result<String, ZdevError> {
    let branch = &area.branch;
    let checked_out = current_branch(root)?.ok_or_else(|| {
        ZdevError::new(format!(
            "Cannot use area {} while HEAD is detached. Check out branch {branch} and retry",
            area.tag
        ))
    })?;
    if checked_out != *branch {
        return Err(ZdevError::new(format!(
            "Cannot use area {} on branch {checked_out}. Switch to {branch} and retry",
            area.tag
        )));
    }
    Ok(branch.to_owned())
}

fn require_existing_branch(root: &Path, branch: &str, role: &str) -> Result<(), ZdevError> {
    if !local_branch_exists(root, branch) {
        return Err(ZdevError::new(format!(
            "Cannot continue because the recorded {role} branch {branch} is missing locally. Restore or create it, then retry"
        )));
    }
    Ok(())
}

fn child_side_has_merges(root: &Path, anchor: &str, branch: &str) -> Result<bool, ZdevError> {
    let range = format!("{anchor}..refs/heads/{branch}");
    let count = git_output(root, &["rev-list", "--count", "--merges", &range])?;
    Ok(count != "0")
}

fn require_linear_child_history(root: &Path, anchor: &str, branch: &str) -> Result<(), ZdevError> {
    if child_side_has_merges(root, anchor, branch)? {
        return Err(ZdevError::new(format!(
            "Cannot manage area branch {branch}: it contains merge commits after base {anchor}. Use rebase-only history for this branch"
        )));
    }
    Ok(())
}

fn require_fresh_area_link(root: &Path, tag: &str) -> Result<(), ZdevError> {
    let config = read_config(root)?;
    let area = load_area(root, tag)?.0;
    let branch = require_checked_out_area_branch(root, &area)?;
    let base = effective_base(root, &config, &area)?;
    if branch == base {
        return Ok(());
    }
    require_existing_branch(root, &branch, "area")?;
    require_existing_branch(root, &base, "effective-base")?;
    let anchor = require_base_anchor(&area)?;
    if base_is_ancestor(root, &base, &branch) == Some(true) {
        let base_tip = branch_tip(root, &base)?.unwrap();
        require_linear_child_history(root, &base_tip, &branch)?;
        if anchor != base_tip {
            return Err(ZdevError::new(format!(
                "Area {tag} needs its current base recorded. Run `zdev area rebase {tag}`"
            )));
        }
        return Ok(());
    }
    if !commit_exists(root, anchor)
        || commit_is_ancestor(root, anchor, &format!("refs/heads/{branch}")) != Some(true)
    {
        return Err(ZdevError::new(format!(
            "Cannot verify area {tag}'s base on branch {branch}. Rebind the area with `zdev area bind {tag} <branch>`"
        )));
    }
    require_linear_child_history(root, anchor, &branch)?;
    Err(ZdevError::new(format!(
        "Area {tag} is stale. Run `zdev area rebase {tag}` to rebase {branch} onto {base}"
    )))
}

fn git_operation(root: &Path) -> Result<Option<&'static str>, ZdevError> {
    for (marker, operation) in [
        ("rebase-merge", "rebase"),
        ("rebase-apply", "rebase"),
        ("MERGE_HEAD", "merge"),
        ("CHERRY_PICK_HEAD", "cherry-pick"),
        ("REVERT_HEAD", "revert"),
        ("BISECT_LOG", "bisect"),
        ("sequencer", "sequenced Git operation"),
    ] {
        let path = git_output(root, &["rev-parse", "--git-path", marker])?;
        let path = PathBuf::from(path);
        let path = if path.is_absolute() {
            path
        } else {
            root.join(path)
        };
        if path.exists() {
            return Ok(Some(operation));
        }
    }
    Ok(None)
}

fn require_clean_worktree(root: &Path) -> Result<(), ZdevError> {
    if !git_output(root, &["status", "--porcelain=v1", "--untracked-files=all"])?.is_empty() {
        return Err(ZdevError::new(
            "Cannot rebase with local changes. Commit or stash them, then retry",
        ));
    }
    Ok(())
}

struct GitRebaseState {
    head_name: String,
    onto: String,
    orig_head: String,
}

fn git_path(root: &Path, name: &str) -> Result<PathBuf, ZdevError> {
    let path = PathBuf::from(git_output(root, &["rev-parse", "--git-path", name])?);
    Ok(if path.is_absolute() {
        path
    } else {
        root.join(path)
    })
}

fn read_git_rebase_state(root: &Path) -> Result<Option<GitRebaseState>, ZdevError> {
    let directory = ["rebase-merge", "rebase-apply"]
        .into_iter()
        .map(|name| git_path(root, name))
        .collect::<Result<Vec<_>, _>>()?
        .into_iter()
        .find(|path| path.is_dir());
    let Some(directory) = directory else {
        return Ok(None);
    };
    let read_field = |name: &str| -> Result<String, ZdevError> {
        let path = directory.join(name);
        fs::read_to_string(&path)
            .map(|value| value.trim().to_owned())
            .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))
    };
    Ok(Some(GitRebaseState {
        head_name: read_field("head-name")?,
        onto: read_field("onto")?,
        orig_head: read_field("orig-head")?,
    }))
}

fn managed_rebase_guidance(tag: &str) -> String {
    format!(
        "Resolve and stage the conflicts, then run `zdev area rebase {tag} --continue`. To cancel, run `zdev area rebase {tag} --abort`. The equivalent Git commands are `git rebase --continue` and `git rebase --abort`"
    )
}

fn finalize_managed_rebase(
    root: &Path,
    tag: &str,
    effective_base: &str,
    new_base_commit: &str,
) -> Result<CommandOutput, ZdevError> {
    let (mut area, _) = load_area(root, tag)?;
    let branch = require_checked_out_area_branch(root, &area)?;
    if commit_is_ancestor(root, new_base_commit, &format!("refs/heads/{branch}")) != Some(true) {
        return Err(ZdevError::new(format!(
            "Cannot finish the rebase: branch {branch} does not contain target {}. Inspect the Git history before retrying",
            new_base_commit
        )));
    }
    require_linear_child_history(root, new_base_commit, &branch)?;
    area.base_commit = Some(new_base_commit.to_owned());
    write_area_metadata(root, &area)?;
    Ok(CommandOutput::new(
        format!("Rebased area {tag} onto {effective_base}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "rebased", "area": tag, "branch": branch, "effective_base": effective_base, "base_commit": new_base_commit, "fresh": true}),
    ))
}

fn continue_managed_rebase(root: &Path, tag: &str) -> Result<CommandOutput, ZdevError> {
    let state = read_git_rebase_state(root)?.ok_or_else(|| {
        ZdevError::new(format!(
            "Cannot continue: no rebase is in progress for area {tag}"
        ))
    })?;
    let config = read_config(root)?;
    let area = load_area(root, tag)?.0;
    let branch = &area.branch;
    if state.head_name != format!("refs/heads/{branch}") {
        return Err(ZdevError::new(format!(
            "Cannot continue area {tag}: Git is rebasing {}, not branch {branch}. Finish or abort that rebase first",
            state.head_name
        )));
    }
    let anchor = require_base_anchor(&area)?;
    if commit_is_ancestor(root, anchor, &state.orig_head) != Some(true)
        || !commit_exists(root, &state.onto)
    {
        return Err(ZdevError::new(
            "Cannot continue: Git's rebase boundary does not match the area's recorded base. Abort and restart the area rebase",
        ));
    }
    let effective_base = effective_base(root, &config, &area)?;
    let expected_onto = branch_tip(root, &effective_base)?.ok_or_else(|| {
        ZdevError::new(format!(
            "Cannot continue: base branch {effective_base} is missing locally. Restore it, abort this rebase, and retry"
        ))
    })?;
    let original_branch_tip = branch_tip(root, branch)?;
    if expected_onto != state.onto
        || original_branch_tip.as_deref() != Some(state.orig_head.as_str())
    {
        return Err(ZdevError::new(format!(
            "Cannot continue: Git's rebase state no longer matches area {tag}. Run `zdev area rebase {tag} --abort`, then start the rebase again"
        )));
    }
    let output = ProcessCommand::new("git")
        .args(["-c", "core.editor=true", "rebase", "--continue"])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot continue git rebase", error))?;
    if !output.status.success() {
        let details = String::from_utf8_lossy(&output.stderr).trim().to_owned();
        if git_operation(root)? == Some("rebase") {
            return Err(ZdevError::new(format!(
                "Area {tag} still has rebase conflicts. {}. {details}",
                managed_rebase_guidance(tag)
            )));
        }
        return Err(ZdevError::new(format!(
            "Could not continue area {tag}'s rebase, and Git left no rebase to resume. Inspect the branch before retrying: {details}"
        )));
    }
    finalize_managed_rebase(root, tag, &effective_base, &state.onto)
}

fn abort_managed_rebase(root: &Path, tag: &str) -> Result<CommandOutput, ZdevError> {
    let state = read_git_rebase_state(root)?.ok_or_else(|| {
        ZdevError::new(format!(
            "Cannot abort: no rebase is in progress for area {tag}"
        ))
    })?;
    let area = load_area(root, tag)?.0;
    let branch = &area.branch;
    if state.head_name != format!("refs/heads/{branch}") {
        return Err(ZdevError::new(format!(
            "Cannot abort area {tag}: Git is rebasing {}, not branch {branch}. Finish or abort that rebase directly",
            state.head_name
        )));
    }
    let output = ProcessCommand::new("git")
        .args(["rebase", "--abort"])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot abort git rebase", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Could not abort area {tag}'s rebase. Run `git rebase --abort` after resolving this error: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    Ok(CommandOutput::new(
        format!("Aborted rebase of area {tag}"),
        json!({"schema_version": SCHEMA_VERSION, "status": "aborted", "area": tag, "base_commit": area.base_commit}),
    ))
}

fn rebase_area(
    root: &Path,
    tag: &str,
    continue_rebase: bool,
    abort: bool,
) -> Result<CommandOutput, ZdevError> {
    if continue_rebase {
        return continue_managed_rebase(root, tag);
    }
    if abort {
        return abort_managed_rebase(root, tag);
    }
    let config = read_config(root)?;
    let area = load_area(root, tag)?.0;
    if let Some(operation) = git_operation(root)? {
        return Err(ZdevError::new(format!(
            "Cannot rebase area {tag} while a {operation} is in progress. Finish or abort it, then retry"
        )));
    }
    let branch = require_checked_out_area_branch(root, &area)?;
    let base = effective_base(root, &config, &area)?;
    let anchor = require_base_anchor(&area)?.to_owned();
    require_clean_worktree(root)?;
    require_existing_branch(root, &branch, "area")?;
    require_existing_branch(root, &base, "effective-base")?;
    let new_base_commit = branch_tip(root, &base)?.unwrap();
    if base_is_ancestor(root, &base, &branch) == Some(true) {
        require_linear_child_history(root, &new_base_commit, &branch)?;
        if area.base_commit.as_deref() == Some(new_base_commit.as_str()) {
            return Ok(CommandOutput::new(
                format!("Area {tag} is already fresh on {base}"),
                json!({"schema_version": SCHEMA_VERSION, "status": "unchanged", "area": tag, "branch": branch, "effective_base": base, "base_commit": new_base_commit, "fresh": true}),
            ));
        }
        let mut area = area;
        area.base_commit = Some(new_base_commit.clone());
        write_area_metadata(root, &area)?;
        return Ok(CommandOutput::new(
            format!("Finalized area {tag}'s incorporated base at {base}"),
            json!({"schema_version": SCHEMA_VERSION, "status": "updated", "area": tag, "branch": branch, "effective_base": base, "base_commit": new_base_commit, "fresh": true}),
        ));
    }
    if !commit_exists(root, &anchor)
        || commit_is_ancestor(root, &anchor, &format!("refs/heads/{branch}")) != Some(true)
    {
        return Err(ZdevError::new(format!(
            "Cannot rebase area {tag}: its recorded base is unavailable on {branch}. Rebind it with `zdev area bind {tag} <branch>`"
        )));
    }
    require_linear_child_history(root, &anchor, &branch)?;
    let output = ProcessCommand::new("git")
        .args(["rebase", "--onto", &new_base_commit, &anchor])
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot run git rebase", error))?;
    if !output.status.success() {
        let details = String::from_utf8_lossy(&output.stderr).trim().to_owned();
        if git_operation(root)? == Some("rebase") {
            return Err(ZdevError::new(format!(
                "Area {tag} has rebase conflicts. {}. {details}",
                managed_rebase_guidance(tag)
            )));
        }
        return Err(ZdevError::new(format!(
            "Could not rebase area {tag}, and Git left no rebase to resume. Inspect the branch before retrying: {details}"
        )));
    }
    finalize_managed_rebase(root, tag, &base, &new_base_commit)
}

fn read_task_bundle(source: &Path) -> Result<TaskBundle, ZdevError> {
    let bytes = if source == Path::new("-") {
        let mut bytes = Vec::new();
        io::stdin()
            .read_to_end(&mut bytes)
            .map_err(|error| ZdevError::io("Cannot read task bundle from standard input", error))?;
        bytes
    } else {
        fs::read(source)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", source.display()), error))?
    };
    serde_json::from_slice(&bytes)
        .map_err(|error| ZdevError::new(format!("Invalid task bundle: {error}")))
}

fn validate_task_bundle(bundle: &TaskBundle, area: &str) -> Result<(), ZdevError> {
    if bundle.schema_version != SCHEMA_VERSION || bundle.area != area {
        return Err(ZdevError::new(
            "Task bundle does not match the selected area",
        ));
    }
    if bundle.tasks.is_empty() {
        return Err(ZdevError::new("Task bundle contains no tasks"));
    }
    let mut seen_keys = BTreeSet::new();
    for task in &bundle.tasks {
        validate_segment(&task.key, "Task key")?;
        validate_nonempty_line(&task.title, "Task title")?;
        validate_nonempty_line(&task.outcome, "Task outcome")?;
        if task
            .context
            .as_deref()
            .is_some_and(|context| context.trim().is_empty())
        {
            return Err(ZdevError::new(format!(
                "Task {} has empty context",
                task.key
            )));
        }
        if task.done_when.is_empty() {
            return Err(ZdevError::new(format!(
                "Task {} has no done conditions",
                task.key
            )));
        }
        if !seen_keys.insert(task.key.as_str()) {
            return Err(ZdevError::new(format!("Duplicate task key: {}", task.key)));
        }
    }
    Ok(())
}

fn task_bundle_approval_id(bundle: &TaskBundle) -> Result<String, ZdevError> {
    let canonical = serde_json::to_vec(bundle)
        .map_err(|error| ZdevError::new(format!("Cannot fingerprint task bundle: {error}")))?;
    let hash = canonical.iter().fold(0xcbf29ce484222325_u64, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
    });
    Ok(format!("T{hash:016x}"))
}

fn approval_value(value: Option<&str>) -> &str {
    value.filter(|value| !value.is_empty()).unwrap_or("None")
}

fn approval_list(values: &[String]) -> String {
    if values.is_empty() {
        "None".to_owned()
    } else {
        values
            .iter()
            .enumerate()
            .map(|(index, value)| format!("{}. {value}", index + 1))
            .collect::<Vec<_>>()
            .join("\n")
    }
}

fn longest_backtick_run(value: &str) -> usize {
    value
        .split(|character| character != '`')
        .map(str::len)
        .max()
        .unwrap_or(0)
}

fn render_task_bundle_approval(bundle: &TaskBundle) -> String {
    let mut document = format!(
        "# Task Bundle\n\n## Area\n{}\n\n## Schema version\n{}",
        bundle.area, bundle.schema_version
    );
    for (index, task) in bundle.tasks.iter().enumerate() {
        document.push_str(&format!(
            "\n\n## Task {}\n\n### Key\n{}\n\n### Title\n{}\n\n### Outcome\n{}\n\n### Context\n{}\n\n### Boundaries\n{}\n\n### Blocked by\n{}\n\n### Done when / proof\n{}\n\n### Validation / Testing\n{}",
            index + 1,
            task.key,
            task.title,
            task.outcome,
            approval_value(task.context.as_deref()),
            approval_list(&task.boundaries),
            approval_list(&task.blocked_by),
            approval_list(&task.done_when),
            approval_list(&task.validation),
        ));
    }
    let fence = "`".repeat(longest_backtick_run(&document).saturating_add(1).max(3));
    format!("{fence}markdown\n{document}\n{fence}")
}

fn review_tasks(root: &Path, area: &str, source: &Path) -> Result<CommandOutput, ZdevError> {
    load_area(root, area)?;
    let bundle = read_task_bundle(source)?;
    validate_task_bundle(&bundle, area)?;
    let approval = task_bundle_approval_id(&bundle)?;
    let markdown = render_task_bundle_approval(&bundle);
    Ok(CommandOutput::new(
        format!("{markdown}\n\nApproval ID: {approval}"),
        json!({
            "schema_version": SCHEMA_VERSION,
            "status": "reviewed",
            "area": area,
            "approval": approval,
            "markdown": markdown,
        }),
    ))
}

fn import_tasks(
    root: &Path,
    area: &str,
    source: &Path,
    commit_changes: bool,
    approval: Option<&str>,
) -> Result<CommandOutput, ZdevError> {
    let bundle = read_task_bundle(source)?;
    validate_task_bundle(&bundle, area)?;
    if let Some(approval) = approval {
        let actual = task_bundle_approval_id(&bundle)?;
        if approval != actual {
            return Err(ZdevError::new(format!(
                "Task bundle differs from approved review {approval}; review this bundle and use its approval ID"
            )));
        }
    }
    let _lock = ZdevStateLock::acquire(root)?;
    let (metadata, area_dir) = load_area(root, area)?;
    if commit_changes {
        require_checked_out_area_branch(root, &metadata)?;
        require_committable_task_import(root, area)?;
    }
    let existing = load_tasks(root, area)?;
    let existing_ids = existing
        .iter()
        .map(|task| task.header.id.as_str())
        .collect::<BTreeSet<_>>();
    let existing_keys = existing
        .iter()
        .map(|task| task.header.key.as_str())
        .collect::<BTreeSet<_>>();
    for task in &bundle.tasks {
        if existing_keys.contains(task.key.as_str()) {
            return Err(ZdevError::new(format!("Duplicate task key: {}", task.key)));
        }
    }
    let mut next_number = existing
        .iter()
        .filter_map(|task| task.header.id.rsplit_once('-')?.1.parse::<u64>().ok())
        .max()
        .unwrap_or(0);
    let mut allocated = BTreeMap::new();
    for task in &bundle.tasks {
        next_number += 1;
        allocated.insert(task.key.as_str(), format!("{area}-{next_number:03}"));
    }
    let mut writes = Vec::new();
    for draft in &bundle.tasks {
        let id = allocated[&draft.key.as_str()].clone();
        let blockers = draft
            .blocked_by
            .iter()
            .map(|blocker| {
                if let Some(id) = allocated.get(blocker.as_str()) {
                    Ok((*id).clone())
                } else if existing_ids.contains(blocker.as_str()) {
                    Ok(blocker.clone())
                } else {
                    Err(ZdevError::new(format!(
                        "Task {} has unknown blocker {blocker}",
                        draft.key
                    )))
                }
            })
            .collect::<Result<Vec<_>, _>>()?;
        if blockers.iter().any(|blocker| blocker == &id) {
            return Err(ZdevError::new(format!("Task {} blocks itself", draft.key)));
        }
        let header = TaskHeader {
            schema_version: SCHEMA_VERSION,
            id: id.clone(),
            key: draft.key.clone(),
            area: area.to_owned(),
            status: TaskStatus::Open,
            blocked_by: blockers,
        };
        let path = area_dir.join("tasks").join(format!(
            "{next:03}-{}.md",
            slug(&draft.title),
            next = parse_number(&id)?
        ));
        let body = render_draft(&header, draft)?;
        writes.push((path, body));
    }
    let mut hypothetical = existing.clone();
    for (path, content) in &writes {
        hypothetical.push(parse_task(content, path, area)?);
    }
    validate_graph(&hypothetical)?;
    let index_path = area_dir.join("TASKS.md");
    let previous_index = fs::read(&index_path)
        .map_err(|error| ZdevError::io(format!("Cannot read {}", index_path.display()), error))?;
    let mut created = Vec::new();
    for (path, content) in &writes {
        match OpenOptions::new().create_new(true).write(true).open(path) {
            Ok(mut file) => {
                created.push(path.clone());
                if let Err(error) = file
                    .write_all(content.as_bytes())
                    .and_then(|()| file.sync_all())
                {
                    let write_error =
                        ZdevError::io(format!("Cannot write {}", path.display()), error);
                    drop(file);
                    return Err(import_rollback_error(write_error, &created, None));
                }
            }
            Err(error) => {
                let create_error =
                    ZdevError::io(format!("Cannot create {}", path.display()), error);
                return Err(import_rollback_error(create_error, &created, None));
            }
        }
    }
    if let Err(error) = write_index(root, area) {
        return Err(import_rollback_error(
            error,
            &created,
            commit_changes.then_some((index_path.as_path(), previous_index.as_slice())),
        ));
    }
    let ids = writes
        .iter()
        .map(|(_, content)| {
            parse_task(content, Path::new("task.md"), area).map(|task| task.header.id)
        })
        .collect::<Result<Vec<_>, _>>()?;
    if commit_changes {
        let paths = writes
            .iter()
            .map(|(path, _)| path.clone())
            .chain(std::iter::once(index_path.clone()))
            .collect::<Vec<_>>();
        return match commit_task_import(root, area, &paths) {
            Ok((revision, change_id)) => Ok(CommandOutput::new(
                format!(
                    "Added and committed {} tasks to {area} ({revision})",
                    ids.len()
                ),
                json!({"schema_version": SCHEMA_VERSION, "status": "committed", "area": area, "tasks": ids, "commit": revision, "change_id": change_id, "paths": relative_paths(root, &paths)?}),
            )),
            Err(error) => Err(import_rollback_error(
                rollback_task_import_index(root, &paths, error),
                &created,
                Some((index_path.as_path(), previous_index.as_slice())),
            )),
        };
    }
    Ok(CommandOutput::new(
        format!("Added {} tasks to {area}", ids.len()),
        json!({"schema_version": SCHEMA_VERSION, "status": "created", "area": area, "tasks": ids}),
    ))
}

fn import_rollback_error(
    error: ZdevError,
    created: &[PathBuf],
    restore_index: Option<(&Path, &[u8])>,
) -> ZdevError {
    let mut cleanup_errors = created
        .iter()
        .filter_map(|path| {
            fs::remove_file(path)
                .err()
                .map(|cleanup| format!("cannot remove {}: {cleanup}", path.display()))
        })
        .collect::<Vec<_>>();
    if let Some((path, contents)) = restore_index
        && let Err(restore) = write_atomic(path, contents)
    {
        cleanup_errors.push(format!("cannot restore {}: {restore}", path.display()));
    }
    if cleanup_errors.is_empty() {
        ZdevError::new(format!(
            "Could not add tasks; the import was rolled back and no imported task changes were kept. {error}"
        ))
    } else {
        ZdevError::new(format!(
            "Could not add tasks, and cleanup was incomplete. {error}. Resolve these paths before retrying: {}",
            cleanup_errors.join("; "),
        ))
    }
}

struct ZdevStateLock {
    _file: Option<File>,
}

impl ZdevStateLock {
    fn acquire(root: &Path) -> Result<Self, ZdevError> {
        let output = ProcessCommand::new("git")
            .args(["rev-parse", "--git-path", "zdev-state.lock"])
            .current_dir(root)
            .env_remove("GIT_DIR")
            .env_remove("GIT_WORK_TREE")
            .output()
            .map_err(|error| ZdevError::io("Cannot inspect the Git state directory", error))?;
        if !output.status.success() {
            return Ok(Self { _file: None });
        }
        let git_path = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim());
        let path = if git_path.is_absolute() {
            git_path
        } else {
            root.join(git_path)
        };
        let mut file = OpenOptions::new()
            .read(true)
            .write(true)
            .create(true)
            .truncate(false)
            .open(&path)
            .map_err(|error| {
                ZdevError::io(
                    format!("Cannot open zdev state lock {}", path.display()),
                    error,
                )
            })?;
        for _ in 0..100 {
            match file.try_lock() {
                Ok(()) => {
                    if let Err(error) = file
                        .set_len(0)
                        .and_then(|()| writeln!(file, "{}", std::process::id()))
                    {
                        return Err(ZdevError::io(
                            format!("Cannot write zdev state lock {}", path.display()),
                            error,
                        ));
                    }
                    return Ok(Self { _file: Some(file) });
                }
                Err(std::fs::TryLockError::WouldBlock) => {
                    std::thread::sleep(std::time::Duration::from_millis(50));
                }
                Err(std::fs::TryLockError::Error(error)) => {
                    return Err(ZdevError::io(
                        format!("Cannot acquire zdev state lock {}", path.display()),
                        error,
                    ));
                }
            }
        }
        Err(ZdevError::new(format!(
            "Another zdev update is running. Retry when it finishes. Lock: {}",
            path.display(),
        )))
    }
}

fn require_committable_task_import(root: &Path, area: &str) -> Result<(), ZdevError> {
    if let Some(operation) = git_operation(root)? {
        return Err(ZdevError::new(format!(
            "Cannot add and commit tasks while a {operation} is in progress. Finish or abort it, then retry"
        )));
    }
    git_output(root, &["rev-parse", "--verify", "HEAD"]).map_err(|_| {
        ZdevError::new(
            "Cannot add and commit tasks before the repository has a commit. Create the initial commit, then retry",
        )
    })?;
    let area_path = format!(".zdev/{area}");
    let changed = git_output(
        root,
        &[
            "status",
            "--porcelain=v1",
            "--untracked-files=all",
            "--",
            &area_path,
        ],
    )?;
    let ignored = git_output(
        root,
        &[
            "ls-files",
            "--others",
            "--ignored",
            "--exclude-standard",
            "--",
            &area_path,
        ],
    )?;
    if !changed.is_empty() || !ignored.is_empty() {
        return Err(ZdevError::new(format!(
            "Cannot add and commit tasks: {area_path} already has local changes. Commit or resolve them first"
        )));
    }
    Ok(())
}

fn relative_paths(root: &Path, paths: &[PathBuf]) -> Result<Vec<String>, ZdevError> {
    paths
        .iter()
        .map(|path| {
            path.strip_prefix(root)
                .map(|path| path.to_string_lossy().replace('\\', "/"))
                .map_err(|_| {
                    ZdevError::new(format!("Path is outside repository: {}", path.display()))
                })
        })
        .collect()
}

fn commit_task_import(
    root: &Path,
    area: &str,
    paths: &[PathBuf],
) -> Result<(String, String), ZdevError> {
    let relative = relative_paths(root, paths)?;
    let mut add = ProcessCommand::new("git");
    add.args(["add", "-f", "--"]);
    add.args(&relative);
    let output = add
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot stage imported task paths", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Could not stage the new task files. Resolve the Git error, then retry: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }

    let change_id = generate_change_id()?;
    let mut command = ProcessCommand::new("git");
    command
        .args(["commit", "--only", "-m"])
        .arg(format!("Add tasks to {area}"))
        .args(["-m", &format!("{CHANGE_ID_TRAILER}: {change_id}"), "--"])
        .args(&relative);
    let output = command
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .map_err(|error| ZdevError::io("Cannot commit imported task paths", error))?;
    if !output.status.success() {
        return Err(ZdevError::new(format!(
            "Could not commit the new task files. Resolve the Git error, then retry: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    Ok((git_output(root, &["rev-parse", "HEAD"])?, change_id))
}

fn rollback_task_import_index(root: &Path, paths: &[PathBuf], error: ZdevError) -> ZdevError {
    let relative = match relative_paths(root, paths) {
        Ok(relative) => relative,
        Err(rollback) => {
            return ZdevError::new(format!(
                "{error}; cannot identify staged task paths during rollback: {rollback}"
            ));
        }
    };
    let mut reset = ProcessCommand::new("git");
    reset.args(["reset", "-q", "HEAD", "--"]).args(&relative);
    match reset
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
    {
        Ok(output) if output.status.success() => error,
        Ok(output) => ZdevError::new(format!(
            "{error}; cannot unstage imported task paths during rollback: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )),
        Err(rollback) => ZdevError::new(format!(
            "{error}; cannot run Git to unstage imported task paths during rollback: {rollback}"
        )),
    }
}

fn render_draft(header: &TaskHeader, draft: &TaskDraft) -> Result<String, ZdevError> {
    let context = draft
        .context
        .as_deref()
        .map_or_else(String::new, |context| {
            format!("\n\n## Context\n\n{}", context.trim())
        });
    let boundaries = if draft.boundaries.is_empty() {
        String::new()
    } else {
        format!(
            "\n\n## Boundaries\n\n{}",
            draft
                .boundaries
                .iter()
                .map(|item| format!("- {item}"))
                .collect::<Vec<_>>()
                .join("\n")
        )
    };
    let validation = if draft.validation.is_empty() {
        "- Let the verifier choose the smallest useful checks.".to_owned()
    } else {
        draft
            .validation
            .iter()
            .map(|item| format!("- {item}"))
            .collect::<Vec<_>>()
            .join("\n")
    };
    Ok(format!(
        "+++\n{}+++\n# {}\n\n## Outcome\n\n{}{}{}\n\n## Done when\n\n{}\n\n## Validation\n\n{}\n",
        toml::to_string(header)
            .map_err(|error| ZdevError::new(format!("Cannot render task: {error}")))?,
        draft.title,
        draft.outcome,
        context,
        boundaries,
        draft
            .done_when
            .iter()
            .map(|item| format!("- [ ] {item}"))
            .collect::<Vec<_>>()
            .join("\n"),
        validation,
    ))
}

fn load_tasks(root: &Path, area: &str) -> Result<Vec<Task>, ZdevError> {
    let (_, area_dir) = load_area(root, area)?;
    let tasks_dir = area_dir.join("tasks");
    if !tasks_dir.is_dir() {
        return Err(ZdevError::new(format!(
            "Area {area} has no tasks directory: {}",
            tasks_dir.display()
        )));
    }
    let mut tasks = Vec::new();
    for entry in fs::read_dir(&tasks_dir)
        .map_err(|error| ZdevError::io(format!("Cannot list {}", tasks_dir.display()), error))?
    {
        let entry = entry.map_err(|error| ZdevError::io("Cannot inspect task", error))?;
        let path = entry.path();
        if path.extension() != Some(OsStr::new("md")) {
            continue;
        }
        let content = fs::read_to_string(&path)
            .map_err(|error| ZdevError::io(format!("Cannot read {}", path.display()), error))?;
        tasks.push(parse_task(&content, &path, area)?);
    }
    tasks.sort_by(compare_tasks_by_id);
    validate_graph(&tasks)?;
    Ok(tasks)
}

fn parse_task(content: &str, path: &Path, area: &str) -> Result<Task, ZdevError> {
    let rest = content.strip_prefix("+++\n").ok_or_else(|| {
        ZdevError::new(format!("Task lacks TOML frontmatter: {}", path.display()))
    })?;
    let (frontmatter, body) = rest.split_once("+++\n").ok_or_else(|| {
        ZdevError::new(format!("Task has unclosed frontmatter: {}", path.display()))
    })?;
    let header: TaskHeader = toml::from_str(frontmatter)
        .map_err(|error| ZdevError::new(format!("Invalid task {}: {error}", path.display())))?;
    if header.schema_version != SCHEMA_VERSION || header.area != area {
        return Err(ZdevError::new(format!(
            "Task has invalid area or schema: {}",
            path.display()
        )));
    }
    validate_segment(&header.key, "Task key")?;
    let expected_prefix = format!("{area}-");
    if !header.id.starts_with(&expected_prefix) || parse_number(&header.id).is_err() {
        return Err(ZdevError::new(format!("Invalid task ID: {}", header.id)));
    }
    let title = body
        .lines()
        .find_map(|line| line.strip_prefix("# "))
        .filter(|title| !title.trim().is_empty())
        .ok_or_else(|| ZdevError::new(format!("Task lacks a title: {}", path.display())))?
        .to_owned();
    validate_task_body(body, header.status, path)?;
    Ok(Task {
        header,
        title,
        body: body.to_owned(),
        path: path.to_path_buf(),
    })
}

fn markdown_section<'a>(
    body: &'a str,
    heading: &str,
    path: &Path,
) -> Result<Option<&'a str>, ZdevError> {
    let marker = format!("\n## {heading}\n");
    let matches = body.match_indices(&marker).collect::<Vec<_>>();
    let start = match matches.as_slice() {
        [] => return Ok(None),
        [(start, _)] => start + marker.len(),
        _ => {
            return Err(ZdevError::new(format!(
                "Task repeats ## {heading}: {}",
                path.display()
            )));
        }
    };
    let end = body[start..]
        .find("\n## ")
        .map_or(body.len(), |offset| start + offset);
    Ok(Some(body[start..end].trim()))
}

fn required_markdown_section<'a>(
    body: &'a str,
    heading: &str,
    path: &Path,
) -> Result<&'a str, ZdevError> {
    markdown_section(body, heading, path)?
        .ok_or_else(|| ZdevError::new(format!("Task lacks ## {heading}: {}", path.display())))
}

fn validate_bullet_section(section: &str, heading: &str, path: &Path) -> Result<(), ZdevError> {
    if section.is_empty()
        || section.lines().any(|line| {
            !line.trim().is_empty()
                && line
                    .strip_prefix("- ")
                    .is_none_or(|item| item.trim().is_empty())
        })
    {
        return Err(ZdevError::new(format!(
            "Task ## {heading} must contain a non-empty bullet list: {}",
            path.display()
        )));
    }
    Ok(())
}

fn validate_task_body(body: &str, status: TaskStatus, path: &Path) -> Result<(), ZdevError> {
    let outcome = required_markdown_section(body, "Outcome", path)?;
    if outcome.is_empty() {
        return Err(ZdevError::new(format!(
            "Task ## Outcome is empty: {}",
            path.display()
        )));
    }
    if let Some(boundaries) = markdown_section(body, "Boundaries", path)? {
        validate_bullet_section(boundaries, "Boundaries", path)?;
    }
    let done_when = required_markdown_section(body, "Done when", path)?;
    let conditions = done_when
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect::<Vec<_>>();
    if conditions.is_empty()
        || conditions.iter().any(|line| {
            ["- [ ] ", "- [x] ", "- [X] "]
                .iter()
                .find_map(|prefix| line.strip_prefix(prefix))
                .is_none_or(|item| item.trim().is_empty())
        })
    {
        return Err(ZdevError::new(format!(
            "Task ## Done when must contain only checklist items: {}",
            path.display()
        )));
    }
    if status == TaskStatus::Done && conditions.iter().any(|line| line.starts_with("- [ ] ")) {
        return Err(ZdevError::new(format!(
            "Done task has unchecked conditions: {}",
            path.display()
        )));
    }
    let validation = required_markdown_section(body, "Validation", path)?;
    validate_bullet_section(validation, "Validation", path)?;
    if status == TaskStatus::Done {
        let result = required_markdown_section(body, "Result", path)?;
        if result.is_empty() {
            return Err(ZdevError::new(format!(
                "Done task has an empty ## Result: {}",
                path.display()
            )));
        }
    }
    Ok(())
}

fn replace_markdown_section(
    body: &str,
    heading: &str,
    path: &Path,
    replace: impl FnOnce(&str) -> String,
) -> Result<String, ZdevError> {
    let marker = format!("\n## {heading}\n");
    let start = body
        .find(&marker)
        .ok_or_else(|| ZdevError::new(format!("Task lacks ## {heading}: {}", path.display())))?
        + marker.len();
    let end = body[start..]
        .find("\n## ")
        .map_or(body.len(), |offset| start + offset);
    let mut updated = String::with_capacity(body.len());
    updated.push_str(&body[..start]);
    updated.push_str(&replace(&body[start..end]));
    updated.push_str(&body[end..]);
    Ok(updated)
}

fn parse_number(id: &str) -> Result<u64, ZdevError> {
    id.rsplit_once('-')
        .and_then(|(_, number)| number.parse().ok())
        .ok_or_else(|| ZdevError::new(format!("Task ID has no numeric suffix: {id}")))
}

fn compare_tasks_by_id(left: &Task, right: &Task) -> std::cmp::Ordering {
    parse_number(&left.header.id)
        .expect("task IDs are validated before sorting")
        .cmp(&parse_number(&right.header.id).expect("task IDs are validated before sorting"))
        .then_with(|| left.header.id.cmp(&right.header.id))
}

fn validate_graph(tasks: &[Task]) -> Result<(), ZdevError> {
    let by_id = tasks
        .iter()
        .map(|task| (task.header.id.as_str(), task))
        .collect::<BTreeMap<_, _>>();
    if by_id.len() != tasks.len() {
        return Err(ZdevError::new("Task IDs must be unique"));
    }
    let keys = tasks
        .iter()
        .map(|task| task.header.key.as_str())
        .collect::<BTreeSet<_>>();
    if keys.len() != tasks.len() {
        return Err(ZdevError::new("Task keys must be unique"));
    }
    for task in tasks {
        let mut seen = BTreeSet::new();
        for blocker in &task.header.blocked_by {
            if blocker == &task.header.id || !seen.insert(blocker) {
                return Err(ZdevError::new(format!(
                    "Invalid blocker on {}",
                    task.header.id
                )));
            }
            if !by_id.contains_key(blocker.as_str()) {
                return Err(ZdevError::new(format!(
                    "Task {} has missing blocker {blocker}",
                    task.header.id
                )));
            }
        }
    }
    fn visit<'a>(
        id: &'a str,
        by_id: &BTreeMap<&'a str, &'a Task>,
        visiting: &mut BTreeSet<&'a str>,
        visited: &mut BTreeSet<&'a str>,
    ) -> Result<(), ZdevError> {
        if visited.contains(id) {
            return Ok(());
        }
        if !visiting.insert(id) {
            return Err(ZdevError::new(format!(
                "Task dependency cycle includes {id}"
            )));
        }
        for blocker in &by_id[id].header.blocked_by {
            visit(blocker, by_id, visiting, visited)?;
        }
        visiting.remove(id);
        visited.insert(id);
        Ok(())
    }
    let mut visiting = BTreeSet::new();
    let mut visited = BTreeSet::new();
    for id in by_id.keys().copied() {
        visit(id, &by_id, &mut visiting, &mut visited)?;
    }
    Ok(())
}

fn task_state(task: &Task, tasks: &[Task]) -> &'static str {
    if task.header.status == TaskStatus::Done {
        return "done";
    }
    let statuses = tasks
        .iter()
        .map(|task| (task.header.id.as_str(), task.header.status))
        .collect::<BTreeMap<_, _>>();
    if task
        .header
        .blocked_by
        .iter()
        .all(|id| statuses.get(id.as_str()) == Some(&TaskStatus::Done))
    {
        "ready"
    } else {
        "blocked"
    }
}

fn views<'a>(root: &Path, tasks: &'a [Task]) -> Vec<TaskView<'a>> {
    tasks
        .iter()
        .map(|task| TaskView {
            id: &task.header.id,
            title: &task.title,
            status: task.header.status.as_str(),
            state: task_state(task, tasks),
            blocked_by: &task.header.blocked_by,
            path: relative(root, &task.path),
        })
        .collect()
}

fn list_tasks_output(root: &Path, area: &str) -> Result<CommandOutput, ZdevError> {
    let tasks = load_tasks(root, area)?;
    let task_views = views(root, &tasks);
    let text = if task_views.is_empty() {
        format!("No tasks in {area}")
    } else {
        task_views
            .iter()
            .map(|task| format!("{}  {:7}  {}", task.id, task.state, task.title))
            .collect::<Vec<_>>()
            .join("\n")
    };
    Ok(CommandOutput::new(
        text,
        json!({"schema_version": SCHEMA_VERSION, "area": area, "tasks": task_views}),
    ))
}

fn next_task(tasks: &[Task]) -> Option<&Task> {
    tasks.iter().find(|task| task_state(task, tasks) == "ready")
}

fn select_area(root: &Path, requested: Option<&str>) -> Result<String, ZdevError> {
    if let Some(area) = requested {
        load_area(root, area)?;
        return Ok(area.to_owned());
    }
    let config = read_config(root)?;
    if let Some(area) = config.project.default_area {
        load_area(root, &area)?;
        return Ok(area);
    }
    let mut active = Vec::new();
    for area in list_areas(root)? {
        let tasks = load_tasks(root, &area.tag)?;
        if tasks.is_empty()
            || tasks
                .iter()
                .any(|task| task.header.status == TaskStatus::Open)
        {
            active.push(area.tag);
        }
    }
    match active.as_slice() {
        [only] => Ok(only.clone()),
        [] => Err(ZdevError::new(
            "No area has open work. Create tasks or reopen a completed task first",
        )),
        _ => Err(ZdevError::new(format!(
            "Specify an area with `zdev next <area>`. Open areas: {}",
            active.join(", ")
        ))),
    }
}

fn next_task_output(root: &Path, requested: Option<&str>) -> Result<CommandOutput, ZdevError> {
    let area = select_area(root, requested)?;
    require_fresh_area_link(root, &area)?;
    let tasks = load_tasks(root, &area)?;
    let Some(task) = next_task(&tasks) else {
        let open = tasks
            .iter()
            .any(|task| task.header.status == TaskStatus::Open);
        let status = if open { "blocked" } else { "complete" };
        return Ok(CommandOutput::new(
            if open {
                format!(
                    "No task is ready in {area}. Complete a blocking task or update the dependencies"
                )
            } else {
                format!("All tasks in {area} are done")
            },
            json!({"schema_version": SCHEMA_VERSION, "area": area, "status": status, "task": Value::Null}),
        ));
    };
    let view = TaskView {
        id: &task.header.id,
        title: &task.title,
        status: task.header.status.as_str(),
        state: "ready",
        blocked_by: &task.header.blocked_by,
        path: relative(root, &task.path),
    };
    Ok(CommandOutput::new(
        format!(
            "{}  {}\n{}",
            task.header.id,
            task.title,
            task.path.display()
        ),
        json!({"schema_version": SCHEMA_VERSION, "area": area, "status": "ready", "task": view}),
    ))
}

